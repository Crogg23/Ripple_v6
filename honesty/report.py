"""Committed governance artifacts: honesty/mart_grades.json + MART_GRADES.md.

Build-time only. Reads the dbt manifest, writes two files meant to be
git-committed so the grades are durable, diffable, and AI-free at runtime —
the same doctrine as every control table in this repo.
"""

from __future__ import annotations

import json
from pathlib import Path

from .grading import FACT, Grade, grade_marts, load_manifest

REPO = Path(__file__).resolve().parents[1]
DEFAULT_MANIFEST = REPO / "library-onboarding" / "ripple_dbt" / "target" / "manifest.json"
OUT_DIR = Path(__file__).resolve().parent

_KIND_PLAIN = {
    "name_join": "name-join (identity by name, no hard ID)",
    "unparseable_join": "join the walker could not read (fails closed)",
    "claim_ancestry": "reads the claims/review layer",
    "no_sql": "no SQL available to walk (fails closed)",
}


def _short(node_id: str) -> str:
    return node_id.split(".")[-1]


def render_md(grades: dict[str, Grade], manifest_rel: str, manifest_meta: dict) -> str:
    counts: dict[str, int] = {}
    for g in grades.values():
        counts[g.grade] = counts.get(g.grade, 0) + 1
    gen_at = manifest_meta.get("generated_at", "<unknown>")
    inv = (manifest_meta.get("invocation_id") or "")[:8]

    lines = [
        "# MART GRADES — machine-checked provenance",
        "",
        f"Generated by `python -m honesty` from `{manifest_rel}`",
        f"(dbt manifest generated_at {gen_at}, invocation {inv}). Content is",
        "deterministic for a given manifest — a diff here means the models or",
        "the rules changed, never the calendar.",
        "**Do not hand-edit** — regenerate after any dbt model change (`dbt parse`",
        "first). Rules and doctrine: `honesty/README.md`. Grades fail closed: a",
        "join the walker cannot prove hard-ID-anchored demotes the mart.",
        "",
        f"**{len(grades)} marts:** "
        + " · ".join(f"{counts.get(k, 0)} {k}" for k in (FACT, "lead", "unverified")),
        "",
        "| Mart | Grade | Traps | Why not fact (first receipts) |",
        "|---|---|---|---|",
    ]
    for nid in sorted(grades, key=lambda n: (grades[n].grade, n)):
        g = grades[nid]
        why = "; ".join(
            f"{_KIND_PLAIN[r.kind]} in `{_short(r.node)}`" for r in g.reasons[:2]
        ) or "—"
        extra = f" (+{len(g.reasons) - 2} more)" if len(g.reasons) > 2 else ""
        traps = ", ".join(g.traps) or "—"
        lines.append(f"| `{_short(nid)}` | **{g.grade}** | {traps} | {why}{extra} |")

    lines += [
        "",
        "Full receipts (every reason, every clause): `honesty/mart_grades.json`.",
        "",
    ]
    return "\n".join(lines)


def write_artifacts(manifest_path: Path = DEFAULT_MANIFEST, out_dir: Path = OUT_DIR) -> dict:
    manifest = load_manifest(manifest_path)
    grades = grade_marts(manifest)

    meta = manifest.get("metadata") or {}
    try:
        manifest_rel = str(Path(manifest_path).resolve().relative_to(REPO))
    except ValueError:
        manifest_rel = str(manifest_path)

    # Deterministic for a given manifest: the fingerprint is the manifest's own
    # generated_at + invocation_id, never today's date — a diff in these files
    # must always mean the models or the rules changed.
    payload = {
        "manifest": manifest_rel,
        "manifest_generated_at": meta.get("generated_at"),
        "dbt_invocation_id": meta.get("invocation_id"),
        "n_marts": len(grades),
        "grades": {k: v.as_dict() for k, v in sorted(grades.items())},
    }
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "mart_grades.json").write_text(json.dumps(payload, indent=2) + "\n")
    (out_dir / "MART_GRADES.md").write_text(render_md(grades, manifest_rel, meta))
    return payload
