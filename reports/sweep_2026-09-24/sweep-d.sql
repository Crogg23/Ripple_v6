WITH st AS (SELECT STAY_ID, MAX_BY(STATE, BOOK_OUT_AT) end_state, MAX(IFF(INITIAL_BOND_SET_AMOUNT IS NOT NULL,1,0)) bond_set, MAX(IFF(BOND_POSTED_AMOUNT IS NOT NULL,1,0)) bond_posted,
