-- [49] Nursing home: cycle-1 survey date as the event; penalties before/after, top home by fines after
WITH n AS (SELECT CMS_CERTIFICATION_NUMBER_CCN ccn, TRY_TO_DATE(RATING_CYCLE_1_STANDARD_SURVEY_HEALTH_DATE::varchar) sd, OVERALL_RATING, CHAIN_NAME FROM LIBRARY_MARTS.HEALTH.HEALTH__FED_CMS_NURSING_HOME),
p AS (SELECT CMS_CERTIFICATION_NUMBER_CCN ccn, TRY_TO_DATE(PENALTY_DATE::varchar) pd, TRY_TO_DOUBLE(FINE_AMOUNT::varchar) fine FROM LIBRARY_MARTS.HEALTH.HEALTH__FED_CMS_NURSING_HOME_PENALTIES),
j AS (SELECT n.ccn, n.sd, n.CHAIN_NAME, SUM(IFF(p.pd>n.sd,1,0)) pen_after, SUM(IFF(p.pd<=n.sd,1,0)) pen_before, SUM(IFF(p.pd>n.sd,p.fine,0)) fine_after, MIN(IFF(p.pd>n.sd,p.pd-n.sd,NULL)) lag_days
  FROM n LEFT JOIN p ON p.ccn=n.ccn GROUP BY 1,2,3)
SELECT YEAR(sd) y, COUNT(*) homes, SUM(IFF(pen_after>0,1,0)) homes_after, SUM(IFF(pen_before>0,1,0)) homes_before, SUM(fine_after) fines_after, MEDIAN(lag_days) med_lag,
 (SELECT LISTAGG(z,'; ') FROM (SELECT ccn||' '||COALESCE(CHAIN_NAME,'-')||' $'||ROUND(fine_after)||' n='||pen_after z FROM j ORDER BY fine_after DESC NULLS LAST LIMIT 5)) top5
FROM j GROUP BY 1 ORDER BY 1;

