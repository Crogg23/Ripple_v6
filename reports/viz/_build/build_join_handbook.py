"""Rebuild reports/viz/join_handbook.html from the template + the inlined edge data.

The measured-overlap payload lives inside the existing built page (a single
`const DATA = {...}` line). This script lifts it out, drops it into the current
template, and writes the page back. Run it after any template edit:

    python reports/viz/_build/build_join_handbook.py

Pass --data <file.json> to build from a freshly exported spine payload instead.

Pass-2 layer (added 2026-08-29): connections measured live but not yet registered in
the spine are read from handbook_pass2_edges_2026-08-29.csv (generated by
pass2_edges_source_2026-08-29.py) and merged in with tier MEASURED (or SUSPECT for the
one downgraded edge). Glossary additions, pass-1 corrections and traps come from
handbook_pass2_notes_2026-08-29.json and ride along inside DATA.notes. The merge is
idempotent: pass-2 edges are tagged src="pass2" and stripped before re-merging, so
rebuilding from the built page never duplicates them. Pass --no-pass2 to skip the layer.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

BUILD = Path(__file__).resolve().parent
VIZ = BUILD.parent
TEMPLATE = BUILD / "join_handbook_template.html"
PAGE = VIZ / "join_handbook.html"
PASS2_EDGES = BUILD / "handbook_pass2_edges_2026-08-29.csv"
PASS2_NOTES = BUILD / "handbook_pass2_notes_2026-08-29.json"
MARKER = "const DATA = "
PLACEHOLDER = "__DATA_PLACEHOLDER__"
PASS2_TIERS = ("MEASURED", "SUSPECT")


def extract_data(html: str) -> dict:
    """Pull the JSON payload out of a previously built page."""
    i = html.find(MARKER)
    if i < 0:
        raise SystemExit(f"no '{MARKER}' line found in the built page")
    start = i + len(MARKER)
    end = html.find("\n", start)
    return json.loads(html[start:end].rstrip().rstrip(";"))


def strip_pass2(data: dict) -> dict:
    """Remove any previously merged pass-2 layer so the merge is idempotent."""
    for name in list(data["edges"]):
        data["edges"][name] = [e for e in data["edges"][name] if e.get("src") != "pass2"]
        if not data["edges"][name]:
            del data["edges"][name]
    data["tables"] = [t for t in data["tables"] if not t.get("src") == "pass2"]
    for t in data["tables"]:
        t.pop("n_measured", None)
        t["tiers"] = [x for x in t["tiers"] if x not in PASS2_TIERS]
        t["n_conn"] = len(data["edges"].get(t["name"], []))
    data.pop("notes", None)
    return data


def _num(v):
    if v in ("", None):
        return None
    f = float(v)
    return int(f) if f.is_integer() else f


def merge_pass2(data: dict, edges_csv: Path, notes_json: Path) -> tuple[int, int]:
    """Add the pass-2 edges (both directions) + notes. Returns (edges added, tables added)."""
    with edges_csv.open(encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    tables = {t["name"]: t for t in data["tables"]}
    edges = data["edges"]

    def existing(self, other, cs, co):
        return any(e["other"] == other and e["col_self"] == cs and e["col_other"] == co
                   for e in edges.get(self, []))

    added = 0
    new_tables = 0
    for r in rows:
        a, b = r["table_a"], r["table_b"]
        base = dict(key=r["key"], tier=r["tier"], rate=_num(r["match_rate"]), matched=_num(r["matched"]),
                    verdict=r["verdict"], note=r["note"], norm=r["norm"], src="pass2",
                    measured_on=json.loads(notes_json.read_text(encoding="utf-8"))["measured_on"])
        directions = [(a, b, r["col_a"], r["col_b"], r["distinct_a"], r["distinct_b"])]
        if a != b:  # a same-table pointer (successor cert -> cert) is listed once, not twice
            directions.append((b, a, r["col_b"], r["col_a"], r["distinct_b"], r["distinct_a"]))
        for self, other, cs, co, ds, do in directions:
            if existing(self, other, cs, co):
                continue
            edges.setdefault(self, []).append(dict(other=other, col_self=cs, col_other=co,
                                                   distinct_self=_num(ds), distinct_other=_num(do), **base))
            added += 1
            t = tables.get(self)
            if t is None:
                t = dict(name=self, n_conn=0, n_hard=0, tiers=[], src="pass2")
                tables[self] = t
                data["tables"].append(t)
                new_tables += 1
            t["n_conn"] += 1
            t["n_measured"] = t.get("n_measured", 0) + 1
            if r["tier"] not in t["tiers"]:
                t["tiers"].append(r["tier"])
    data["notes"] = json.loads(notes_json.read_text(encoding="utf-8"))
    return added, new_tables


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", type=Path, help="JSON payload to build from (default: reuse the built page's)")
    ap.add_argument("--out", type=Path, default=PAGE)
    ap.add_argument("--no-pass2", action="store_true", help="skip the measured-not-in-spine layer")
    ap.add_argument("--dump-data", type=Path, help="also write the merged payload to this JSON file")
    args = ap.parse_args()

    if args.data:
        data = json.loads(args.data.read_text(encoding="utf-8"))
    else:
        if not PAGE.exists():
            raise SystemExit(f"{PAGE} does not exist and no --data given")
        data = extract_data(PAGE.read_text(encoding="utf-8"))

    data = strip_pass2(data)
    added = new_tables = 0
    if not args.no_pass2:
        added, new_tables = merge_pass2(data, PASS2_EDGES, PASS2_NOTES)

    template = TEMPLATE.read_text(encoding="utf-8")
    if PLACEHOLDER not in template:
        raise SystemExit(f"template is missing {PLACEHOLDER}")

    blob = json.dumps(data, separators=(",", ":"), ensure_ascii=False)
    # </script> inside a JS string literal would close the block early.
    blob = blob.replace("</", "<\\/")

    html = template.replace(PLACEHOLDER, blob)
    args.out.write_text(html, encoding="utf-8")
    if args.dump_data:
        args.dump_data.write_text(json.dumps(data, indent=1, ensure_ascii=False), encoding="utf-8")

    edges = sum(len(v) for v in data["edges"].values())
    print(f"wrote {args.out}  ({len(html):,} bytes)")
    print(f"  {len(data['tables']):,} tables, {edges:,} measured connections")
    if not args.no_pass2:
        print(f"  pass-2 layer: {added} directed edges merged ({added // 2} pairs approx), {new_tables} tables new to the handbook")
    return 0


if __name__ == "__main__":
    sys.exit(main())
