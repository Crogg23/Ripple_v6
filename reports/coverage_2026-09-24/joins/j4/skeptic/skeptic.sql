-- S2
SELECT YEAR(TRANSACTION_DATE) y, COUNT(*) n, SUM(DOSAGE_UNITS) du, TYPEOF(ANY_VALUE(DOSAGE_STRENGTH::variant)) t FROM LIBRARY_MARTS.HEALTH.HEALTH__FED_DEA_ARCOS WHERE TRANSACTION_CODE='S' GROUP BY 1 ORDER BY 1

