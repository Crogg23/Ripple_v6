-- [S15] Decode the pollutant codes on open NE HPVs and GPC fails (ICIS-Air pollutant table), plus GPC pre-2017 fail pollutant codes
SELECT POLLUTANT_CODE, ANY_VALUE(POLLUTANT_DESC) AS DESCR, COUNT(*) AS N
FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ICIS_AIR_ICIS_AIR_POLLUTANTS
WHERE POLLUTANT_CODE IN ('300000282','300000327','300000243','300000377','10461','300000119','300000007','300000088','300000329','300000330','300000331','300000268')
GROUP BY 1 ORDER BY 1
