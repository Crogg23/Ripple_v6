-- Q5 foodcity_reporters
-- who shipped to Food City pharmacies (TN/VA/KY/GA) and to every Knox County TN pharmacy: buyer x reporter rollup, code S only
SELECT BUYER_DEA_NO, ANY_VALUE(BUYER_NAME) buyer, ANY_VALUE(BUYER_ADDL_CO_INFO) addl, ANY_VALUE(BUYER_ADDRESS1) addr, ANY_VALUE(BUYER_CITY) city, ANY_VALUE(BUYER_STATE) st, ANY_VALUE(BUYER_COUNTY_FIPS) fips,
  ANY_VALUE(BUYER_BUSINESS_ACTIVITY) act, REPORTER_DEA_NO, ANY_VALUE(REPORTER_NAME) reporter, ANY_VALUE(REPORTER_FAMILY) family, ANY_VALUE(REPORTER_CITY) rcity, ANY_VALUE(REPORTER_STATE) rst,
  ANY_VALUE(REPORTER_BUSINESS_ACTIVITY) ract,
  SUM(DOSAGE_UNITS) du, SUM(IFF(DRUG_NAME = 'OXYCODONE' AND DOSAGE_STRENGTH >= 30, DOSAGE_UNITS, 0)) o30,
  MIN(YEAR(TRANSACTION_DATE)) y0, MAX(YEAR(TRANSACTION_DATE)) y1, COUNT(*) n
FROM LIBRARY_MARTS.HEALTH.HEALTH__FED_DEA_ARCOS
WHERE TRANSACTION_CODE = 'S' AND ((BUYER_NAME ILIKE 'FOOD CITY%' AND BUYER_STATE IN ('TN','VA','KY','GA'))
   OR (BUYER_COUNTY_FIPS = '47093' AND BUYER_BUSINESS_ACTIVITY IN ('RETAIL PHARMACY','CHAIN PHARMACY')))
GROUP BY BUYER_DEA_NO, REPORTER_DEA_NO
