-- Q7 cluster_by_year
-- six-store Knoxville Food City cluster, by year and distributor: pills and oxycodone 30mg+
SELECT YEAR(TRANSACTION_DATE) yr, REPORTER_FAMILY family, SUM(DOSAGE_UNITS) du,
  SUM(IFF(DRUG_NAME = 'OXYCODONE' AND DOSAGE_STRENGTH >= 30, DOSAGE_UNITS, 0)) o30, COUNT(DISTINCT BUYER_DEA_NO) stores
FROM LIBRARY_MARTS.HEALTH.HEALTH__FED_DEA_ARCOS
WHERE TRANSACTION_CODE = 'S' AND BUYER_DEA_NO IN ('FF1280089','BF7000526','BF9649508','BF7399531','FF0911811','FF2853100')
GROUP BY 1, 2 ORDER BY 1, 2
