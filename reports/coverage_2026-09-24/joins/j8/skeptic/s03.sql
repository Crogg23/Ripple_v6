-- what the "fundraising" keyword actually caught for the 19: dollars by trigger class, and top purpose strings
WITH g AS (SELECT column1 EIN FROM VALUES ('821194581'),('822366231'),('815214552'),('843153271'),('822315009'),('834686848'),('843763411'),('853307234'),('472041040'),('273594732'),('843763242'),
  ('921706849'),('922354897'),('861386683'),('843763606'),('922452599'),('923489519'),('854325630'),('923489713')),
f AS (SELECT b.EIN, UPPER(TRIM(REGEXP_REPLACE(RECIPIENT_NAME,'[^A-Za-z0-9& ]',''))) r, EXPENDITURE_DATE d, EXPENDITURE_AMOUNT a, FORM_ID_NUMBER, COUNT(*) n, MAX(UPPER(TRIM(EXPENDITURE_PURPOSE))) p
  FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_IRS527_SCHEDULE_B_EXPENDITURES b JOIN g ON g.EIN=b.EIN GROUP BY 1,2,3,4,5),
k AS (SELECT EIN, r, d, a, MAX(n) n, MAX(p) p FROM f GROUP BY 1,2,3,4),
c AS (SELECT *, CASE WHEN REGEXP_LIKE(p,'.*(FUNDRAIS|FUND RAIS|TELEFUND|CAGING|SOLICIT|DONOR ACQU|LIST RENTAL|MAIL HOUSE).*') THEN '1 explicit fundraising'
   WHEN REGEXP_LIKE(p,'.*TELEMARKET.*') AND REGEXP_LIKE(p,'.*(PROGRAM|POLITICAL|VOTER|EDUCAT|ADVOCA|PERSUA|GOTV).*') THEN '2 telemarketing labelled program/political'
   WHEN REGEXP_LIKE(p,'.*TELEMARKET.*') THEN '3 telemarketing bare'
   WHEN REGEXP_LIKE(p,'.*DIRECT MAIL.*') THEN '4 direct mail'
   WHEN REGEXP_LIKE(p,'.*PHONE.*') THEN '5 phone only'
   ELSE '9 not fundraising' END cls FROM k)
SELECT 'class' k, cls, NULL p, ROUND(SUM(n*a)/1e6,2) m, ROUND(100*RATIO_TO_REPORT(SUM(n*a)) OVER (),1) pct FROM c GROUP BY cls
UNION ALL
SELECT * FROM (SELECT 'top', cls, LEFT(p,70), ROUND(SUM(n*a)/1e6,2) m, NULL FROM c GROUP BY cls, p ORDER BY m DESC LIMIT 30)
ORDER BY 1, 4 DESC
