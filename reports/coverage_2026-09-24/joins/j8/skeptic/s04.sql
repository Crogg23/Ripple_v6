-- null test for the zip+surname+first-initial donor match: real key vs shifted initial (A->B..Z->A) vs zip shuffled across donors
WITH g AS (SELECT column1 EIN FROM VALUES ('821194581'),('822366231'),('815214552'),('843153271'),('822315009'),('834686848'),('843763411'),('853307234'),('472041040'),('273594732'),('843763242'),
  ('921706849'),('922354897'),('861386683'),('843763606'),('922452599'),('923489519'),('854325630'),('923489713')),
s AS (SELECT DISTINCT LEFT(CONTRIBUTOR_ZIP,5) z,
   IFF(CONTRIBUTOR_NAME LIKE '%,%', TRIM(SPLIT_PART(UPPER(CONTRIBUTOR_NAME),',',1)), REGEXP_SUBSTR(TRIM(UPPER(CONTRIBUTOR_NAME)),'[A-Z]+$')) ln,
   LEFT(IFF(CONTRIBUTOR_NAME LIKE '%,%', TRIM(SPLIT_PART(UPPER(CONTRIBUTOR_NAME),',',2)), TRIM(UPPER(CONTRIBUTOR_NAME))),1) fi
  FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_IRS527_SCHEDULE_A_CONTRIBUTIONS WHERE EIN IN (SELECT EIN FROM g)
   AND NOT REGEXP_LIKE(UPPER(CONTRIBUTOR_NAME),'.*(AGGREGATE|UNITEMIZED|TOTAL|BELOW THRESHOLD|VARIOUS|ITEMIZED|WITHHELD).*')),
s2 AS (SELECT z, ln, fi, ROW_NUMBER() OVER (ORDER BY HASH(ln, fi, 'a')) r1, ROW_NUMBER() OVER (ORDER BY HASH(z, ln, fi, 'b')) r2 FROM s),
keys AS (
  SELECT 'real' t, z||ln||fi kk FROM s
  UNION SELECT 'shift_initial', z||ln||IFF(fi='Z','A',CHR(ASCII(fi)+1)) FROM s WHERE fi RLIKE '[A-Z]'
  UNION SELECT 'shuffle_zip', b.z||a.ln||a.fi FROM s2 a JOIN s2 b ON a.r1=b.r2),
f AS (SELECT DISTINCT CMTE_ID, LEFT(ZIP_CODE,5)||TRIM(SPLIT_PART(DONOR_NAME,',',1))||LEFT(TRIM(SPLIT_PART(DONOR_NAME,',',2)),1) kk
  FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_FEC_INDIV_CONTRIBUTIONS WHERE COALESCE(MEMO_CD,'')<>'X'
   AND CMTE_ID IN ('C00570093','C00715433','C00709113','C00710160','C00650168','C00784496','C00755694','C00681825','C00570416','C00758938','C00712885','C00710178','C00699801',
                   'C00003418','C00570226','C00295527','C00506105','C00488304'))
SELECT f.CMTE_ID, COUNT(DISTINCT f.kk) donors,
  COUNT(DISTINCT IFF(k.t='real', f.kk, NULL)) real_hits,
  COUNT(DISTINCT IFF(k.t='shift_initial', f.kk, NULL)) shift_initial_hits,
  COUNT(DISTINCT IFF(k.t='shuffle_zip', f.kk, NULL)) shuffle_zip_hits,
  ROUND(100*COUNT(DISTINCT IFF(k.t='real', f.kk, NULL))/COUNT(DISTINCT f.kk),1) pct_real,
  ROUND(100*COUNT(DISTINCT IFF(k.t='shift_initial', f.kk, NULL))/COUNT(DISTINCT f.kk),2) pct_shift,
  ROUND(100*COUNT(DISTINCT IFF(k.t='shuffle_zip', f.kk, NULL))/COUNT(DISTINCT f.kk),2) pct_shuffle
FROM f LEFT JOIN keys k ON k.kk=f.kk GROUP BY 1 ORDER BY pct_real DESC
