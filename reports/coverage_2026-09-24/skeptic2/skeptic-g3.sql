-- ===== file os3
-- @@ O4 null test: OFAC SDN + UK FCDO people with full DOB vs UK PSC individuals, sorted-token full-name equality + birth year + month; true DOB (shift 0) vs fake DOB (birth year shifted -2,-1,+1,+2). Fake-DOB hits estimate same-name strangers.
WITH os AS (
  SELECT ID, YEAR(BIRTH_DATE) by_, MONTH(BIRTH_DATE) bm,
         ARRAY_TO_STRING(ARRAY_SORT(SPLIT(TRIM(REGEXP_REPLACE(REGEXP_REPLACE(UPPER(NAME),'[^A-Z ]',' '),' +',' ')),' ')),' ') nk,
         DATASET ILIKE '%OFAC Specially%' ofac
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__INTL_OPENSANCTIONS
  WHERE SCHEMA='Person' AND BIRTH_DATE IS NOT NULL AND LENGTH(BIRTH_DATE_RAW) >= 10 AND (DATASET ILIKE '%OFAC Specially%' OR DATASET ILIKE '%UK FCDO%')
), s AS (SELECT column1 sh FROM VALUES (0),(-2),(-1),(1),(2)),
psc AS (
  SELECT COMPANY_NUMBER, TRY_TO_NUMBER(TO_VARCHAR(DOB_YEAR)) y, TRY_TO_NUMBER(TO_VARCHAR(DOB_MONTH)) m, CEASED_ON,
         ARRAY_TO_STRING(ARRAY_SORT(SPLIT(TRIM(REGEXP_REPLACE(REGEXP_REPLACE(UPPER(COALESCE(NAME_FORENAME,'')||' '||COALESCE(NAME_MIDDLE,'')||' '||COALESCE(NAME_SURNAME,'')),'[^A-Z ]',' '),' +',' ')),' ')),' ') nk
  FROM LIBRARY_MARTS.CORPORATE_REGISTRY.CORPORATE_REGISTRY__UK_COMPANIES_HOUSE_PSC
  WHERE KIND ILIKE 'individual%' AND DOB_YEAR IS NOT NULL
)
SELECT s.sh, COUNT(DISTINCT os.ID) people_matched, COUNT(DISTINCT psc.COMPANY_NUMBER) companies,
       COUNT(DISTINCT IFF(psc.CEASED_ON IS NULL, os.ID, NULL)) people_open_control, COUNT(DISTINCT IFF(psc.CEASED_ON IS NULL, psc.COMPANY_NUMBER, NULL)) companies_open,
       COUNT(DISTINCT IFF(os.ofac, os.ID, NULL)) ofac_people
FROM os CROSS JOIN s JOIN psc ON psc.nk = os.nk AND psc.y = os.by_ + s.sh AND psc.m = os.bm
GROUP BY 1 ORDER BY 1

-- ===== file os4
-- @@ O5 true-DOB strict matches with open control: who, which program, how many open UK companies, PSC nationality, how many active in Companies House
WITH os AS (
  SELECT ID, NAME, LEFT(SANCTIONS,60) sanc, COUNTRIES, YEAR(BIRTH_DATE) by_, MONTH(BIRTH_DATE) bm,
         ARRAY_TO_STRING(ARRAY_SORT(SPLIT(TRIM(REGEXP_REPLACE(REGEXP_REPLACE(UPPER(NAME),'[^A-Z ]',' '),' +',' ')),' ')),' ') nk
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__INTL_OPENSANCTIONS
  WHERE SCHEMA='Person' AND BIRTH_DATE IS NOT NULL AND LENGTH(BIRTH_DATE_RAW) >= 10 AND (DATASET ILIKE '%OFAC Specially%' OR DATASET ILIKE '%UK FCDO%')
), psc AS (
  SELECT COMPANY_NUMBER, TRY_TO_NUMBER(TO_VARCHAR(DOB_YEAR)) y, TRY_TO_NUMBER(TO_VARCHAR(DOB_MONTH)) m, CEASED_ON, NATIONALITY,
         ARRAY_TO_STRING(ARRAY_SORT(SPLIT(TRIM(REGEXP_REPLACE(REGEXP_REPLACE(UPPER(COALESCE(NAME_FORENAME,'')||' '||COALESCE(NAME_MIDDLE,'')||' '||COALESCE(NAME_SURNAME,'')),'[^A-Z ]',' '),' +',' ')),' ')),' ') nk
  FROM LIBRARY_MARTS.CORPORATE_REGISTRY.CORPORATE_REGISTRY__UK_COMPANIES_HOUSE_PSC
  WHERE KIND ILIKE 'individual%' AND DOB_YEAR IS NOT NULL AND CEASED_ON IS NULL
)
SELECT os.NAME, os.sanc, os.COUNTRIES, COUNT(DISTINCT psc.COMPANY_NUMBER) open_cos, LISTAGG(DISTINCT psc.NATIONALITY, '/') psc_nat,
       COUNT(DISTINCT IFF(u.COMPANY_STATUS ILIKE 'active%', u.COMPANY_NUMBER, NULL)) ch_active, COUNT(DISTINCT u.COMPANY_NUMBER) ch_found
FROM os JOIN psc ON psc.nk = os.nk AND psc.y = os.by_ AND psc.m = os.bm
LEFT JOIN LIBRARY_MARTS.CORPORATE_REGISTRY.CORPORATE_REGISTRY__INTL_UK_COMPANIES_HOUSE u ON u.COMPANY_NUMBER = psc.COMPANY_NUMBER
GROUP BY 1,2,3 ORDER BY open_cos DESC

