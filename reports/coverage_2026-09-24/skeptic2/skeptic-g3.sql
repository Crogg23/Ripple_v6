-- ===== file fjc1
-- @@ J1 PR foreclosures (NOS 220) since 2015, one row per case, by plaintiff class: open share, default share among CLOSED cases, other dispositions
WITH c AS (
  SELECT DISTRICT, OFFICE, DOCKET, FILE_DATE, TAPE_YEAR, JURISDICTION, DISPOSITION, JUDGMENT, TERM_DATE, UPPER(TRIM(PLAINTIFF)) p, UPPER(TRIM(DEFENDANT)) d
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_FJC_IDB_CIVIL
  WHERE FILE_DATE >= '2015-01-01' AND NATURE_OF_SUIT = '220'
  QUALIFY ROW_NUMBER() OVER (PARTITION BY DISTRICT, OFFICE, DOCKET, FILE_DATE ORDER BY IFF(TAPE_YEAR=2099,0,1) DESC, TAPE_YEAR DESC) = 1
), k AS (
  SELECT c.*, CASE WHEN DISTRICT<>'04' THEN 'Z mainland'
    WHEN p LIKE '%ROOSEVELT%' THEN 'A roosevelt (any spelling)'
    WHEN p LIKE '%CAYMAN%' THEN 'B other cayman'
    WHEN JURISDICTION IN ('1','2') THEN 'C PR US-govt party'
    WHEN JURISDICTION = '4' THEN 'D PR other diversity'
    ELSE 'E PR other juris' END grp,
    TERM_DATE IS NOT NULL AND DISPOSITION IS NOT NULL AND DISPOSITION NOT IN ('-8','') closed
  FROM c)
SELECT grp, COUNT(*) cases, COUNT(DISTINCT d) distinct_defendants, ROUND(AVG(IFF(closed,0,1)),3) open_share,
  ROUND(AVG(IFF(DISPOSITION='4',1,0)),3) default_all, ROUND(SUM(IFF(DISPOSITION='4',1,0))/NULLIF(SUM(IFF(closed,1,0)),0),3) default_of_closed,
  ROUND(SUM(IFF(DISPOSITION='12',1,0))/NULLIF(SUM(IFF(closed,1,0)),0),3) voldis_of_closed,
  ROUND(SUM(IFF(DISPOSITION='13',1,0))/NULLIF(SUM(IFF(closed,1,0)),0),3) settled_of_closed,
  ROUND(SUM(IFF(DISPOSITION IN ('18','16'),1,0))/NULLIF(SUM(IFF(closed,1,0)),0),3) statclose_or_bkstay_of_closed,
  ROUND(SUM(IFF(DISPOSITION='2',1,0))/NULLIF(SUM(IFF(closed,1,0)),0),3) dwop_of_closed,
  MEDIAN(YEAR(FILE_DATE)) med_file_yr, MIN(FILE_DATE) f0, MAX(FILE_DATE) f1
FROM k GROUP BY grp ORDER BY grp
-- @@ J2 PR only: default share among closed cases by filing year, Roosevelt vs other PR diversity plaintiffs vs other PR
WITH c AS (
  SELECT DISTRICT, OFFICE, DOCKET, FILE_DATE, TAPE_YEAR, JURISDICTION, DISPOSITION, TERM_DATE, UPPER(TRIM(PLAINTIFF)) p
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_FJC_IDB_CIVIL
  WHERE FILE_DATE >= '2015-01-01' AND NATURE_OF_SUIT = '220' AND DISTRICT = '04'
  QUALIFY ROW_NUMBER() OVER (PARTITION BY DISTRICT, OFFICE, DOCKET, FILE_DATE ORDER BY IFF(TAPE_YEAR=2099,0,1) DESC, TAPE_YEAR DESC) = 1
)
SELECT YEAR(FILE_DATE) yr,
  SUM(IFF(p LIKE '%ROOSEVELT%',1,0)) roos_n, ROUND(SUM(IFF(p LIKE '%ROOSEVELT%' AND DISPOSITION='4',1,0))/NULLIF(SUM(IFF(p LIKE '%ROOSEVELT%' AND TERM_DATE IS NOT NULL,1,0)),0),3) roos_def,
  SUM(IFF(p NOT LIKE '%ROOSEVELT%' AND p NOT LIKE '%CAYMAN%' AND JURISDICTION='4',1,0)) div_n,
  ROUND(SUM(IFF(p NOT LIKE '%ROOSEVELT%' AND p NOT LIKE '%CAYMAN%' AND JURISDICTION='4' AND DISPOSITION='4',1,0))/NULLIF(SUM(IFF(p NOT LIKE '%ROOSEVELT%' AND p NOT LIKE '%CAYMAN%' AND JURISDICTION='4' AND TERM_DATE IS NOT NULL,1,0)),0),3) div_def,
  SUM(IFF(p NOT LIKE '%ROOSEVELT%' AND p NOT LIKE '%CAYMAN%' AND JURISDICTION IN ('1','2'),1,0)) gov_n,
  ROUND(SUM(IFF(p NOT LIKE '%ROOSEVELT%' AND p NOT LIKE '%CAYMAN%' AND JURISDICTION IN ('1','2') AND DISPOSITION='4',1,0))/NULLIF(SUM(IFF(p NOT LIKE '%ROOSEVELT%' AND p NOT LIKE '%CAYMAN%' AND JURISDICTION IN ('1','2') AND TERM_DATE IS NOT NULL,1,0)),0),3) gov_def
FROM c GROUP BY 1 ORDER BY 1
-- @@ J3 PR diversity foreclosure plaintiffs with 40+ cases since 2015: who are Roosevelt's real peers, and their default share of closed cases
WITH c AS (
  SELECT DISTRICT, OFFICE, DOCKET, FILE_DATE, TAPE_YEAR, JURISDICTION, DISPOSITION, TERM_DATE, UPPER(TRIM(PLAINTIFF)) p
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_FJC_IDB_CIVIL
  WHERE FILE_DATE >= '2015-01-01' AND NATURE_OF_SUIT = '220' AND DISTRICT = '04'
  QUALIFY ROW_NUMBER() OVER (PARTITION BY DISTRICT, OFFICE, DOCKET, FILE_DATE ORDER BY IFF(TAPE_YEAR=2099,0,1) DESC, TAPE_YEAR DESC) = 1
)
SELECT p, MODE(JURISDICTION) juris, COUNT(*) n, SUM(IFF(TERM_DATE IS NOT NULL,1,0)) closed,
  ROUND(SUM(IFF(DISPOSITION='4',1,0))/NULLIF(SUM(IFF(TERM_DATE IS NOT NULL,1,0)),0),3) def_of_closed,
  ROUND(SUM(IFF(DISPOSITION='12',1,0))/NULLIF(SUM(IFF(TERM_DATE IS NOT NULL,1,0)),0),3) vol_of_closed,
  MIN(YEAR(FILE_DATE)) y0, MAX(YEAR(FILE_DATE)) y1
FROM c GROUP BY p HAVING COUNT(*) >= 30 ORDER BY n DESC

