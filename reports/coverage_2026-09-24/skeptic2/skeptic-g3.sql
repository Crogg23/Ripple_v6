-- ===== file fbi1
-- @@ F1 NM by year: homicide offenses, clearances, rate; implied covered population = offenses*1e5/rate (homicide and violent-crime)
SELECT YEAR(MONTH_DATE) yr, OFFENSE, COUNT(*) months, SUM(OFFENSES) off, SUM(CLEARANCES) clr, ROUND(SUM(CLEARANCES)/NULLIF(SUM(OFFENSES),0),3) clr_rate,
       ROUND(SUM(OFFENSES)*100000/NULLIF(SUM(OFFENSE_RATE_PER_100K),0)) implied_pop,
       ROUND(MIN(IFF(OFFENSE_RATE_PER_100K>0, OFFENSES*100000/OFFENSE_RATE_PER_100K, NULL))) min_m_pop, ROUND(MAX(IFF(OFFENSE_RATE_PER_100K>0, OFFENSES*100000/OFFENSE_RATE_PER_100K, NULL))) max_m_pop
FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_FBI_CDE
WHERE STATE='NM' AND OFFENSE IN ('homicide','violent-crime') AND MONTH_DATE >= '2012-01-01'
GROUP BY 1,2 ORDER BY 2,1
-- @@ F0 distinct offense labels
SELECT DISTINCT OFFENSE FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_FBI_CDE

-- ===== file fbi2
-- @@ F2 every state: homicide clearance 2015-19 vs 2022-23, and covered-population ratio (offenses*1e5/rate) for violent-crime, late vs early
WITH y AS (
  SELECT STATE, OFFENSE, IFF(YEAR(MONTH_DATE) BETWEEN 2015 AND 2019,'early','late') per, SUM(OFFENSES) off, SUM(CLEARANCES) clr,
         SUM(OFFENSES)*100000/NULLIF(SUM(OFFENSE_RATE_PER_100K),0) pop
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_FBI_CDE
  WHERE OFFENSE IN ('homicide','violent-crime') AND (YEAR(MONTH_DATE) BETWEEN 2015 AND 2019 OR YEAR(MONTH_DATE) IN (2022,2023))
  GROUP BY 1,2,3)
SELECT h.STATE, ROUND(h.clr/h.off,3) hom_early, ROUND(h2.clr/h2.off,3) hom_late, h2.off hom_off_late, ROUND(v2.pop/v.pop,3) cov_ratio_late_vs_early,
       ROUND(v.clr/v.off,3) vc_early, ROUND(v2.clr/v2.off,3) vc_late
FROM y h JOIN y h2 ON h2.STATE=h.STATE AND h2.OFFENSE='homicide' AND h2.per='late'
JOIN y v ON v.STATE=h.STATE AND v.OFFENSE='violent-crime' AND v.per='early'
JOIN y v2 ON v2.STATE=h.STATE AND v2.OFFENSE='violent-crime' AND v2.per='late'
WHERE h.OFFENSE='homicide' AND h.per='early'
ORDER BY hom_late
-- @@ F3 NM vs nation, every offense type: clearance rate 2015-19 vs 2022-23
SELECT OFFENSE,
  ROUND(SUM(IFF(STATE='NM' AND YEAR(MONTH_DATE)<=2019, CLEARANCES,0))/NULLIF(SUM(IFF(STATE='NM' AND YEAR(MONTH_DATE)<=2019, OFFENSES,0)),0),3) nm_early,
  ROUND(SUM(IFF(STATE='NM' AND YEAR(MONTH_DATE)>=2022, CLEARANCES,0))/NULLIF(SUM(IFF(STATE='NM' AND YEAR(MONTH_DATE)>=2022, OFFENSES,0)),0),3) nm_late,
  ROUND(SUM(IFF(STATE<>'NM' AND YEAR(MONTH_DATE)<=2019, CLEARANCES,0))/NULLIF(SUM(IFF(STATE<>'NM' AND YEAR(MONTH_DATE)<=2019, OFFENSES,0)),0),3) us_early,
  ROUND(SUM(IFF(STATE<>'NM' AND YEAR(MONTH_DATE)>=2022, CLEARANCES,0))/NULLIF(SUM(IFF(STATE<>'NM' AND YEAR(MONTH_DATE)>=2022, OFFENSES,0)),0),3) us_late
FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_FBI_CDE
WHERE YEAR(MONTH_DATE) BETWEEN 2015 AND 2019 OR YEAR(MONTH_DATE) IN (2022,2023)
GROUP BY 1 ORDER BY 1
-- @@ F4 NM homicide by month 2021-2023: months with offenses but zero clearances
SELECT YEAR(MONTH_DATE) yr, LISTAGG(OFFENSES||'/'||CLEARANCES, ' ') WITHIN GROUP (ORDER BY MONTH_DATE) off_slash_clr, SUM(IFF(CLEARANCES=0 AND OFFENSES>0,1,0)) zero_clr_months
FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_FBI_CDE WHERE STATE='NM' AND OFFENSE='homicide' AND YEAR(MONTH_DATE) BETWEEN 2016 AND 2023 GROUP BY 1 ORDER BY 1

