-- [g6-0 metadata: columns of lead tables and any enforcement/case/mine tables]
SELECT table_name, LISTAGG(column_name, ',') WITHIN GROUP (ORDER BY ordinal_position) cols
FROM LIBRARY_MARTS.INFORMATION_SCHEMA.COLUMNS
WHERE table_schema = 'ENVIRONMENT' AND (table_name IN ('ENVIRONMENT__FED_EPA_NPDES_NPDES_FORMAL_ENFORCEMENT_ACTIONS','ENVIRONMENT__FED_EPA_SDWA_SDWA_LCR_SAMPLES','ENVIRONMENT__FED_EPA_SDWA_SDWA_EVENTS_MILESTONES','ENVIRONMENT__FED_EPA_SDWA_SDWA_SITE_VISITS','ENVIRONMENT__FED_EPA_RCRA_EVALUATIONS','ENVIRONMENT__FED_EPA_NPDES_ICIS_FACILITIES','ENVIRONMENT__FED_EPA_ECHO')
  OR table_name ILIKE '%ENFORCE%' OR table_name ILIKE '%CASE%' OR table_name ILIKE '%SMCRA%' OR table_name ILIKE '%MINE%')
GROUP BY 1 ORDER BY 1;

-- [g6-L4-1 SDWA LCR: PB90 units, sign codes, spread, since 2024-10-16]
SELECT UNIT_OF_MEASURE, RESULT_SIGN_CODE, COUNT(*) n, COUNT(DISTINCT PWSID) sys,
  COUNT(DISTINCT SAMPLE_ID) sample_ids, COUNT(DISTINCT PWSID||'|'||SAMPLE_ID) pws_sample_ids,
  MIN(SAMPLE_MEASURE) mn, MEDIAN(SAMPLE_MEASURE) med, APPROX_PERCENTILE(SAMPLE_MEASURE,0.9) p90, MAX(SAMPLE_MEASURE) mx,
  COUNT(DISTINCT IFF(SAMPLE_MEASURE > 0.015, PWSID, NULL)) sys_over_015,
  COUNT(DISTINCT IFF(SAMPLE_MEASURE > 1, PWSID, NULL)) sys_over_1,
  COUNT(DISTINCT IFF(SAMPLE_MEASURE >= 15, PWSID, NULL)) sys_ge_15,
  MIN(SAMPLING_END_DATE) min_end, MAX(SAMPLING_END_DATE) max_end,
  COUNT(DISTINCT LEFT(PWSID,2)) states
FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_SDWA_SDWA_LCR_SAMPLES
WHERE CONTAMINANT_CODE = 'PB90' AND SAMPLING_END_DATE >= '2024-10-16'
GROUP BY ROLLUP(UNIT_OF_MEASURE, RESULT_SIGN_CODE) ORDER BY n DESC;

-- [g6-L4-2 SDWA LCR x LALE: over-limit systems by when the period started and when the result was reported vs the 2024-10-16 rule]
WITH o AS (
  SELECT PWSID, MIN(SAMPLING_START_DATE) min_start, MAX(SAMPLING_END_DATE) max_end,
    MAX(COALESCE(SAR_FIRST_REPORTED_DATE, SAMPLE_FIRST_REPORTED_DATE)) last_rep, MIN(COALESCE(SAR_FIRST_REPORTED_DATE, SAMPLE_FIRST_REPORTED_DATE)) first_rep,
    MAX(IFF(SAMPLING_START_DATE >= '2024-10-16',1,0)) any_start_post,
    MAX(IFF(COALESCE(SAR_FIRST_REPORTED_DATE, SAMPLE_FIRST_REPORTED_DATE) >= '2024-10-16',1,0)) any_rep_post,
    MAX(IFF(SAMPLING_END_DATE > '2026-09-24',1,0)) any_future_end,
    MAX(DATEDIFF(day, SAMPLING_START_DATE, SAMPLING_END_DATE)) max_len
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_SDWA_SDWA_LCR_SAMPLES
  WHERE CONTAMINANT_CODE = 'PB90' AND SAMPLING_END_DATE >= '2024-10-16' AND SAMPLE_MEASURE > 0.015
  GROUP BY 1),
l AS (SELECT PWSID, MIN(EVENT_ACTUAL_DATE) lale_dt, COUNT(*) n FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_SDWA_SDWA_EVENTS_MILESTONES WHERE EVENT_MILESTONE_CODE = 'LALE' GROUP BY 1),
lst AS (SELECT DISTINCT LEFT(PWSID,2) st FROM l),
p AS (SELECT PWSID, COUNT(*) prow, MAX(POPULATION_SERVED_COUNT) pop FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_SDWA_SDWA_PUB_WATER_SYSTEMS GROUP BY 1)
SELECT IFF(LEFT(o.PWSID,2) IN (SELECT st FROM lst),'state logs LALE','state logs none') peer,
  CASE WHEN any_start_post = 1 THEN 'A period starts after rule'
       WHEN any_rep_post = 1 THEN 'B period starts before, reported after rule'
       ELSE 'C reported before rule' END timing,
  COUNT(*) sys, SUM(IFF(l.PWSID IS NOT NULL,1,0)) with_lale, SUM(p.pop) pop, SUM(IFF(p.prow > 1,1,0)) dup_pws_rows,
  SUM(any_future_end) future_end, MEDIAN(max_len) med_period_days, MIN(first_rep) min_rep, MAX(last_rep) max_rep,
  SUM(IFF(l.PWSID IS NOT NULL AND l.lale_dt < '2024-10-16',1,0)) lale_before_rule
FROM o LEFT JOIN l ON l.PWSID = o.PWSID LEFT JOIN p ON p.PWSID = o.PWSID
GROUP BY ROLLUP(1,2) ORDER BY 1,2;

