-- [g6-L1-1 RCRA: EPA CEIs that found violations, paired state CEIs within 730 days, split by same-day, state-before, state-after]
WITH ev AS (
  SELECT ID_NUMBER, ACTIVITY_LOCATION st, EVALUATION_START_DATE dt, EVALUATION_AGENCY ag, MAX(IFF(FOUND_VIOLATION = 'Y',1,0)) y
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_RCRA_EVALUATIONS
  WHERE EVALUATION_TYPE = 'CEI' AND EVALUATION_START_DATE BETWEEN '2013-01-01' AND '2025-12-31'
    AND EVALUATION_AGENCY IN ('S','E') AND FOUND_VIOLATION IN ('Y','N')
  GROUP BY 1,2,3,4),
e AS (SELECT * FROM ev WHERE ag = 'E' AND dt >= '2015-01-01' AND y = 1),
s AS (SELECT * FROM ev WHERE ag = 'S'),
pr AS (
  SELECT e.st, e.ID_NUMBER, e.dt edt, s.dt sdt, s.y sy, DATEDIFF(day, e.dt, s.dt) gap
  FROM e JOIN s ON s.ID_NUMBER = e.ID_NUMBER AND ABS(DATEDIFF(day, s.dt, e.dt)) BETWEEN 0 AND 730)
SELECT IFF(st IN ('IL','NJ','PA','NC','CA','KY','WI'), st, 'other') grp,
  COUNT(DISTINCT ID_NUMBER||edt) epa_found_insp,
  COUNT(IFF(gap = 0,1,NULL)) same_day, ROUND(100*AVG(IFF(gap = 0, sy, NULL)),1) same_day_y,
  COUNT(IFF(gap BETWEEN -730 AND -1,1,NULL)) state_before, ROUND(100*AVG(IFF(gap BETWEEN -730 AND -1, sy, NULL)),1) before_y,
  COUNT(IFF(gap BETWEEN 1 AND 30,1,NULL)) after_1_30, ROUND(100*AVG(IFF(gap BETWEEN 1 AND 30, sy, NULL)),1) after_1_30_y,
  COUNT(IFF(gap BETWEEN 31 AND 730,1,NULL)) after_31_730, ROUND(100*AVG(IFF(gap BETWEEN 31 AND 730, sy, NULL)),1) after_31_730_y,
  COUNT(IFF(gap BETWEEN -30 AND -1,1,NULL)) before_1_30, ROUND(100*AVG(IFF(gap BETWEEN -30 AND -1, sy, NULL)),1) before_1_30_y
FROM pr GROUP BY ROLLUP(1) ORDER BY 1;

