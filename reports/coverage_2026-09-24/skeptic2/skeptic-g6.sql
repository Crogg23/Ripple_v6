enf AS (SELECT ID_NUMBER, ENFORCEMENT_ACTION_DATE edate, ENFORCEMENT_AGENCY eag, ENFORCEMENT_TYPE et FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_RCRA_ENFORCEMENTS
        WHERE ENFORCEMENT_ACTION_DATE >= '2015-01-01'),
pe AS (SELECT pr.*, MAX(IFF(enf.eag = 'E' AND enf.edate BETWEEN pr.edt AND DATEADD(day,365,pr.edt),1,0)) epa_enf_1y,
              MAX(IFF(enf.eag = 'E' AND enf.edate BETWEEN pr.edt AND DATEADD(day,365,pr.edt) AND enf.et >= '200',1,0)) epa_formal_1y
       FROM pr LEFT JOIN enf ON enf.ID_NUMBER = pr.ID_NUMBER GROUP BY 1,2,3,4,5,6),
sb AS (SELECT st, ROUND(100*AVG(y),1) state_base FROM ev WHERE ag = 'S' AND dt >= '2015-01-01' GROUP BY 1),
top AS (SELECT st, ID_NUMBER, COUNT(*) k FROM pr WHERE ey = 1 GROUP BY 1,2)
SELECT COALESCE(pe.st,'ALL') st,
  COUNT(IFF(ey=1,1,NULL)) epa_found, COUNT(DISTINCT IFF(ey=1,pe.ID_NUMBER,NULL)) epa_found_sites,
  ROUND(100*AVG(IFF(ey=1,sy,NULL)),1) state_y_where_epa_found,
  COUNT(IFF(ey=0,1,NULL)) epa_clean, ROUND(100*AVG(IFF(ey=0,sy,NULL)),1) state_y_where_epa_clean,
  MAX(sb.state_base) state_all_cei_base,
  ROUND(100*AVG(IFF(ey=1,epa_enf_1y,NULL)),1) epa_enf_within_1y_pct,
  ROUND(100*AVG(IFF(ey=1,epa_formal_1y,NULL)),1) epa_formal_code200plus_pct,
  (SELECT MAX(k) FROM top WHERE top.st = pe.st) max_insp_one_site
FROM pe LEFT JOIN sb ON sb.st = pe.st
WHERE pe.st IN ('IL','NJ','PA','NC','CA','KY','MD','WI','NE','WA','SC','TX')
GROUP BY ROLLUP(pe.st) ORDER BY state_y_where_epa_found;

-- [g6-L2-1 NPDES WV: mines vs sewer vs other, chronic20, formal actions by agency and era, violations per bad quarter]
WITH q AS (
  SELECT NPDES_ID, COUNT(DISTINCT YEARQTR) qtrs, COUNT(DISTINCT IFF(TRY_TO_NUMBER(NUME90_Q) > 0, YEARQTR, NULL)) eff_q, SUM(TRY_TO_NUMBER(NUME90_Q)) eff_n
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_QNCR_HISTORY
  WHERE TRY_TO_NUMBER(YEARQTR) BETWEEN 20161 AND 20254 AND LEFT(NPDES_ID,2) = 'WV' GROUP BY 1),
fe AS (
  SELECT NPDES_ID, COUNT(*) fe_all, MAX(SETTLEMENT_ENTERED_DATE) last_fe,
    COUNT(IFF(SETTLEMENT_ENTERED_DATE >= '2016-01-01',1,NULL)) fe_win,
    COUNT(IFF(SETTLEMENT_ENTERED_DATE >= '2016-01-01' AND AGENCY ILIKE 'S%',1,NULL)) fe_win_state,
    COUNT(IFF(SETTLEMENT_ENTERED_DATE >= '2016-01-01' AND AGENCY ILIKE 'E%',1,NULL)) fe_win_epa,
    COUNT(IFF(SETTLEMENT_ENTERED_DATE BETWEEN '2010-01-01' AND '2015-12-31',1,NULL)) fe_1015,
    COUNT(IFF(SETTLEMENT_ENTERED_DATE IS NULL,1,NULL)) fe_null,
    LISTAGG(DISTINCT AGENCY, ',') ags
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_FORMAL_ENFORCEMENT_ACTIONS WHERE LEFT(NPDES_ID,2) = 'WV' GROUP BY 1),
j AS (
  SELECT q.*, COALESCE(fe.fe_all,0) fe_all, COALESCE(fe.fe_win,0) fe_win, COALESCE(fe.fe_win_state,0) fws, COALESCE(fe.fe_win_epa,0) fwe,
    COALESCE(fe.fe_1015,0) f1015, COALESCE(fe.fe_null,0) fnull, fe.ags, fac.FACILITY_TYPE_CODE ft,
    CASE WHEN fac.FACILITY_NAME ILIKE ANY ('%MINE%','%MINING%','%COAL%','%SURFACE%','%PREP PLANT%','%REFUSE%') THEN 'mine'
         WHEN fac.FACILITY_TYPE_CODE IN ('MWD','CTG','CNG') THEN 'public sewer' ELSE 'other' END kind
  FROM q LEFT JOIN fe ON fe.NPDES_ID = q.NPDES_ID
  LEFT JOIN LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_ICIS_FACILITIES fac ON fac.NPDES_ID = q.NPDES_ID
  WHERE q.qtrs >= 36)
SELECT kind, IFF(eff_q >= 20,'chronic20','not') grp, COUNT(*) permits,
  SUM(IFF(fe_win > 0,1,0)) formal_since16, SUM(IFF(fws > 0,1,0)) state_formal_since16, SUM(IFF(fwe > 0,1,0)) epa_formal_since16,
  SUM(IFF(fe_win = 0 AND f1015 > 0,1,0)) only_2010_15_formal, SUM(IFF(fe_all = 0,1,0)) never_formal, SUM(IFF(fe_win = 0 AND fnull > 0,1,0)) null_dated_only,
  ROUND(AVG(eff_n / NULLIF(eff_q,0)),1) viol_per_bad_qtr, LISTAGG(DISTINCT ft, ',') ftypes, LISTAGG(DISTINCT ags, ',') agencies
FROM j GROUP BY 1,2 ORDER BY 1,2;

-- [g6-L2-2 NPDES: the 553 worst and 152 no-formal by state, against each state's own formal and informal action rates]
WITH q AS (
  SELECT NPDES_ID, COUNT(DISTINCT YEARQTR) qtrs, COUNT(DISTINCT IFF(TRY_TO_NUMBER(NUME90_Q) > 0, YEARQTR, NULL)) eff_q
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_QNCR_HISTORY
  WHERE TRY_TO_NUMBER(YEARQTR) BETWEEN 20161 AND 20254 GROUP BY 1 HAVING COUNT(DISTINCT YEARQTR) >= 36),
fe AS (SELECT NPDES_ID, COUNT(*) fe_all, COUNT(IFF(SETTLEMENT_ENTERED_DATE >= '2016-01-01',1,NULL)) fe_win
       FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_FORMAL_ENFORCEMENT_ACTIONS GROUP BY 1),
ie AS (SELECT NPDES_ID, COUNT(IFF(ACHIEVED_DATE BETWEEN '2016-01-01' AND '2025-12-31',1,NULL)) ie_win
       FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_INFORMAL_ENFORCEMENT_ACTIONS GROUP BY 1),
j AS (SELECT q.*, LEFT(q.NPDES_ID,2) st, COALESCE(fe.fe_all,0) fe_all, COALESCE(fe.fe_win,0) fe_win, COALESCE(ie.ie_win,0) ie_win
      FROM q LEFT JOIN fe ON fe.NPDES_ID = q.NPDES_ID LEFT JOIN ie ON ie.NPDES_ID = q.NPDES_ID),
sts AS (SELECT st, COUNT(*) permits36, ROUND(100*AVG(IFF(fe_win > 0,1,0)),1) st_formal_pct_all, ROUND(100*AVG(IFF(ie_win > 0,1,0)),1) st_informal_pct_all,
          ROUND(100*AVG(IFF(eff_q >= 20, IFF(fe_win > 0,1,0), NULL)),1) st_formal_pct_chronic20,
          COUNT(IFF(eff_q >= 36,1,NULL)) worst, COUNT(IFF(eff_q >= 36 AND fe_win = 0,1,NULL)) worst_no_formal,
          COUNT(IFF(eff_q >= 36 AND fe_win = 0 AND ie_win = 0,1,NULL)) worst_no_action
        FROM j GROUP BY 1)
SELECT * FROM sts WHERE worst_no_formal > 0 OR st IN ('WV') 
UNION ALL
SELECT 'ALL', SUM(permits36), NULL, NULL, NULL, SUM(worst), SUM(worst_no_formal), SUM(worst_no_action) FROM sts
ORDER BY worst_no_formal DESC;

-- [g6-L2-3 NPDES WV chronic mines: state-held (reclamation/forfeiture) names, still violating 2024-25, top no-formal list]
WITH q AS (
  SELECT NPDES_ID, COUNT(DISTINCT YEARQTR) qtrs, COUNT(DISTINCT IFF(TRY_TO_NUMBER(NUME90_Q) > 0, YEARQTR, NULL)) eff_q, SUM(TRY_TO_NUMBER(NUME90_Q)) eff_n,
    COUNT(DISTINCT IFF(TRY_TO_NUMBER(YEARQTR) >= 20241 AND TRY_TO_NUMBER(NUME90_Q) > 0, YEARQTR, NULL)) eff_q_24_25
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_QNCR_HISTORY
  WHERE TRY_TO_NUMBER(YEARQTR) BETWEEN 20161 AND 20254 AND LEFT(NPDES_ID,2) = 'WV' GROUP BY 1 HAVING COUNT(DISTINCT YEARQTR) >= 36),
fe AS (SELECT NPDES_ID, COUNT(IFF(SETTLEMENT_ENTERED_DATE >= '2016-01-01',1,NULL)) fe_win, COUNT(*) fe_all FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_FORMAL_ENFORCEMENT_ACTIONS WHERE LEFT(NPDES_ID,2)='WV' GROUP BY 1),
j AS (SELECT q.*, COALESCE(fe.fe_win,0) fe_win, COALESCE(fe.fe_all,0) fe_all, fac.FACILITY_NAME nm, fac.CITY, fac.FACILITY_TYPE_CODE ft
      FROM q LEFT JOIN fe ON fe.NPDES_ID = q.NPDES_ID
      JOIN LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_ICIS_FACILITIES fac ON fac.NPDES_ID = q.NPDES_ID
      WHERE q.eff_q >= 20 AND fac.FACILITY_NAME ILIKE ANY ('%MINE%','%MINING%','%COAL%','%SURFACE%','%PREP PLANT%','%REFUSE%'))
SELECT 'SUM' k, IFF(nm ILIKE ANY ('%RECLAMATION%','%FORFEIT%','%WVDEP%','%DEP %','%DEPARTMENT OF ENV%'),'state-held name','other') grp,
  COUNT(*) n, SUM(IFF(fe_win = 0,1,0)) no_formal, SUM(IFF(eff_q_24_25 > 0,1,0)) still_violating_24_25, SUM(eff_n) eff_n, NULL nm, NULL ft
FROM j GROUP BY 2
UNION ALL
SELECT * FROM (SELECT 'ROW', NPDES_ID, eff_q, fe_win, eff_q_24_25, eff_n, nm||' / '||CITY, ft FROM j WHERE fe_win = 0 ORDER BY eff_n DESC LIMIT 25)
ORDER BY 1 DESC, 6 DESC;
