-- [29] reimb: mega-venue bankruptcy judges vs other bk judges, practitioner-paid share
WITH ct AS (
  SELECT PERSON_ID::VARCHAR pid,
         MAX(IFF(COURT_ID IN ('deb','nysb','txsb','njb'), 1, 0)) mega,
         MAX(IFF(RIGHT(COURT_ID,1)='b', 1, 0)) is_bk, LISTAGG(DISTINCT IFF(RIGHT(COURT_ID,1)='b', COURT_ID, NULL), ',') bk_courts
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_COURTLISTENER_POSITIONS WHERE COURT_ID IS NOT NULL AND COURT_ID <> '' GROUP BY 1
),
r AS (
  SELECT d.PERSON_ID::VARCHAR pid, d.YEAR_COL::INT yr, r.SOURCE,
    IFF(r.SOURCE ILIKE '%turnaround%' OR r.SOURCE ILIKE '%American Bankruptcy Inst%' OR r.SOURCE ILIKE 'ABI%' OR r.SOURCE ILIKE '%insolvency%'
        OR r.SOURCE ILIKE '%INSOL%' OR r.SOURCE ILIKE '%restructuring%' OR r.SOURCE ILIKE '%American College of Bankruptcy%'
        OR (r.SOURCE ILIKE '%bankrupt%' AND r.SOURCE NOT ILIKE '%conference of bankruptcy judges%'), 1, 0) prac,
    IFF(r.SOURCE ILIKE '%turnaround%', 1, 0) tma
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_COURTLISTENER_DISCLOSURE_REIMBURSEMENTS r
  JOIN LIBRARY_MARTS.JUSTICE.JUSTICE__FED_COURTLISTENER_FINANCIAL_DISCLOSURES d
    ON TRY_TO_NUMBER(d.ID::VARCHAR) = TRY_TO_NUMBER(r.FINANCIAL_DISCLOSURE_ID::VARCHAR)
  WHERE d.PERSON_ID IS NOT NULL AND TRY_TO_NUMBER(d.YEAR_COL::VARCHAR) BETWEEN 2011 AND 2019
)
SELECT IFF(ct.mega=1, 'mega-venue bk judge: ' || COALESCE(j.NAME_LAST,'?') || ' (' || ct.bk_courts || ')', 'ALL OTHER BK JUDGES') who,
       COUNT(DISTINCT r.pid) judges, COUNT(DISTINCT r.pid||r.yr) judge_yrs_with_trips, COUNT(*) trips, SUM(prac) prac_trips, SUM(tma) tma_trips,
       ROUND(100*SUM(prac)/COUNT(*),1) prac_pct, ROUND(COUNT(*)/COUNT(DISTINCT r.pid||r.yr),2) trips_per_yr
FROM r JOIN ct ON ct.pid = r.pid AND ct.is_bk = 1
LEFT JOIN LIBRARY_MARTS.JUSTICE.JUSTICE__FED_COURTLISTENER_JUDGES j ON j.ID::VARCHAR = r.pid
GROUP BY 1 ORDER BY trips DESC LIMIT 30;

