-- [2] reimb: join coverage by disclosure year
WITH r AS (
  SELECT r.*, d.YEAR_COL, d.PERSON_ID
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_COURTLISTENER_DISCLOSURE_REIMBURSEMENTS r
  LEFT JOIN LIBRARY_MARTS.JUSTICE.JUSTICE__FED_COURTLISTENER_FINANCIAL_DISCLOSURES d
    ON TRY_TO_NUMBER(d.ID::VARCHAR) = TRY_TO_NUMBER(r.FINANCIAL_DISCLOSURE_ID::VARCHAR)
)
SELECT YEAR_COL, COUNT(*) AS rows_, COUNT(PERSON_ID) AS with_person,
       COUNT(DISTINCT PERSON_ID) AS judges, COUNT(DISTINCT FINANCIAL_DISCLOSURE_ID) AS reports,
       COUNT_IF(REDACTED = 't') AS redacted,
       COUNT_IF(SOURCE ILIKE '%bankrupt%' OR SOURCE ILIKE 'ABI%' OR SOURCE ILIKE '%NCBJ%') AS bk_group_rows
FROM r GROUP BY 1 ORDER BY 1;

-- [3] reimb: top judges by trips 2011-19
WITH r AS (
  SELECT r.SOURCE, r.PURPOSE, d.YEAR_COL::INT AS yr, d.PERSON_ID
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_COURTLISTENER_DISCLOSURE_REIMBURSEMENTS r
  JOIN LIBRARY_MARTS.JUSTICE.JUSTICE__FED_COURTLISTENER_FINANCIAL_DISCLOSURES d
    ON TRY_TO_NUMBER(d.ID::VARCHAR) = TRY_TO_NUMBER(r.FINANCIAL_DISCLOSURE_ID::VARCHAR)
  WHERE d.PERSON_ID IS NOT NULL AND TRY_TO_NUMBER(d.YEAR_COL::VARCHAR) BETWEEN 2011 AND 2019
),
src AS (
  SELECT PERSON_ID, SOURCE, COUNT(*) n,
         ROW_NUMBER() OVER (PARTITION BY PERSON_ID ORDER BY COUNT(*) DESC) rk
  FROM r GROUP BY 1,2
),
j AS (
  SELECT PERSON_ID, COUNT(*) trips, COUNT(DISTINCT yr) yrs, COUNT(DISTINCT SOURCE) sources,
         COUNT_IF(SOURCE ILIKE '%bankrupt%' OR SOURCE ILIKE 'ABI%' OR SOURCE ILIKE '%NCBJ%') bk_grp
  FROM r GROUP BY 1
),
ct AS (
  SELECT PERSON_ID::VARCHAR pid, LISTAGG(DISTINCT COURT_ID, ',') courts
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_COURTLISTENER_POSITIONS
  WHERE COURT_ID IS NOT NULL AND COURT_ID <> '' GROUP BY 1
)
SELECT jg.NAME_FIRST || ' ' || jg.NAME_LAST AS judge, ct.courts, j.trips, j.yrs,
       ROUND(j.trips / j.yrs, 1) per_yr, j.sources, j.bk_grp,
       LISTAGG(s.SOURCE || ' (' || s.n || ')', '; ') WITHIN GROUP (ORDER BY s.n DESC) top3
FROM j
JOIN src s ON s.PERSON_ID = j.PERSON_ID AND s.rk <= 3
LEFT JOIN LIBRARY_MARTS.JUSTICE.JUSTICE__FED_COURTLISTENER_JUDGES jg ON jg.ID::VARCHAR = j.PERSON_ID::VARCHAR
LEFT JOIN ct ON ct.pid = j.PERSON_ID::VARCHAR
GROUP BY 1,2,3,4,5,6,7
ORDER BY j.trips DESC
LIMIT 30;

-- [4] reimb: bankruptcy judges vs peers, who pays
WITH ct AS (
  SELECT PERSON_ID::VARCHAR pid,
         MAX(IFF(RIGHT(COURT_ID,1)='b' AND COURT_ID NOT IN ('scotus'), 1, 0)) is_bk,
         MAX(IFF(COURT_ID LIKE 'ca%' OR COURT_ID='cafc' OR COURT_ID='scotus', 1, 0)) is_app
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_COURTLISTENER_POSITIONS
  WHERE COURT_ID IS NOT NULL AND COURT_ID <> '' GROUP BY 1
),
r AS (
  SELECT r.SOURCE, d.YEAR_COL::INT yr, d.PERSON_ID::VARCHAR pid,
    CASE WHEN r.SOURCE ILIKE '%conference of bankruptcy judges%' OR r.SOURCE ILIKE '%NCBJ%' THEN 'NCBJ judges own group'
         WHEN r.SOURCE ILIKE '%bankrupt%' OR r.SOURCE ILIKE 'ABI%' OR r.SOURCE ILIKE '%turnaround%' OR r.SOURCE ILIKE '%insolvency%'
              OR r.SOURCE ILIKE '%INSOL%' OR r.SOURCE ILIKE '%restructuring%' OR r.SOURCE ILIKE '%creditor%' OR r.SOURCE ILIKE '%chapter 13 trustee%' THEN 'bk practitioner group'
         WHEN r.SOURCE ILIKE '%LLP%' OR r.SOURCE ILIKE '%L.L.P%' OR r.SOURCE ILIKE '%LLC%' OR r.SOURCE ILIKE '% P.C.%' OR r.SOURCE ILIKE '%, PC%'
              OR r.SOURCE ILIKE '%PLLC%' OR r.SOURCE ILIKE '% Inc%' OR r.SOURCE ILIKE '%Corp%' OR r.SOURCE ILIKE '%law firm%' OR r.SOURCE ILIKE '%law office%' THEN 'firm or company'
         ELSE 'other' END AS kind
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_COURTLISTENER_DISCLOSURE_REIMBURSEMENTS r
  JOIN LIBRARY_MARTS.JUSTICE.JUSTICE__FED_COURTLISTENER_FINANCIAL_DISCLOSURES d
    ON TRY_TO_NUMBER(d.ID::VARCHAR) = TRY_TO_NUMBER(r.FINANCIAL_DISCLOSURE_ID::VARCHAR)
  WHERE d.PERSON_ID IS NOT NULL AND TRY_TO_NUMBER(d.YEAR_COL::VARCHAR) BETWEEN 2011 AND 2019
)
SELECT CASE WHEN ct.is_bk=1 THEN 'bankruptcy judge' WHEN ct.is_app=1 THEN 'appeals/scotus' WHEN ct.pid IS NULL THEN 'no court on file' ELSE 'district/magistrate/other' END grp,
       COUNT(DISTINCT r.pid) judges, COUNT(DISTINCT r.pid||'-'||r.yr) judge_years, COUNT(*) trips,
       ROUND(COUNT(*)/COUNT(DISTINCT r.pid||'-'||r.yr),2) trips_per_judge_year,
       COUNT_IF(kind='bk practitioner group') bk_prac, ROUND(100*COUNT_IF(kind='bk practitioner group')/COUNT(*),1) bk_prac_pct,
       COUNT_IF(kind='NCBJ judges own group') ncbj,
       COUNT_IF(kind='firm or company') firm_co, ROUND(100*COUNT_IF(kind='firm or company')/COUNT(*),1) firm_pct
FROM r LEFT JOIN ct ON ct.pid = r.pid
GROUP BY 1 ORDER BY 2 DESC;

-- [5] reimb: firms and companies paying judges
WITH r AS (
  SELECT r.SOURCE, r.PURPOSE, d.YEAR_COL::INT yr, d.PERSON_ID::VARCHAR pid
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_COURTLISTENER_DISCLOSURE_REIMBURSEMENTS r
  JOIN LIBRARY_MARTS.JUSTICE.JUSTICE__FED_COURTLISTENER_FINANCIAL_DISCLOSURES d
    ON TRY_TO_NUMBER(d.ID::VARCHAR) = TRY_TO_NUMBER(r.FINANCIAL_DISCLOSURE_ID::VARCHAR)
  WHERE d.PERSON_ID IS NOT NULL
    AND (r.SOURCE ILIKE '%LLP%' OR r.SOURCE ILIKE '%L.L.P%' OR r.SOURCE ILIKE '%LLC%' OR r.SOURCE ILIKE '% P.C.%' OR r.SOURCE ILIKE '%, PC%'
      OR r.SOURCE ILIKE '%PLLC%' OR r.SOURCE ILIKE '% Inc%' OR r.SOURCE ILIKE '%Corp%' OR r.SOURCE ILIKE '%law firm%' OR r.SOURCE ILIKE '%law office%'
      OR r.SOURCE ILIKE '%turnaround%')
)
SELECT UPPER(REGEXP_REPLACE(SOURCE, '[^A-Za-z ]', '')) src_norm, COUNT(*) trips, COUNT(DISTINCT pid) judges, MIN(yr) y0, MAX(yr) y1,
       LISTAGG(DISTINCT j.NAME_LAST, ',') WITHIN GROUP (ORDER BY j.NAME_LAST) judge_names,
       ANY_VALUE(PURPOSE) a_purpose
FROM r LEFT JOIN LIBRARY_MARTS.JUSTICE.JUSTICE__FED_COURTLISTENER_JUDGES j ON j.ID::VARCHAR = r.pid
GROUP BY 1 ORDER BY 2 DESC LIMIT 30;

