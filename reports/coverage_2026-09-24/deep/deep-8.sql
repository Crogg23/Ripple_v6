-- [8] fjc bk: ch11 2015+ latest snapshot, discharged vs total debt by disposition
WITH c AS (
  SELECT * FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_FJC_IDB_BANKRUPTCY
  WHERE ORIGINAL_FILING_CHAPTER = '11' AND ORIGINAL_FILING_DATE >= '2015-01-01'
  QUALIFY ROW_NUMBER() OVER (PARTITION BY CASE_KEY ORDER BY SNAPSHOT DESC) = 1
)
SELECT COALESCE(NULLIF(DEBTOR1_FINAL_DISPOSITION,''),'(open/blank)') disp, DEBTOR_TYPE,
       COUNT(*) cases,
       COUNT(DEBT_DISCHARGED) dd_filled,
       COUNT_IF(DEBT_DISCHARGED = TOTAL_DEBT AND TOTAL_DEBT > 0) dd_eq_total,
       COUNT_IF(DEBT_DISCHARGED > 0) dd_pos,
       ROUND(SUM(DEBT_DISCHARGED)/1e9,1) dd_bn, ROUND(SUM(TOTAL_ASSETS)/1e9,1) assets_bn,
       ROUND(MAX(TOTAL_ASSETS)/1e9,2) max_assets_bn, ROUND(MAX(DEBT_DISCHARGED)/1e9,2) max_dd_bn,
       COUNT_IF(JOINT_ADMINISTRATION_LEAD IS NOT NULL AND JOINT_ADMINISTRATION_LEAD <> '') joint_admin
FROM c GROUP BY 1,2 HAVING COUNT(*) >= 50 ORDER BY 3 DESC LIMIT 30;

-- [9] fjc bk: ch11 business families 2015+, $1B+ by district
WITH c AS (
  SELECT CASE_KEY, DISTRICT, FILING_CALENDAR_YEAR, TOTAL_ASSETS, TOTAL_LIABILITIES,
         COALESCE(NULLIF(LEFT(JOINT_ADMINISTRATION_LEAD,12),''), SUBSTR(CASE_KEY,3,12)) fam
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_FJC_IDB_BANKRUPTCY
  WHERE ORIGINAL_FILING_CHAPTER = '11' AND ORIGINAL_FILING_DATE >= '2015-01-01' AND DEBTOR_TYPE <> 'i'
  QUALIFY ROW_NUMBER() OVER (PARTITION BY CASE_KEY ORDER BY SNAPSHOT DESC) = 1
),
f AS (
  SELECT fam, SUBSTR(fam,3,2) dist, COUNT(*) affiliates, MAX(TOTAL_ASSETS) fam_assets, MAX(TOTAL_LIABILITIES) fam_liab
  FROM c GROUP BY 1,2
)
SELECT dist,
       COUNT(*) families, COUNT_IF(fam_assets >= 1e9) fam_1bn_plus, COUNT_IF(fam_liab >= 1e9) liab_1bn_plus,
       ROUND(SUM(IFF(fam_assets>=1e9, fam_assets,0))/1e9,0) assets_bn_in_1bn_fams,
       ROUND(100*RATIO_TO_REPORT(COUNT_IF(fam_assets >= 1e9)) OVER (),1) pct_of_us_1bn_fams,
       ROUND(100*RATIO_TO_REPORT(COUNT(*)) OVER (),1) pct_of_all_fams,
       MAX(affiliates) max_affiliates, ROUND(MAX(fam_assets)/1e9,1) biggest_bn
FROM f GROUP BY 1 ORDER BY fam_1bn_plus DESC LIMIT 12;

-- [10] fjc bk: 20+ affiliate families by district and era; discharged on pending cases
WITH c AS (
  SELECT CASE_KEY, FILING_CALENDAR_YEAR yr, TOTAL_ASSETS, TOTAL_DEBT, DEBT_DISCHARGED, SNAPSHOT_PENDING_FLAG, DEBTOR1_FINAL_DISPOSITION,
         COALESCE(NULLIF(LEFT(JOINT_ADMINISTRATION_LEAD,12),''), SUBSTR(CASE_KEY,3,12)) fam
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_FJC_IDB_BANKRUPTCY
  WHERE ORIGINAL_FILING_CHAPTER = '11' AND ORIGINAL_FILING_DATE >= '2015-01-01' AND DEBTOR_TYPE <> 'i'
  QUALIFY ROW_NUMBER() OVER (PARTITION BY CASE_KEY ORDER BY SNAPSHOT DESC) = 1
),
f AS (
  SELECT fam, SUBSTR(fam,3,2) dist, MIN(yr) yr, COUNT(*) affiliates, MAX(COALESCE(TOTAL_ASSETS,0)) fam_assets
  FROM c GROUP BY 1,2 HAVING COUNT(*) >= 20
)
SELECT 'fam20+ ' || CASE WHEN dist IN ('11','08','41','12','39') THEN dist ELSE 'rest' END AS label,
       COUNT(*) n_all, COUNT_IF(yr BETWEEN 2015 AND 2018) n_15_18, COUNT_IF(yr BETWEEN 2019 AND 2022) n_19_22, COUNT_IF(yr >= 2023) n_23_plus,
       COUNT_IF(fam_assets < 1e6) assets_under_1m
FROM f GROUP BY 1
UNION ALL
SELECT 'dd check pending=' || COALESCE(SNAPSHOT_PENDING_FLAG::VARCHAR,'null') || ' disp=' || IFF(COALESCE(DEBTOR1_FINAL_DISPOSITION,'')='','blank','set'),
       COUNT(*), COUNT_IF(DEBT_DISCHARGED > 0), ROUND(SUM(DEBT_DISCHARGED)/1e9,1), COUNT_IF(DEBT_DISCHARGED = TOTAL_DEBT AND TOTAL_DEBT > 0), NULL
FROM c GROUP BY 1
ORDER BY 1;

