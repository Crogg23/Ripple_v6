-- Q8: PENALTY_GAP program mix of the 8+ quarter group, with the drinking-water flag pulled from ECHO by FRS_ID
WITH e AS (
  SELECT FRS_ID, MAX(LOWER(HAS_DRINKING_WATER_PROGRAM::STRING) = 'true') dw
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ECHO GROUP BY FRS_ID
), g AS (
  SELECT p.*, e.dw,
    CASE WHEN LOWER(HAS_AIR_PROGRAM::STRING) = 'true' THEN 'AIR'
         WHEN LOWER(HAS_HAZWASTE_PROGRAM::STRING) = 'true' THEN 'HAZ'
         WHEN LOWER(HAS_WATER_PROGRAM::STRING) = 'true' THEN 'WATER'
         ELSE 'NONE' END prog
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__EPA_PENALTY_GAP p LEFT JOIN e ON e.FRS_ID = p.FRS_ID
)
SELECT prog, COUNT(*) n, COUNT_IF(e_match) echo_matched, COUNT_IF(dw) drinking_water,
  COUNT_IF(q >= 8) q8,
  COUNT_IF(q >= 8 AND COALESCE(LAST_PENALTY_AMT_ALLOCATED, 0) = 0) q8_never_pen,
  COUNT_IF(q >= 8 AND COALESCE(LAST_PENALTY_AMT_ALLOCATED, 0) = 0 AND COALESCE(TOTAL_INSPECTION_COUNT, 0) = 0) q8_never_pen_no_insp,
  COUNT_IF(q >= 8 AND COALESCE(LAST_PENALTY_AMT_ALLOCATED, 0) = 0 AND DATE_LAST_INSPECTION IS NULL) q8_never_pen_no_insp_ever,
  COUNT_IF(q >= 8 AND PCT_MINORITY IS NULL) q8_pct_null
FROM (SELECT g.*, QUARTERS_WITH_NONCOMPLIANCE::NUMBER q, dw IS NOT NULL e_match FROM g) x
GROUP BY prog ORDER BY n DESC;

-- Q9: PENALTY_GAP: among 8+ quarter violators, share never fined and share never inspected, by neighborhood minority band, within program
WITH g AS (
  SELECT QUARTERS_WITH_NONCOMPLIANCE::NUMBER q, LAST_PENALTY_AMT_ALLOCATED pen, TOTAL_INSPECTION_COUNT insp, DATE_LAST_INSPECTION dli,
    CASE WHEN LOWER(HAS_AIR_PROGRAM::STRING) = 'true' THEN 'AIR'
         WHEN LOWER(HAS_HAZWASTE_PROGRAM::STRING) = 'true' THEN 'HAZ'
         WHEN LOWER(HAS_WATER_PROGRAM::STRING) = 'true' THEN 'WATER'
         ELSE 'NONE' END prog,
    CASE WHEN PCT_MINORITY IS NULL THEN '9 null'
         WHEN PCT_MINORITY < 10 THEN '1 <10' WHEN PCT_MINORITY < 25 THEN '2 10-25'
         WHEN PCT_MINORITY < 50 THEN '3 25-50' WHEN PCT_MINORITY < 75 THEN '4 50-75' ELSE '5 75+' END band
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__EPA_PENALTY_GAP
)
SELECT prog, band, COUNT(*) all_fac, COUNT_IF(q >= 8) q8,
  ROUND(COUNT_IF(q >= 8) / COUNT(*) * 100, 1) pct_q8_of_all,
  ROUND(COUNT_IF(q >= 8 AND COALESCE(pen, 0) = 0) / NULLIF(COUNT_IF(q >= 8), 0) * 100, 1) pct_q8_never_pen,
  ROUND(COUNT_IF(q >= 8 AND dli IS NULL) / NULLIF(COUNT_IF(q >= 8), 0) * 100, 1) pct_q8_never_insp,
  ROUND(COUNT_IF(q >= 8 AND COALESCE(pen, 0) = 0 AND COALESCE(insp, 0) = 0) / NULLIF(COUNT_IF(q >= 8), 0) * 100, 1) pct_q8_nopen_noinsp_window
FROM g WHERE prog <> 'NONE' GROUP BY prog, band ORDER BY prog, band;

