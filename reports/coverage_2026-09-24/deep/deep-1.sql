-- Q19: AIR_VIOL: HPVs that started 2012-2021 (so 4+ years to act); resolved share, time to resolve, and any formal action or penalty at the same facility after day zero, by state
WITH h AS (
  SELECT PGM_SYS_ID, COMP_DETERMINATION_UID uid, ANY_VALUE(STATE_CODE) st, MIN(HPV_DAYZERO_DATE) dz, MAX(HPV_RESOLVED_DATE) res
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ICIS_AIR_ICIS_AIR_VIOLATION_HISTORY
  WHERE ENF_RESPONSE_POLICY_CODE = 'HPV' AND HPV_DAYZERO_DATE BETWEEN '2012-01-01' AND '2021-12-31'
  GROUP BY 1, 2
), a AS (
  SELECT PGM_SYS_ID, ENF_IDENTIFIER, MIN(SETTLEMENT_ENTERED_DATE) d, MAX(PENALTY_AMOUNT) pen
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ICIS_AIR_ICIS_AIR_FORMAL_ACTIONS GROUP BY 1, 2
), j AS (
  SELECT h.st, h.uid, h.dz, h.res,
    COUNT(IFF(a.d >= h.dz AND a.d <= DATEADD(day, 730, h.dz), 1, NULL)) fa_2y,
    COUNT(IFF(a.d >= h.dz, 1, NULL)) fa_after,
    SUM(IFF(a.d >= h.dz, a.pen, 0)) pen_after
  FROM h LEFT JOIN a ON a.PGM_SYS_ID = h.PGM_SYS_ID
  GROUP BY 1, 2, 3, 4
)
SELECT st, COUNT(*) hpvs, ROUND(COUNT_IF(res IS NULL) / COUNT(*) * 100, 1) pct_unresolved,
  MEDIAN(DATEDIFF(day, dz, res)) med_days_to_resolve,
  ROUND(COUNT_IF(fa_2y > 0) / COUNT(*) * 100, 1) pct_formal_2y, ROUND(COUNT_IF(fa_after = 0) / COUNT(*) * 100, 1) pct_no_formal_ever,
  ROUND(COUNT_IF(COALESCE(pen_after, 0) = 0) / COUNT(*) * 100, 1) pct_no_pen_after,
  SUM(COUNT(*)) OVER () all_hpvs, SUM(COUNT_IF(fa_after = 0)) OVER () all_no_formal, SUM(COUNT_IF(res IS NULL)) OVER () all_unres
FROM j GROUP BY st HAVING COUNT(*) >= 40 ORDER BY hpvs DESC;

