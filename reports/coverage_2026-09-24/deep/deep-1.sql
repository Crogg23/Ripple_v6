-- Q11: PENALTY_GAP: no-inspection-on-record gap, 8+ quarter WATER and HAZ violators, 50%+ minority vs under 25% minority, state by state (peers inside each state); PR row shown
WITH g AS (
  SELECT STATE, DATE_LAST_INSPECTION dli, PCT_MINORITY pm
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__EPA_PENALTY_GAP
  WHERE QUARTERS_WITH_NONCOMPLIANCE::NUMBER >= 8 AND LOWER(HAS_AIR_PROGRAM::STRING) <> 'true'
    AND (LOWER(HAS_WATER_PROGRAM::STRING) = 'true' OR LOWER(HAS_HAZWASTE_PROGRAM::STRING) = 'true')
    AND PCT_MINORITY IS NOT NULL
), s AS (
  SELECT STATE, COUNT_IF(pm >= 50) n_hi, COUNT_IF(pm >= 50 AND dli IS NULL) ni_hi,
         COUNT_IF(pm < 25) n_lo, COUNT_IF(pm < 25 AND dli IS NULL) ni_lo
  FROM g GROUP BY STATE
)
SELECT STATE, n_hi, ROUND(ni_hi / NULLIF(n_hi, 0) * 100, 1) pct_noinsp_hi, n_lo, ROUND(ni_lo / NULLIF(n_lo, 0) * 100, 1) pct_noinsp_lo,
  SUM(n_hi) OVER () tot_hi, SUM(ni_hi) OVER () tot_ni_hi, SUM(n_lo) OVER () tot_lo, SUM(ni_lo) OVER () tot_ni_lo
FROM s WHERE (n_hi >= 25 AND n_lo >= 25) OR STATE = 'PR'
ORDER BY n_hi DESC;

