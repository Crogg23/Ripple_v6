  SELECT f.ST, COUNT_IF(a.SETTLEMENT_ENTERED_DATE >= '2015-01-01' AND a.SETTLEMENT_ENTERED_DATE < '2027-01-01') AS FORMAL_15,
    COUNT_IF(a.SETTLEMENT_ENTERED_DATE IS NULL) AS FORMAL_NODATE, COUNT(*) AS FORMAL_ALL,
    SUM(CASE WHEN a.SETTLEMENT_ENTERED_DATE >= '2015-01-01' THEN TRY_TO_DOUBLE(TO_VARCHAR(a.PENALTY_AMOUNT)) END) AS PEN_15,
    COUNT_IF(a.SETTLEMENT_ENTERED_DATE >= '2015-01-01' AND a.STATE_EPA_FLAG = 'E') AS FORMAL_15_BY_EPA
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ICIS_AIR_ICIS_AIR_FORMAL_ACTIONS a JOIN f USING (PGM_SYS_ID) GROUP BY 1),
ia AS (
  SELECT f.ST, COUNT(*) AS INFORMAL_15
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ICIS_AIR_ICIS_AIR_INFORMAL_ACTIONS i JOIN f USING (PGM_SYS_ID)
  WHERE i.ACHIEVED_DATE >= '2015-01-01' AND i.ACHIEVED_DATE < '2027-01-01' GROUP BY 1),
stk AS (
  SELECT f.ST, COUNT_IF(s.AIR_STACK_TEST_STATUS_CODE = 'PSS') AS ST_PASS, COUNT_IF(s.AIR_STACK_TEST_STATUS_CODE = 'FAI') AS ST_FAIL
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ICIS_AIR_ICIS_AIR_STACK_TESTS s JOIN f USING (PGM_SYS_ID)
  WHERE s.ACTUAL_END_DATE >= '2015-01-01' AND s.ACTUAL_END_DATE < '2027-01-01' GROUP BY 1),
vh AS (
  SELECT f.ST,
    COUNT_IF(v.ENF_RESPONSE_POLICY_CODE = 'HPV') AS HPV_15,
    COUNT_IF(v.ENF_RESPONSE_POLICY_CODE = 'HPV' AND v.HPV_RESOLVED_DATE IS NOT NULL) AS HPV_15_RESOLVED,
    COUNT_IF(v.ENF_RESPONSE_POLICY_CODE = 'HPV' AND v.HPV_RESOLVED_DATE IS NULL AND TRY_TO_DATE(TO_VARCHAR(v.HPV_DAYZERO_DATE)) < '2023-07-01') AS HPV_OPEN_3Y,
    MEDIAN(CASE WHEN v.ENF_RESPONSE_POLICY_CODE = 'HPV' THEN DATEDIFF(day, TRY_TO_DATE(TO_VARCHAR(v.HPV_DAYZERO_DATE)), TRY_TO_DATE(TO_VARCHAR(v.HPV_RESOLVED_DATE))) END) AS HPV_MED_DAYS_TO_RESOLVE,
    COUNT_IF(v.ENF_RESPONSE_POLICY_CODE = 'FRV') AS FRV_15
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ICIS_AIR_ICIS_AIR_VIOLATION_HISTORY v JOIN f USING (PGM_SYS_ID)
  WHERE TRY_TO_DATE(TO_VARCHAR(COALESCE(v.HPV_DAYZERO_DATE, v.EARLIEST_FRV_DETERM_DATE))) >= '2015-01-01' GROUP BY 1)
SELECT maj.ST, maj.OPR_MAJORS, maj.OPR_ALL, fa.FORMAL_15, fa.FORMAL_15_BY_EPA, fa.PEN_15, fa.FORMAL_NODATE, fa.FORMAL_ALL, ia.INFORMAL_15,
  stk.ST_PASS, stk.ST_FAIL, vh.HPV_15, vh.HPV_15_RESOLVED, vh.HPV_OPEN_3Y, vh.HPV_MED_DAYS_TO_RESOLVE, vh.FRV_15
FROM maj LEFT JOIN fa USING (ST) LEFT JOIN ia USING (ST) LEFT JOIN stk USING (ST) LEFT JOIN vh USING (ST)
WHERE maj.OPR_MAJORS > 0 ORDER BY maj.OPR_MAJORS DESC;

-- [20] FCES_PCES: are the stale majors alive? last stack test, informal, formal, violation, emissions report year (2021+) and ECHO status for every operating major
WITH f AS (
