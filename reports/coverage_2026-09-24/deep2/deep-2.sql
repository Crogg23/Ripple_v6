  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ICIS_AIR_ICIS_AIR_FACILITIES
  GROUP BY 1 HAVING ANY_VALUE(AIR_POLLUTANT_CLASS_CODE) = 'MAJ' AND ANY_VALUE(AIR_OPERATING_STATUS_CODE) = 'OPR'),
