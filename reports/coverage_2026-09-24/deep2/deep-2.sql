-- [13] STACK TESTS: every facility with a failed test 2015+, its retest passes, and its ICIS-Air enforcement since 2015
WITH st AS (
  SELECT PGM_SYS_ID, ACTIVITY_ID, ACTUAL_END_DATE AS D, COALESCE(POLLUTANT_CODES, '') AS POL, AIR_STACK_TEST_STATUS_CODE AS S
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ICIS_AIR_ICIS_AIR_STACK_TESTS
  WHERE ACTUAL_END_DATE >= '2015-01-01' AND ACTUAL_END_DATE < '2027-01-01'),
fails AS (SELECT * FROM st WHERE S = 'FAI'),
retest AS (
  SELECT f.ACTIVITY_ID, f.POL FROM fails f JOIN st p
    ON p.PGM_SYS_ID = f.PGM_SYS_ID AND p.POL = f.POL AND p.S = 'PSS' AND p.D > f.D AND p.D <= DATEADD(day, 180, f.D)
  GROUP BY 1, 2),
fac AS (
  SELECT st.PGM_SYS_ID,
    COUNT_IF(S = 'FAI') AS FAIL_ROWS, COUNT(DISTINCT CASE WHEN S = 'FAI' THEN st.ACTIVITY_ID END) AS FAIL_TESTS,
    COUNT(DISTINCT CASE WHEN S IN ('FAI','PSS') THEN st.ACTIVITY_ID END) AS PF_TESTS,
    COUNT_IF(S = 'FAI' AND r.ACTIVITY_ID IS NOT NULL) AS FAIL_ROWS_RETEST_PASSED_180D,
    COUNT(DISTINCT CASE WHEN S = 'FAI' THEN YEAR(D) END) AS FAIL_YEARS,
    MIN(CASE WHEN S = 'FAI' THEN D END) AS FIRST_FAIL, MAX(CASE WHEN S = 'FAI' THEN D END) AS LAST_FAIL,
    LISTAGG(DISTINCT CASE WHEN S = 'FAI' THEN st.POL END, ' | ') WITHIN GROUP (ORDER BY CASE WHEN S = 'FAI' THEN st.POL END) AS FAIL_POLS
  FROM st LEFT JOIN retest r ON r.ACTIVITY_ID = st.ACTIVITY_ID AND r.POL = st.POL
  GROUP BY 1 HAVING COUNT_IF(S = 'FAI') > 0),
fa AS (
  SELECT PGM_SYS_ID, COUNT(*) AS FORMAL_2015, SUM(TRY_TO_DOUBLE(TO_VARCHAR(PENALTY_AMOUNT))) AS PEN_2015,
    MAX(SETTLEMENT_ENTERED_DATE) AS LAST_SETTLE
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ICIS_AIR_ICIS_AIR_FORMAL_ACTIONS
  WHERE SETTLEMENT_ENTERED_DATE >= '2015-01-01' AND SETTLEMENT_ENTERED_DATE < '2027-01-01' GROUP BY 1),
fa_all AS (
  SELECT PGM_SYS_ID, COUNT(*) AS FORMAL_ANY, COUNT_IF(SETTLEMENT_ENTERED_DATE IS NULL) AS FORMAL_NODATE
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ICIS_AIR_ICIS_AIR_FORMAL_ACTIONS GROUP BY 1),
inf AS (
  SELECT PGM_SYS_ID, COUNT(*) AS INFORMAL_2015
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ICIS_AIR_ICIS_AIR_INFORMAL_ACTIONS
  WHERE ACHIEVED_DATE >= '2015-01-01' AND ACHIEVED_DATE < '2027-01-01' GROUP BY 1),
vh AS (
  SELECT PGM_SYS_ID, COUNT(*) AS VIOL_2015, COUNT_IF(ENF_RESPONSE_POLICY_CODE = 'HPV') AS HPV_2015
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ICIS_AIR_ICIS_AIR_VIOLATION_HISTORY
  WHERE COALESCE(EARLIEST_FRV_DETERM_DATE, HPV_DAYZERO_DATE) >= '2015-01-01' GROUP BY 1),
f AS (
  SELECT PGM_SYS_ID, ANY_VALUE(REGISTRY_ID) AS REGISTRY_ID, ANY_VALUE(FACILITY_NAME) AS FACILITY_NAME, ANY_VALUE(CITY) AS CITY,
    ANY_VALUE(STATE) AS STATE, ANY_VALUE(AIR_POLLUTANT_CLASS_CODE) AS CLS, ANY_VALUE(AIR_OPERATING_STATUS_CODE) AS OPSTAT,
    ANY_VALUE(CURRENT_HPV) AS CURRENT_HPV, ANY_VALUE(NAICS_CODES) AS NAICS, COUNT(*) AS F_ROWS
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ICIS_AIR_ICIS_AIR_FACILITIES GROUP BY 1)
SELECT fac.*, f.REGISTRY_ID, f.FACILITY_NAME, f.CITY, f.STATE, f.CLS, f.OPSTAT, f.CURRENT_HPV, f.NAICS, f.F_ROWS,
  COALESCE(fa.FORMAL_2015, 0) AS FORMAL_2015, COALESCE(fa.PEN_2015, 0) AS PEN_2015, fa.LAST_SETTLE,
  COALESCE(fa_all.FORMAL_ANY, 0) AS FORMAL_ANY, COALESCE(fa_all.FORMAL_NODATE, 0) AS FORMAL_NODATE,
  COALESCE(inf.INFORMAL_2015, 0) AS INFORMAL_2015, COALESCE(vh.VIOL_2015, 0) AS VIOL_2015, COALESCE(vh.HPV_2015, 0) AS HPV_2015
FROM fac LEFT JOIN f USING (PGM_SYS_ID) LEFT JOIN fa USING (PGM_SYS_ID) LEFT JOIN fa_all USING (PGM_SYS_ID)
LEFT JOIN inf USING (PGM_SYS_ID) LEFT JOIN vh USING (PGM_SYS_ID)
ORDER BY fac.FAIL_TESTS DESC;

