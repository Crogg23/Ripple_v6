  ec.IS_ACTIVE, ec.DATE_LAST_INSPECTION, ec.COMPLIANCE_STATUS
FROM f LEFT JOIN stk USING (PGM_SYS_ID) LEFT JOIN inf USING (PGM_SYS_ID) LEFT JOIN fa USING (PGM_SYS_ID) LEFT JOIN vh USING (PGM_SYS_ID)
LEFT JOIN em ON em.REG = TO_VARCHAR(f.REGISTRY_ID) LEFT JOIN ec ON ec.REG = TO_VARCHAR(f.REGISTRY_ID);

