-- [16] AIR EMISSIONS: TRI vs EIS on the same facility, pollutant and year (2017 and 2020, the only overlap years)
WITH t AS (
  SELECT TO_VARCHAR(REGISTRY_ID) AS REG, REPORTING_YEAR AS Y, UPPER(POLLUTANT_NAME) AS POL, SUM(TRY_TO_DOUBLE(ANNUAL_EMISSION)) AS V
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_AIR_EMISSIONS_POLL_RPT_COMBINED_EMISSIONS
  WHERE PGM_SYS_ACRNM = 'TRIS' AND REPORTING_YEAR IN (2017, 2020) AND UNIT_OF_MEASURE = 'Pounds' GROUP BY 1, 2, 3),
e AS (
  SELECT TO_VARCHAR(REGISTRY_ID) AS REG, REPORTING_YEAR AS Y, UPPER(POLLUTANT_NAME) AS POL, SUM(TRY_TO_DOUBLE(ANNUAL_EMISSION)) AS EV
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_AIR_EMISSIONS_POLL_RPT_COMBINED_EMISSIONS
  WHERE PGM_SYS_ACRNM = 'EIS' AND REPORTING_YEAR IN (2017, 2020) AND UNIT_OF_MEASURE = 'Pounds' GROUP BY 1, 2, 3),
tr AS (SELECT POL, COUNT(*) AS TRI_ROWS, COUNT(DISTINCT REG) AS TRI_FACS FROM t GROUP BY 1),
p AS (SELECT t.REG, t.Y, t.POL, t.V, e.EV FROM t JOIN e ON e.REG = t.REG AND e.Y = t.Y AND e.POL = t.POL)
SELECT p.POL, ANY_VALUE(tr.TRI_ROWS) AS TRI_ROWS, ANY_VALUE(tr.TRI_FACS) AS TRI_FACS, COUNT(*) AS PAIRS,
  COUNT_IF(V > 0 AND EV > 0) AS BOTH_POS,
  COUNT_IF(V > 0 AND EV > 0 AND V / EV >= 10) AS TRI_10X_HIGHER, COUNT_IF(V > 0 AND EV > 0 AND EV / V >= 10) AS EIS_10X_HIGHER,
  COUNT_IF(V = 0 AND EV > 0) AS TRI_ZERO_EIS_POS, COUNT_IF(EV = 0 AND V > 0) AS EIS_ZERO_TRI_POS,
  SUM(V) AS TRI_LB, SUM(EV) AS EIS_LB, MEDIAN(CASE WHEN V > 0 AND EV > 0 THEN V / EV END) AS MED_TRI_OVER_EIS
FROM p JOIN tr ON tr.POL = p.POL GROUP BY p.POL ORDER BY PAIRS DESC;

