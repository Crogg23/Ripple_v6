-- [19] ICIS-Air state roll-up since 2015: operating majors, formal and informal actions, stack tests, HPV violations and how many got resolved
WITH f AS (
  SELECT PGM_SYS_ID, ANY_VALUE(STATE) AS ST, ANY_VALUE(AIR_POLLUTANT_CLASS_CODE) AS CLS, ANY_VALUE(AIR_OPERATING_STATUS_CODE) AS OP
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ICIS_AIR_ICIS_AIR_FACILITIES GROUP BY 1),
maj AS (SELECT ST, COUNT_IF(CLS = 'MAJ' AND OP = 'OPR') AS OPR_MAJORS, COUNT_IF(OP = 'OPR') AS OPR_ALL FROM f GROUP BY 1),
