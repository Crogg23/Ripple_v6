  WHERE cls = 'work' AND alive = 1 GROUP BY 1,2 QUALIFY ROW_NUMBER() OVER (ORDER BY SUM(IFF(done IS NULL,1,0)) DESC) <= 20)
SELECT part, label, n, unmet, unmet_alive::string unmet_alive, nm, ft FROM descs
UNION ALL SELECT part, label, n, unmet, unmet_alive::string, nm, ft FROM tot
UNION ALL SELECT * FROM tops
ORDER BY part, unmet DESC;

