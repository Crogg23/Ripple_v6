-- [4] CS and PS: value profile of coded columns, event-id repeats, states
WITH cs AS (SELECT * FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_CS_VIOLATIONS),
ps AS (SELECT * FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_PS_VIOLATIONS),
p AS (
  SELECT 'CS' tb, 'vcode' col, VIOLATION_CODE||' | '||VIOLATION_DESC v, COUNT(*) n FROM cs GROUP BY 3
  UNION ALL SELECT 'CS','event', SCHEDULE_EVENT_CODE||' | '||SCHEDULE_EVENT_DESC, COUNT(*) FROM cs GROUP BY 3
  UNION ALL SELECT 'CS','rnc_det', RNC_DETECTION_CODE||' | '||RNC_DETECTION_DESC, COUNT(*) FROM cs GROUP BY 3
  UNION ALL SELECT 'CS','rnc_res', RNC_RESOLUTION_CODE||' | '||RNC_RESOLUTION_DESC, COUNT(*) FROM cs GROUP BY 3
  UNION ALL SELECT 'CS','actual_null', IFF(ACTUAL_DATE IS NULL,'null','filled'), COUNT(*) FROM cs GROUP BY 3
  UNION ALL SELECT 'CS','sched_nmbr', COMP_SCHEDULE_NMBR::string, COUNT(*) FROM cs GROUP BY 3
  UNION ALL SELECT 'CS','state', LEFT(NPDES_ID,2), COUNT(*) FROM cs GROUP BY 3
  UNION ALL SELECT 'CS','events_per_eventid', c::string, COUNT(*) FROM (SELECT COMP_SCHEDULE_EVENT_ID, COUNT(*) c FROM cs GROUP BY 1) GROUP BY 3
  UNION ALL SELECT 'PS','vcode', VIOLATION_CODE||' | '||VIOLATION_DESC, COUNT(*) FROM ps GROUP BY 3
  UNION ALL SELECT 'PS','event', SCHEDULE_EVENT_CODE||' | '||SCHEDULE_EVENT_DESC, COUNT(*) FROM ps GROUP BY 3
  UNION ALL SELECT 'PS','rnc_det', RNC_DETECTION_CODE||' | '||RNC_DETECTION_DESC, COUNT(*) FROM ps GROUP BY 3
  UNION ALL SELECT 'PS','rnc_res', RNC_RESOLUTION_CODE||' | '||RNC_RESOLUTION_DESC, COUNT(*) FROM ps GROUP BY 3
  UNION ALL SELECT 'PS','actual_null', IFF(ACTUAL_DATE IS NULL,'null','filled'), COUNT(*) FROM ps GROUP BY 3
  UNION ALL SELECT 'PS','state', LEFT(NPDES_ID,2), COUNT(*) FROM ps GROUP BY 3
  UNION ALL SELECT 'PS','events_per_eventid', c::string, COUNT(*) FROM (SELECT PERM_SCHEDULE_EVENT_ID, COUNT(*) c FROM ps GROUP BY 1) GROUP BY 3
)
SELECT tb, col, v, n FROM p QUALIFY ROW_NUMBER() OVER (PARTITION BY tb, col ORDER BY n DESC) <= 14 ORDER BY tb, col, n DESC;

-- [5] SE, QNCR, RCRA: value profile; QNCR letter vs any-violation share; RCRA hit rate by agency and type; RCRA duplicate check
WITH se AS (SELECT * FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_SE_VIOLATIONS),
q AS (SELECT HLRNC, YEARQTR,
        IFF(TRY_TO_NUMBER(NUME90_Q)>0 OR TRY_TO_NUMBER(NUMCVDT)>0 OR TRY_TO_NUMBER(NUMSVCD)>0 OR TRY_TO_NUMBER(NUMPSCH)>0 OR TRY_TO_NUMBER(NUMD8090_Q)>0,1,0) anyv,
        IFF(TRY_TO_NUMBER(NUME90_Q) IS NULL OR TRY_TO_NUMBER(NUMD8090_Q) IS NULL,1,0) nonnum
      FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_QNCR_HISTORY),
r AS (SELECT * FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_RCRA_EVALUATIONS),
p AS (
  SELECT 'SE' tb, 'vcode' col, VIOLATION_CODE||' | '||VIOLATION_DESC v, COUNT(*) n, NULL x FROM se GROUP BY 3
  UNION ALL SELECT 'SE','agency', SINGLE_EVENT_AGENCY_TYPE_CODE, COUNT(*), NULL FROM se GROUP BY 3
  UNION ALL SELECT 'SE','rnc_det', RNC_DETECTION_CODE||' | '||RNC_DETECTION_DESC, COUNT(*), NULL FROM se GROUP BY 3
  UNION ALL SELECT 'SE','rnc_res', RNC_RESOLUTION_CODE||' | '||RNC_RESOLUTION_DESC, COUNT(*), NULL FROM se GROUP BY 3
  UNION ALL SELECT 'SE','state', LEFT(NPDES_ID,2), COUNT(*), NULL FROM se GROUP BY 3
  UNION ALL SELECT 'SE','year', YEAR(SINGLE_EVENT_VIOLATION_DATE)::string, COUNT(*), NULL FROM se GROUP BY 3
  UNION ALL SELECT 'SE','comment', IFF(NULLIF(TRIM(SINGLE_EVENT_VIOLATION_COMMENT),'') IS NULL,'blank','filled'), COUNT(*), NULL FROM se GROUP BY 3
  UNION ALL SELECT 'QN','hlrnc', HLRNC, COUNT(*), ROUND(AVG(anyv),3) FROM q GROUP BY 3
  UNION ALL SELECT 'QN','future_qtr', IFF(YEARQTR::int > 20263,'after 2026Q3','ok'), COUNT(*), ROUND(AVG(anyv),3) FROM q GROUP BY 3
  UNION ALL SELECT 'QN','nonnumeric', nonnum::string, COUNT(*), NULL FROM q GROUP BY 3
  UNION ALL SELECT 'QN','year', LEFT(YEARQTR,4), COUNT(*), ROUND(AVG(anyv),3) FROM q GROUP BY 3
  UNION ALL SELECT 'RC','agency', EVALUATION_AGENCY, COUNT(*), ROUND(AVG(IFF(FOUND_VIOLATION='Y',1,0)),3) FROM r GROUP BY 3
  UNION ALL SELECT 'RC','found', FOUND_VIOLATION, COUNT(*), NULL FROM r GROUP BY 3
  UNION ALL SELECT 'RC','etype', EVALUATION_TYPE||' | '||EVALUATION_DESC, COUNT(*), ROUND(AVG(IFF(FOUND_VIOLATION='Y',1,0)),3) FROM r GROUP BY 3
  UNION ALL SELECT 'RC','baddate', IFF(YEAR(EVALUATION_START_DATE)<1980,'pre-1980','ok'), COUNT(*), NULL FROM r GROUP BY 3
  UNION ALL SELECT 'RC','dupes', c::string, COUNT(*), NULL FROM (SELECT ID_NUMBER, EVALUATION_START_DATE, EVALUATION_TYPE, EVALUATION_AGENCY, COUNT(*) c FROM r GROUP BY 1,2,3,4) GROUP BY 3
)
SELECT tb, col, v, n, x FROM p QUALIFY ROW_NUMBER() OVER (PARTITION BY tb, col ORDER BY IFF(col='year', TRY_TO_NUMBER(v), n) DESC) <= IFF(col='year', 60, 16) ORDER BY tb, col, IFF(col='year', TRY_TO_NUMBER(v), n) DESC;

-- [6] CS: never-met milestones per permit (dedup by event id), still-alive permits, names, formal actions
WITH ev AS (
  SELECT NPDES_ID, COMP_SCHEDULE_EVENT_ID, MAX(SCHEDULE_EVENT_CODE) code, MIN(SCHEDULE_DATE) due, MAX(ACTUAL_DATE) done
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_CS_VIOLATIONS GROUP BY 1,2),
f AS (
  SELECT NPDES_ID, COUNT(*) ms, SUM(IFF(done IS NULL,1,0)) unmet,
    SUM(IFF(done IS NULL AND code IN ('CS015','CS016','CS017','CS031','CS022'),1,0)) unmet_work,
    SUM(IFF(done IS NULL AND code = 'CS001',1,0)) unmet_pay,
    MIN(IFF(done IS NULL, due, NULL)) oldest_unmet,
    MAX(due) last_due
  FROM ev GROUP BY 1),
qa AS (
  SELECT NPDES_ID, MAX(TRY_TO_NUMBER(YEARQTR)) lastq,
    SUM(IFF(TRY_TO_NUMBER(YEARQTR) BETWEEN 20211 AND 20254 AND TRY_TO_NUMBER(NUME90_Q) > 0,1,0)) eff_q_21_25
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_QNCR_HISTORY
  WHERE TRY_TO_NUMBER(YEARQTR) <= 20263 GROUP BY 1),
fe AS (
  SELECT NPDES_ID, COUNT(*) acts, SUM(COALESCE(FED_PENALTY_ASSESSED_AMT,0) + COALESCE(STATE_LOCAL_PENALTY_AMT,0)) pen
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_FORMAL_ENFORCEMENT_ACTIONS GROUP BY 1),
j AS (
  SELECT f.*, fac.FACILITY_NAME, fac.CITY, fac.FACILITY_TYPE_CODE ftype, qa.lastq, qa.eff_q_21_25, fe.acts, fe.pen,
    IFF(fac.NPDES_ID IS NULL,0,1) in_fac, IFF(fe.NPDES_ID IS NULL,0,1) in_fe, IFF(qa.lastq >= 20251,1,0) alive
  FROM f
  LEFT JOIN LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_ICIS_FACILITIES fac ON fac.NPDES_ID = f.NPDES_ID
  LEFT JOIN qa ON qa.NPDES_ID = f.NPDES_ID
  LEFT JOIN fe ON fe.NPDES_ID = f.NPDES_ID)
SELECT * FROM (
  SELECT 0 k, 'TOTAL' NPDES_ID, SUM(ms) ms, SUM(unmet) unmet, SUM(unmet_work) unmet_work, SUM(unmet_pay) unmet_pay,
    MIN(oldest_unmet) oldest_unmet, COUNT(*)::string last_due,
    'permits, in_fac=' || SUM(in_fac) || ' in_fe=' || SUM(in_fe) || ' alive=' || SUM(alive) FACILITY_NAME,
    'unmet on alive=' || SUM(IFF(alive=1, unmet, 0)) || ' work on alive=' || SUM(IFF(alive=1, unmet_work, 0)) || ' pay on alive=' || SUM(IFF(alive=1, unmet_pay, 0)) CITY,
    NULL ftype, NULL lastq, NULL eff_q_21_25, NULL acts, NULL pen
  FROM j
  UNION ALL
  SELECT * FROM (SELECT 1, NPDES_ID, ms, unmet, unmet_work, unmet_pay, oldest_unmet, last_due::string, FACILITY_NAME, CITY, ftype, lastq, eff_q_21_25, acts, pen
    FROM j WHERE alive = 1 ORDER BY unmet_work DESC, unmet DESC LIMIT 25)
) ORDER BY k, unmet_work DESC, unmet DESC;

-- [7] PS: never-met permit milestones due 2016-2025H1, work vs paperwork by keyword, top alive permits on work
