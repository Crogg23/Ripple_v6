UNION ALL
SELECT * FROM (SELECT NPDES_ID, n, n_dt_code, sso, byp, yrs, first_dt, last_dt, FACILITY_NAME, CITY, ft, acts, pen, last_act, rk_in_type, peers, peer_median, top_code
  FROM j ORDER BY n DESC LIMIT 25);

-- [10] QNCR: permits with 36+ of 40 quarters 2016-2025, bucketed by effluent-violation quarters vs formal/informal action share; chronic with no formal action
WITH q AS (
  SELECT NPDES_ID, COUNT(DISTINCT YEARQTR) qtrs,
    COUNT(DISTINCT IFF(TRY_TO_NUMBER(NUME90_Q) > 0, YEARQTR, NULL)) eff_q,
    SUM(TRY_TO_NUMBER(NUME90_Q)) eff_n,
    COUNT(DISTINCT IFF(TRY_TO_NUMBER(NUME90_Q) > 0 OR TRY_TO_NUMBER(NUMCVDT) > 0 OR TRY_TO_NUMBER(NUMSVCD) > 0 OR TRY_TO_NUMBER(NUMPSCH) > 0 OR TRY_TO_NUMBER(NUMD8090_Q) > 0, YEARQTR, NULL)) any_q,
    COUNT(DISTINCT IFF(HLRNC IN ('S','E','X','T'), YEARQTR, NULL)) sext_q
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_QNCR_HISTORY
  WHERE TRY_TO_NUMBER(YEARQTR) BETWEEN 20161 AND 20254 GROUP BY 1),
fe AS (
  SELECT NPDES_ID, COUNT(*) fe_all, COUNT(IFF(SETTLEMENT_ENTERED_DATE >= '2016-01-01', 1, NULL)) fe_win,
    SUM(IFF(SETTLEMENT_ENTERED_DATE >= '2016-01-01', COALESCE(FED_PENALTY_ASSESSED_AMT,0) + COALESCE(STATE_LOCAL_PENALTY_AMT,0), 0)) pen_win
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_FORMAL_ENFORCEMENT_ACTIONS GROUP BY 1),
ie AS (
  SELECT NPDES_ID, COUNT(IFF(ACHIEVED_DATE BETWEEN '2016-01-01' AND '2025-12-31', 1, NULL)) ie_win
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_INFORMAL_ENFORCEMENT_ACTIONS GROUP BY 1),
j AS (
  SELECT q.*, COALESCE(fe.fe_all,0) fe_all, COALESCE(fe.fe_win,0) fe_win, COALESCE(fe.pen_win,0) pen_win, COALESCE(ie.ie_win,0) ie_win,
    fac.FACILITY_NAME, fac.CITY, fac.FACILITY_TYPE_CODE ft,
    CASE WHEN eff_q = 0 THEN '0' WHEN eff_q < 10 THEN '01-09' WHEN eff_q < 20 THEN '10-19' WHEN eff_q < 30 THEN '20-29' WHEN eff_q < 36 THEN '30-35' ELSE '36-40' END bkt
  FROM q LEFT JOIN fe ON fe.NPDES_ID = q.NPDES_ID LEFT JOIN ie ON ie.NPDES_ID = q.NPDES_ID
  LEFT JOIN LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_ICIS_FACILITIES fac ON fac.NPDES_ID = q.NPDES_ID
  WHERE q.qtrs >= 36)
SELECT 'A_bucket' part, bkt label, COUNT(*) permits, ROUND(AVG(IFF(fe_win > 0,1,0)),3) sh_formal, ROUND(AVG(IFF(ie_win > 0,1,0)),3) sh_informal,
  SUM(IFF(fe_win = 0 AND ie_win = 0,1,0)) no_action, ROUND(AVG(sext_q),1) avg_sext_q, SUM(IFF(ft = 'POT' OR ft = 'MWD' OR ft = 'CTG' OR ft = 'CNG',1,0))::string muni_types, NULL nm, NULL c
