-- [9] SE: top permits by single events since 2015, SSO and bypass counts, dup check, names, formal actions since 2015, rank within facility type
WITH se AS (
  SELECT NPDES_ID, SINGLE_EVENT_VIOLATION_DATE dt, VIOLATION_CODE, VIOLATION_DESC,
    IFF(VIOLATION_DESC ILIKE '%SSO%' OR VIOLATION_DESC ILIKE '%overflow%' OR VIOLATION_DESC ILIKE '%CSO%', 1, 0) sso,
    IFF(VIOLATION_DESC ILIKE '%bypass%', 1, 0) byp,
    SINGLE_EVENT_AGENCY_TYPE_CODE ag
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_SE_VIOLATIONS
  WHERE SINGLE_EVENT_VIOLATION_DATE >= '2015-01-01'),
p AS (
  SELECT NPDES_ID, COUNT(*) n, COUNT(DISTINCT dt, VIOLATION_CODE) n_dt_code, SUM(sso) sso, SUM(byp) byp,
    COUNT(DISTINCT YEAR(dt)) yrs, MIN(dt) first_dt, MAX(dt) last_dt,
    MAX_BY(VIOLATION_DESC, 1) any_desc, MODE(VIOLATION_CODE) top_code, MODE(ag) top_ag
  FROM se GROUP BY 1),
fe AS (
  SELECT NPDES_ID, COUNT(*) acts, SUM(COALESCE(FED_PENALTY_ASSESSED_AMT,0) + COALESCE(STATE_LOCAL_PENALTY_AMT,0)) pen, MAX(SETTLEMENT_ENTERED_DATE) last_act
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_FORMAL_ENFORCEMENT_ACTIONS
  WHERE SETTLEMENT_ENTERED_DATE >= '2015-01-01' GROUP BY 1),
j AS (
  SELECT p.*, fac.FACILITY_NAME, fac.CITY, fac.FACILITY_TYPE_CODE ft, fe.acts, fe.pen, fe.last_act,
    RANK() OVER (PARTITION BY fac.FACILITY_TYPE_CODE ORDER BY p.n DESC) rk_in_type,
    COUNT(*) OVER (PARTITION BY fac.FACILITY_TYPE_CODE) peers,
    MEDIAN(p.n) OVER (PARTITION BY fac.FACILITY_TYPE_CODE) peer_median
  FROM p
  LEFT JOIN LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_ICIS_FACILITIES fac ON fac.NPDES_ID = p.NPDES_ID
  LEFT JOIN fe ON fe.NPDES_ID = p.NPDES_ID)
SELECT 'TOTAL' NPDES_ID, SUM(n) n, SUM(n_dt_code) n_dt_code, SUM(sso) sso, SUM(byp) byp, COUNT(*) yrs, NULL first_dt, NULL last_dt,
  'permits with fac name=' || COUNT(FACILITY_NAME) || ', with formal action since 2015=' || COUNT(acts) FACILITY_NAME,
  'SSO events at permits w/ formal action=' || SUM(IFF(acts IS NOT NULL, sso, 0)) CITY, NULL ft, NULL acts, NULL pen, NULL last_act, NULL rk_in_type, NULL peers, NULL peer_median, NULL top_code
