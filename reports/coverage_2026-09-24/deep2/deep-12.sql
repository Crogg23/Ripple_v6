  SELECT DISTRICT, OFFICE, DOCKET, FILE_DATE, TAPE_YEAR, NATURE_OF_SUIT, DISPOSITION, TERM_DATE, JUDGMENT, AMOUNT_RECEIVED,
         UPPER(TRIM(PLAINTIFF)) p
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_FJC_IDB_CIVIL
