-- [15] FJC top plaintiffs since 2015, deduped to one row per case DUMP: fjc_top  (ok)
WITH c AS (
  SELECT DISTRICT, OFFICE, DOCKET, FILE_DATE, TAPE_YEAR, NATURE_OF_SUIT, DISPOSITION, TERM_DATE,
         UPPER(TRIM(PLAINTIFF)) p
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_FJC_IDB_CIVIL
  WHERE FILE_DATE >= '2015-01-01'
  QUALIFY ROW_NUMBER() OVER (PARTITION BY DISTRICT, OFFICE, DOCKET, FILE_DATE ORDER BY IFF(TAPE_YEAR=2099,0,1) DESC, TAPE_YEAR DESC) = 1
)
SELECT p, COUNT(*) cases, MODE(NATURE_OF_SUIT) top_nos, ROUND(AVG(IFF(NATURE_OF_SUIT = MODE_NOS,1,0)),2) share_top_nos,
       COUNT(DISTINCT DISTRICT) districts, MIN(FILE_DATE) first_f, MAX(FILE_DATE) last_f,
       ROUND(AVG(IFF(DISPOSITION='12',1,0)),3) d12, ROUND(AVG(IFF(DISPOSITION='13',1,0)),3) d13,
       ROUND(AVG(IFF(DISPOSITION='2',1,0)),3) d2, ROUND(AVG(IFF(DISPOSITION='4',1,0)),3) d4,
       ROUND(AVG(IFF(TERM_DATE IS NULL,1,0)),3) open_share,
       MEDIAN(DATEDIFF('day', FILE_DATE, TERM_DATE)) med_days
FROM (SELECT c.*, MODE(NATURE_OF_SUIT) OVER (PARTITION BY p) MODE_NOS FROM c)
GROUP BY p ORDER BY cases DESC LIMIT 300;

