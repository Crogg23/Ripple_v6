-- [17] arcos_outlier_products
SELECT BUYER_DEA_NO, ANY_VALUE(BUYER_NAME) AS NAME, ANY_VALUE(BUYER_ADDL) AS ADDL, PRODUCT_NAME, DOSAGE_STRENGTH, SUM(DOSAGE_UNITS) AS DU, COUNT(*) AS N
FROM (SELECT A.*, NULL AS BUYER_ADDL FROM LIBRARY_MARTS.HEALTH.HEALTH__FED_DEA_ARCOS A
      WHERE TRANSACTION_CODE = 'S' AND DRUG_NAME = 'OXYCODONE'
        AND BUYER_DEA_NO IN ('BF7000526','BD9670058','BT6419053','BB8426264','BB7675400','BC9843132','AD2366183','AN1556337'))
GROUP BY BUYER_DEA_NO, PRODUCT_NAME, DOSAGE_STRENGTH
QUALIFY ROW_NUMBER() OVER (PARTITION BY BUYER_DEA_NO ORDER BY SUM(DOSAGE_UNITS) DESC) <= 4
ORDER BY BUYER_DEA_NO, DU DESC;

