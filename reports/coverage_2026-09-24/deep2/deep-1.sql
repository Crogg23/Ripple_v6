-- Q21: REPEX ultimate-parent reason shares by legal-address country and by managing registration office (LOU); denominator = every LEI in GLEIF for that group; groups with 10K+ LEIs
WITH r AS (SELECT LEI, MAX(EXCEPTION_REASON_1) rsn FROM LIBRARY_MARTS.ECONOMICS.ECONOMICS__INTL_GLEIF_REPEX WHERE EXCEPTION_CATEGORY LIKE 'ULTIMATE%' GROUP BY LEI),
g AS (SELECT LEI, ENTITY_LEGALADDRESS_COUNTRY ctry, REGISTRATION_MANAGINGLOU lou, REGISTRATION_REGISTRATIONSTATUS st FROM LIBRARY_MARTS.ECONOMICS.ECONOMICS__INTL_GLEIF),
j AS (SELECT g.*, r.rsn, IFF(r.rsn IN ('NON_PUBLIC','CONSENT_NOT_OBTAINED','BINDING_LEGAL_COMMITMENTS','DETRIMENT_NOT_EXCLUDED','DISCLOSURE_DETRIMENTAL','LEGAL_OBSTACLES'),1,0) np FROM g LEFT JOIN r ON g.LEI=r.LEI),
agg AS (
  SELECT IFF(GROUPING(ctry)=0,'CTRY','LOU') lvl, COALESCE(ctry, lou) k, COUNT(*) leis, COUNT_IF(st='ISSUED') issued,
    ROUND(AVG(np),4) np_share, SUM(np) np_n, ROUND(AVG(IFF(rsn='NO_LEI',1,0)),4) nolei_share, ROUND(AVG(IFF(rsn='NATURAL_PERSONS',1,0)),3) natp_share,
    ROUND(AVG(IFF(rsn='NO_KNOWN_PERSON',1,0)),3) nokp_share, ROUND(AVG(IFF(rsn IS NULL,1,0)),3) no_exception_share
  FROM j GROUP BY GROUPING SETS ((ctry),(lou)) HAVING COUNT(*)>=10000)
SELECT a.lvl, a.k, LEFT(n.ENTITY_LEGALNAME,40) lou_name, a.leis, a.issued, a.np_share, a.np_n, a.nolei_share, a.natp_share, a.nokp_share, a.no_exception_share
FROM agg a LEFT JOIN LIBRARY_MARTS.ECONOMICS.ECONOMICS__INTL_GLEIF n ON a.lvl='LOU' AND a.k=n.LEI
ORDER BY a.lvl, a.np_share DESC;

