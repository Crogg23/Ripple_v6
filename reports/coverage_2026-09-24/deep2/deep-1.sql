   WHEN REGEXP_LIKE(UPPER(nm), '.*(FOR GOVERNOR|FOR MAYOR|FOR ATTORNEY GENERAL|FOR STATE|FOR SENATE|FOR ASSEMBLY|FOR DELEGATE|FOR JUDGE|FOR JUSTICE|FOR SHERIFF|FOR COUNCIL|FOR DISTRICT|FOR SUPERVISOR|FOR COMMISSIONER|FOR TREASURER|FOR AUDITOR|FOR SECRETARY|FOR CONTROLLER|FOR HOUSE|FOR CONGRESS|FOR PRESIDENT| 20[0-9][0-9]).*') THEN 'candidate-named'
