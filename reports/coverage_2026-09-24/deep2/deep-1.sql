j AS (SELECT a.*, IFF(f.nk IS NOT NULL,1,0) name_in_fec FROM a LEFT JOIN f ON a.nk=f.nk)
SELECT 'TYPE '||idtype grp, NULL name, COUNT(*) advs, ROUND(SUM(spend)/1e6,1) spend_musd, COUNT_IF(spend>=1000000) advs_1m, ROUND(AVG(name_in_fec),3) name_land, NULL ids FROM j GROUP BY idtype
UNION ALL
SELECT * FROM (SELECT 'TOP_NOFEC', ADVERTISER_NAME, NULL, ROUND(spend/1e6,2), NULL, name_in_fec, LEFT(ids,40) FROM j WHERE idtype<>'FEC' ORDER BY spend DESC NULLS LAST LIMIT 22);

-- Q19: POLADS US ads started 2024: share of spend-range midpoint on one-gender ads, ZIP-targeted ads, narrow-age ads; top advertisers by one-gender midpoint spend
WITH u AS (
  SELECT ADVERTISER_NAME, (SPEND_RANGE_MIN_USD+SPEND_RANGE_MAX_USD)/2 mid,
    IFF(GENDER_TARGETING IN ('Male','Female'),1,0) one_g,
    IFF(REGEXP_COUNT(GEO_TARGETING_INCLUDED, '(^|,)[0-9]{5}(,|$)')>0,1,0) zip_t,
    IFF(AGE_TARGETING IS NOT NULL AND AGE_TARGETING<>'' AND REGEXP_COUNT(AGE_TARGETING, ',')<=1,1,0) narrow_age
  FROM LIBRARY_MARTS.EDUCATION.EDUCATION__FED_GOOGLE_POLADS_CREATIVE_STATS
  WHERE REGIONS='US' AND DATE_RANGE_START BETWEEN '2024-01-01' AND '2024-12-31')
SELECT 'ALL' grp, NULL adv, COUNT(*) ads, ROUND(SUM(mid)/1e6,1) mid_musd, ROUND(SUM(mid*one_g)/SUM(mid),3) one_g_share, ROUND(SUM(mid*zip_t)/SUM(mid),3) zip_share, ROUND(SUM(mid*narrow_age)/SUM(mid),3) narrow_age_share, SUM(zip_t) zip_ads FROM u
UNION ALL
SELECT * FROM (SELECT 'TOP_ONE_GENDER', ADVERTISER_NAME, SUM(one_g), ROUND(SUM(mid*one_g)/1e6,2), ROUND(SUM(mid*one_g)/SUM(mid),3), ROUND(SUM(mid*zip_t)/SUM(mid),3), ROUND(SUM(mid*narrow_age)/SUM(mid),3), SUM(zip_t)
  FROM u GROUP BY ADVERTISER_NAME ORDER BY SUM(mid*one_g) DESC LIMIT 12);

