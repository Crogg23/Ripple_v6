-- Q18: POLADS US advertisers by the ID they gave Google (FEC ID vs EIN only vs other), exact spend, and exact-name land rate in the FEC committee list; then top 20 spenders with no FEC ID
WITH a AS (
  SELECT ADVERTISER_ID, ADVERTISER_NAME, TRY_TO_NUMBER(SPEND_USD::STRING) spend, PUBLIC_IDS_LIST ids,
    CASE WHEN PUBLIC_IDS_LIST ILIKE '%FEC ID%' THEN 'FEC' WHEN PUBLIC_IDS_LIST ILIKE '%EIN ID%' THEN 'EIN_ONLY'
         WHEN PUBLIC_IDS_LIST IS NULL OR TRIM(PUBLIC_IDS_LIST)='' THEN 'BLANK' ELSE 'OTHER' END idtype,
    REGEXP_REPLACE(UPPER(ADVERTISER_NAME),'[^A-Z0-9]','') nk
  FROM LIBRARY_MARTS.EDUCATION.EDUCATION__FED_GOOGLE_POLADS_ADVERTISER_STATS WHERE REGIONS='US'),
