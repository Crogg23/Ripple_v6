  FROM LIBRARY_MARTS.EDUCATION.EDUCATION__FED_GOOGLE_POLADS_ADVERTISER_STATS WHERE REGIONS='US' AND COALESCE(PUBLIC_IDS_LIST,'') NOT ILIKE '%FEC ID%'),
