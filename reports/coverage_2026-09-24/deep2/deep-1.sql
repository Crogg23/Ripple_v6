-- Q11: SALES home price per kWh, full-service (Part A, Bundled, reported rows only), 10K+ home customers, against state peers (Part A utilities with 1K+ home customers)
WITH b AS (
  SELECT UTILITY_NUMBER, UTILITY_NAME, STATE, OWNERSHIP, RESIDENTIAL_CUSTOMERS rc, RESIDENTIAL_SALES_MWH mwh, RESIDENTIAL_REVENUES_THOUSAND_DOLLARS rev_k,
    RESIDENTIAL_REVENUES_THOUSAND_DOLLARS*100/NULLIF(RESIDENTIAL_SALES_MWH,0) cents,
    RESIDENTIAL_REVENUES_THOUSAND_DOLLARS*1000/NULLIF(RESIDENTIAL_CUSTOMERS,0)/12 bill_mo,
    RESIDENTIAL_SALES_MWH*1000/NULLIF(RESIDENTIAL_CUSTOMERS,0)/12 kwh_mo
  FROM LIBRARY_MARTS.ENERGY.ENERGY__FED_EIA861_SALES_ULT_CUST
  WHERE PART='A' AND SERVICE_TYPE='Bundled' AND DATA_TYPE='O' AND RESIDENTIAL_CUSTOMERS>=1000 AND RESIDENTIAL_SALES_MWH>0),
s AS (SELECT *, MEDIAN(cents) OVER (PARTITION BY STATE) st_med, COUNT(*) OVER (PARTITION BY STATE) st_n,
  MEDIAN(bill_mo) OVER (PARTITION BY STATE) st_bill,
  MEDIAN(cents) OVER (PARTITION BY STATE, OWNERSHIP) st_own_med, COUNT(*) OVER (PARTITION BY STATE, OWNERSHIP) st_own_n FROM b)
SELECT UTILITY_NAME, STATE, OWNERSHIP, rc, ROUND(cents,1) cents, ROUND(st_med,1) st_med, st_n, ROUND(cents/st_med,2) x_state,
  ROUND(st_own_med,1) st_own_med, st_own_n, ROUND(bill_mo) bill_mo, ROUND(st_bill) st_bill, ROUND(kwh_mo) kwh_mo, ROUND(rev_k/1000,1) rev_musd
FROM s WHERE rc>=10000 ORDER BY cents/st_med DESC LIMIT 30;

