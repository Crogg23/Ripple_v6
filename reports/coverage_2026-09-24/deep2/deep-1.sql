  SELECT *, IFF(STATE IN ('GA','NC','SC','FL','TN','VA'),'HELENE6','REST') AS zone
  FROM LIBRARY_MARTS.ENERGY.ENERGY__FED_EIA861_RELIABILITY)
SELECT 'own:'||COALESCE(OWNERSHIP,'?') grp, COUNT(*) n, COUNT(IEEE_SAIDI_WITH_MED_MINUTES) with_filled, COUNT(IEEE_SAIDI_WITHOUT_MED_MINUTES) wo_filled,
  COUNT_IF(IEEE_SAIDI_WITH_MED_MINUTES IS NULL AND OTHER_SAIDI_WITH_MED_MINUTES IS NOT NULL) other_only,
  COUNT_IF(IEEE_SAIDI_WITH_MED_MINUTES = 0) with_zero,
  COUNT_IF(IEEE_SAIDI_WITHOUT_MED_MINUTES > IEEE_SAIDI_WITH_MED_MINUTES) wo_gt_with,
  MEDIAN(IEEE_SAIDI_WITH_MED_MINUTES) med_with, MEDIAN(IEEE_SAIDI_WITHOUT_MED_MINUTES) med_wo,
  APPROX_PERCENTILE(IEEE_SAIDI_WITHOUT_MED_MINUTES,0.9) p90_wo,
  SUM(IEEE_NUMBER_OF_CUSTOMERS) cust,
  SUM(IEEE_SAIDI_WITH_MED_MINUTES*IEEE_NUMBER_OF_CUSTOMERS)/NULLIF(SUM(IFF(IEEE_SAIDI_WITH_MED_MINUTES IS NOT NULL,IEEE_NUMBER_OF_CUSTOMERS,0)),0) custwt_with,
  SUM(IEEE_SAIDI_WITHOUT_MED_MINUTES*IEEE_NUMBER_OF_CUSTOMERS)/NULLIF(SUM(IFF(IEEE_SAIDI_WITHOUT_MED_MINUTES IS NOT NULL,IEEE_NUMBER_OF_CUSTOMERS,0)),0) custwt_wo
FROM b GROUP BY 1
UNION ALL
SELECT 'zone:'||zone, COUNT(*), COUNT(IEEE_SAIDI_WITH_MED_MINUTES), COUNT(IEEE_SAIDI_WITHOUT_MED_MINUTES),
  COUNT_IF(IEEE_SAIDI_WITH_MED_MINUTES IS NULL AND OTHER_SAIDI_WITH_MED_MINUTES IS NOT NULL), COUNT_IF(IEEE_SAIDI_WITH_MED_MINUTES = 0),
  COUNT_IF(IEEE_SAIDI_WITHOUT_MED_MINUTES > IEEE_SAIDI_WITH_MED_MINUTES),
  MEDIAN(IEEE_SAIDI_WITH_MED_MINUTES), MEDIAN(IEEE_SAIDI_WITHOUT_MED_MINUTES), APPROX_PERCENTILE(IEEE_SAIDI_WITHOUT_MED_MINUTES,0.9),
