-- [15] Epstein snapshot: the 94 files not seen on the last crawl; renamed? wayback status? on DOJ page table?
WITH t AS (SELECT * FROM LIBRARY_MARTS.EPSTEIN.FCT_LIBRARY_SNAPSHOT),
mx AS (SELECT TO_DATE(MAX(LAST_OBSERVED_AT)) d FROM t),
gone AS (SELECT t.* FROM t, mx WHERE TO_DATE(t.LAST_OBSERVED_AT) < mx.d),
still AS (SELECT t.EFTA_FILE_NUMBER, t.FILE_URL FROM t, mx WHERE TO_DATE(t.LAST_OBSERVED_AT) = mx.d),
wb AS (
  SELECT w.ORIGINAL_URL, COUNT(*) caps, MIN(w.CAPTURED_AT) first_cap, MAX(w.CAPTURED_AT) last_cap,
         MAX_BY(w.STATUS_CODE, w.CAPTURED_AT) last_status,
         LISTAGG(DISTINCT w.STATUS_CODE, ',') statuses,
         COUNT(DISTINCT w.CONTENT_DIGEST) digests
  FROM LIBRARY_MARTS.OPEN_DATA.OPEN_DATA__XC_WAYBACK_DOJ_EPSTEIN w
  WHERE w.ORIGINAL_URL IN (SELECT FILE_URL FROM gone)
     OR REPLACE(w.ORIGINAL_URL, 'http://', 'https://') IN (SELECT FILE_URL FROM gone)
  GROUP BY 1
),
lib AS (SELECT DISTINCT COALESCE(RESOLVED_URL, HREF) u, FETCHED_AT_UTC FROM LIBRARY_MARTS.POLITICS.POLITICS__FED_DOJ_EPSTEIN_LIBRARY)
SELECT g.DATASET_NAME, g.FILE_URL, g.EFTA_FILE_NUMBER, TO_DATE(g.FIRST_OBSERVED_AT) first_seen, TO_DATE(g.LAST_OBSERVED_AT) last_seen, g.OBSERVATIONS,
       (SELECT COUNT(*) FROM still s WHERE s.EFTA_FILE_NUMBER = g.EFTA_FILE_NUMBER) same_efta_still_live,
       (SELECT MIN(s.FILE_URL) FROM still s WHERE s.EFTA_FILE_NUMBER = g.EFTA_FILE_NUMBER) live_url_same_efta,
       wb.caps, wb.first_cap, wb.last_cap, wb.last_status, wb.statuses, wb.digests,
       (SELECT COUNT(*) FROM lib WHERE lib.u = g.FILE_URL) on_doj_page_table
FROM gone g LEFT JOIN wb ON REPLACE(wb.ORIGINAL_URL, 'http://', 'https://') = g.FILE_URL
ORDER BY g.LAST_OBSERVED_AT, g.FILE_URL;

