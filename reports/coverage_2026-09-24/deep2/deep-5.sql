-- [12] PHMSA: operators ranked by unintentional release volume, incident count, deaths
WITH t AS (
  SELECT *, TRY_TO_DOUBLE(UNINTENTIONAL_RELEASE_VOLUME::string) uv
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_PHMSA_FLAGGED_INCIDENTS
), op AS (
  SELECT PHMSA_OPERATOR_ID, MAX_BY(OPERATOR_NAME, REPORT_RECEIVED_DATE) name, COUNT(*) incidents,
         COUNT(DISTINCT INCIDENT_YEAR) yrs, ROUND(SUM(uv)) mcf, ROUND(MAX(uv)) max_mcf,
         SUM(TOTAL_FATALITIES) deaths, SUM(TOTAL_INJURIES) inj,
         COUNT(IFF(uv >= 10000, 1, NULL)) n_10k_mcf,
         COUNT(IFF(INCIDENT_YEAR >= 2023, 1, NULL)) n_2023plus,
         ROUND(SUM(IFF(INCIDENT_YEAR >= 2023, uv, 0))) mcf_2023plus
  FROM t GROUP BY PHMSA_OPERATOR_ID
), tot AS (SELECT SUM(mcf) all_mcf, SUM(incidents) all_inc, MEDIAN(incidents) med_inc, MEDIAN(mcf) med_mcf FROM op)
SELECT op.*, ROUND(mcf / all_mcf, 3) share_mcf, all_inc, med_inc, med_mcf,
       RANK() OVER (ORDER BY incidents DESC) rank_by_count
FROM op, tot
QUALIFY RANK() OVER (ORDER BY mcf DESC) <= 15 OR RANK() OVER (ORDER BY incidents DESC) <= 8 OR deaths > 0
ORDER BY mcf DESC;

