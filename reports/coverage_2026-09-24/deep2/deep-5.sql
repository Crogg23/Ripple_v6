-- [5] FEC: PAC summary years; treasurer clusters joined to 2026-cycle PAC money by designation
WITH yrs AS (
  SELECT 'ps_year' grp, YEAR(COVERAGE_END_DATE)::string dsgn, COUNT(*) n_cmte, COUNT(DISTINCT CMTE_ID) n_landed,
         SUM(TOTAL_RECEIPTS) receipts, SUM(INDIVIDUAL_CONTRIBUTIONS) indiv, SUM(CONTRIBUTIONS_TO_OTHER_COMMITTEES) to_cmtes,
         SUM(INDEPENDENT_EXPENDITURES) ie, SUM(TRANSFERS_TO_AFFILIATES) xfer_out, SUM(TOTAL_DISBURSEMENTS) disb
  FROM LIBRARY_MARTS.POLITICS.POLITICS__FED_FEC_PAC_SUMMARY GROUP BY 2
), ps AS (
  SELECT * FROM LIBRARY_MARTS.POLITICS.POLITICS__FED_FEC_PAC_SUMMARY
  WHERE COVERAGE_END_DATE >= '2025-01-01'
  QUALIFY ROW_NUMBER() OVER (PARTITION BY CMTE_ID ORDER BY COVERAGE_END_DATE DESC) = 1
), c AS (
  SELECT FEC_CMTE_ID, CMTE_DSGN,
    CASE WHEN TRES_NM ILIKE '%DATWYLER%' OR TRES_NM ILIKE '%DAWTYLER%' THEN 'DATWYLER'
         WHEN TRES_NM IN ('KILGORE, PAUL','LISKER, LISA','PETTERSON, JAY','HOBBS, CABELL','CURTIS, ELIZABETH','CRATE, BRADLEY T.','MARSTON, CHRIS','BOLES, JASON D') THEN TRES_NM
         ELSE 'all other committees' END grp
  FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_FEC_BULK_COMMITTEES
  WHERE CMTE_TP IN ('N','Q','O','V','W')
)
SELECT * FROM yrs
UNION ALL
SELECT c.grp, c.CMTE_DSGN, COUNT(*), COUNT(ps.CMTE_ID), SUM(ps.TOTAL_RECEIPTS), SUM(ps.INDIVIDUAL_CONTRIBUTIONS), SUM(ps.CONTRIBUTIONS_TO_OTHER_COMMITTEES),
       SUM(ps.INDEPENDENT_EXPENDITURES), SUM(ps.TRANSFERS_TO_AFFILIATES), SUM(ps.TOTAL_DISBURSEMENTS)
FROM c LEFT JOIN ps ON ps.CMTE_ID = c.FEC_CMTE_ID
GROUP BY 1, 2
ORDER BY 1, 2;

-- [6] FEC: clusters vs peers on 2024-cycle PAC money; lowest political-share U PACs with 1M+ from individuals
WITH ps AS (
  SELECT * FROM LIBRARY_MARTS.POLITICS.POLITICS__FED_FEC_PAC_SUMMARY
  WHERE COVERAGE_END_DATE >= '2023-01-01' AND COVERAGE_END_DATE < '2025-01-01'
  QUALIFY ROW_NUMBER() OVER (PARTITION BY CMTE_ID ORDER BY COVERAGE_END_DATE DESC) = 1
), c AS (
  SELECT FEC_CMTE_ID, CMTE_NM, TRES_NM, CMTE_DSGN, CMTE_TP,
    CASE WHEN TRES_NM ILIKE '%DATWYLER%' OR TRES_NM ILIKE '%DAWTYLER%' THEN 'DATWYLER'
         WHEN TRES_NM IN ('KILGORE, PAUL','LISKER, LISA','PETTERSON, JAY','HOBBS, CABELL','CURTIS, ELIZABETH','CRATE, BRADLEY T.','MARSTON, CHRIS','BOLES, JASON D') THEN 'top-8 other treasurers'
         ELSE 'all other committees' END grp
  FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_FEC_BULK_COMMITTEES
  WHERE CMTE_TP IN ('N','Q','O','V','W')
), j AS (
  SELECT c.*, ps.CMTE_ID landed, ps.TOTAL_RECEIPTS rec, ps.INDIVIDUAL_CONTRIBUTIONS indiv, ps.CONTRIBUTIONS_TO_OTHER_COMMITTEES to_c,
         ps.INDEPENDENT_EXPENDITURES ie, ps.TRANSFERS_TO_AFFILIATES xf, ps.TOTAL_DISBURSEMENTS disb, ps.COMMITTEE_NAME ps_name,
         (COALESCE(ps.CONTRIBUTIONS_TO_OTHER_COMMITTEES,0)+COALESCE(ps.INDEPENDENT_EXPENDITURES,0))/NULLIF(ps.TOTAL_DISBURSEMENTS,0) pol_share
  FROM c LEFT JOIN ps ON ps.CMTE_ID = c.FEC_CMTE_ID
)
SELECT 'cluster' k, grp||' | '||CMTE_DSGN name, NULL tres, COUNT(*) n, COUNT(landed) landed, ROUND(SUM(rec)) rec, ROUND(SUM(indiv)) indiv,
       ROUND(SUM(to_c)) to_c, ROUND(SUM(ie)) ie, ROUND(SUM(xf)) xf, ROUND(SUM(disb)) disb,
       ROUND((SUM(to_c)+SUM(ie))/NULLIF(SUM(disb),0),3) pol_share_dollar,
       ROUND(MEDIAN(IFF(indiv >= 100000, pol_share, NULL)),3) med_share_100k, COUNT(IFF(indiv >= 100000, 1, NULL)) n_100k,
       COUNT(IFF(indiv >= 100000 AND pol_share < 0.05, 1, NULL)) n_100k_under5pct
FROM j WHERE CMTE_DSGN IN ('U','D') GROUP BY 1, 2
UNION ALL
SELECT * FROM (
  SELECT 'lowshare', FEC_CMTE_ID||' '||CMTE_NM, TRES_NM, 1, 1, ROUND(rec), ROUND(indiv), ROUND(to_c), ROUND(ie), ROUND(xf), ROUND(disb), ROUND(pol_share,3), NULL, NULL, NULL
  FROM j WHERE landed IS NOT NULL AND CMTE_DSGN = 'U' AND indiv >= 1000000 AND disb > 0
  ORDER BY pol_share ASC LIMIT 30)
ORDER BY 1, 7 DESC;

