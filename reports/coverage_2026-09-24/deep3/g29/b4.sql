       t.SHARES * t.PRICE_PER_SHARE AS val, o.OWNER_NAME, o.RELATIONSHIP, o.TITLE, sub.REMARKS
FROM w
JOIN LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_INSIDER_SUBMISSION sub ON TRY_TO_NUMBER(sub.ISSUER_CIK) = w.cik
JOIN LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_INSIDER_NONDERIV_TRANS t ON t.ACCESSION_NUMBER = sub.ACCESSION_NUMBER
LEFT JOIN LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_INSIDER_REPORTINGOWNER o ON o.ACCESSION_NUMBER = sub.ACCESSION_NUMBER
WHERE t.TRANSACTION_CODE = 'S' AND t.TRANSACTION_DATE BETWEEN w.w0 AND w.w1
ORDER BY val DESC;

-- S18 Trap check: open-market sale prices in the insider table, how many are absurd (over $10,000 or $1M a share) and how much value they carry
SELECT YEAR(TRANSACTION_DATE) AS yr, COUNT(*) AS sales, COUNT_IF(PRICE_PER_SHARE > 10000) AS px_over_10k, COUNT_IF(PRICE_PER_SHARE > 1000000) AS px_over_1m,
       SUM(SHARES * PRICE_PER_SHARE) AS val_all, SUM(IFF(PRICE_PER_SHARE <= 10000, SHARES * PRICE_PER_SHARE, 0)) AS val_px_le_10k,
       COUNT_IF(PRICE_PER_SHARE IS NULL OR PRICE_PER_SHARE = 0) AS px_null_or_0
FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_INSIDER_NONDERIV_TRANS
WHERE TRANSACTION_CODE = 'S' AND TRANSACTION_DATE BETWEEN '2022-01-01' AND '2025-03-31'
GROUP BY 1 ORDER BY 1;
