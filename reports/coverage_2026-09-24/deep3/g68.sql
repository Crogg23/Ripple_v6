-- S11 eoir_fixed_cohort_entered_by_2021_by_nationality
-- Fixed cohort: entry date on or before 2021-12-31. Jan-May detentions per year. prior_case = CASE_ID below roughly the first case number issued that January (p10 of border cases detained that Q1, from S09).
SELECT NATIONALITY,
       COUNT_IF(DATE_OF_ENTRY <= '2021-12-31') pool_entered_by_2021,
       COUNT_IF(DATE_OF_ENTRY <= '2021-12-31' AND MONTH(DATE_DETAINED) <= 5 AND YEAR(DATE_DETAINED) = 2023) d23,
       COUNT_IF(DATE_OF_ENTRY <= '2021-12-31' AND MONTH(DATE_DETAINED) <= 5 AND YEAR(DATE_DETAINED) = 2024) d24,
       COUNT_IF(DATE_OF_ENTRY <= '2021-12-31' AND MONTH(DATE_DETAINED) <= 5 AND YEAR(DATE_DETAINED) = 2025) d25,
       COUNT_IF(DATE_OF_ENTRY <= '2021-12-31' AND MONTH(DATE_DETAINED) <= 5 AND YEAR(DATE_DETAINED) = 2026) d26,
       COUNT_IF(DATE_OF_ENTRY <= '2021-12-31' AND MONTH(DATE_DETAINED) <= 5 AND YEAR(DATE_DETAINED) = 2023 AND CASE_ID < 11379000) p23,
       COUNT_IF(DATE_OF_ENTRY <= '2021-12-31' AND MONTH(DATE_DETAINED) <= 5 AND YEAR(DATE_DETAINED) = 2024 AND CASE_ID < 13459000) p24,
       COUNT_IF(DATE_OF_ENTRY <= '2021-12-31' AND MONTH(DATE_DETAINED) <= 5 AND YEAR(DATE_DETAINED) = 2025 AND CASE_ID < 14828000) p25,
       COUNT_IF(DATE_OF_ENTRY <= '2021-12-31' AND MONTH(DATE_DETAINED) <= 5 AND YEAR(DATE_DETAINED) = 2026 AND CASE_ID < 15324000) p26,
       COUNT_IF(DATE_OF_ENTRY <= '2021-12-31' AND MONTH(DATE_DETAINED) <= 5 AND YEAR(DATE_DETAINED) = 2026 AND DATE_OF_ENTRY < '2006-01-01') d26_20y,
       COUNT_IF(DATE_OF_ENTRY <= '2021-12-31' AND MONTH(DATE_DETAINED) <= 5 AND YEAR(DATE_DETAINED) = 2024 AND DATE_OF_ENTRY < '2004-01-01') d24_20y,
       COUNT_IF(DATE_OF_ENTRY < '1940-01-01') entry_pre1940
FROM LIBRARY_MARTS.IMMIGRATION.IMMIGRATION__FED_EOIR_CASES
GROUP BY 1 ORDER BY pool_entered_by_2021 DESC;

