-- S07 eoir_detained_month_by_residence
SELECT DATE_TRUNC('month', DATE_DETAINED)::DATE mon,
       CASE WHEN DATE_OF_ENTRY IS NULL THEN 'no_entry_date'
            WHEN DATEDIFF('day', DATE_OF_ENTRY, DATE_DETAINED) < 0 THEN 'entry_after_detained'
            WHEN DATEDIFF('day', DATE_OF_ENTRY, DATE_DETAINED) <= 30 THEN 'a_0_30d'
            WHEN DATEDIFF('day', DATE_OF_ENTRY, DATE_DETAINED) < 730 THEN 'b_31d_2y'
            WHEN DATEDIFF('day', DATE_OF_ENTRY, DATE_DETAINED) < 3652 THEN 'c_2_10y'
            ELSE 'd_10y_plus' END bucket,
       COUNT(*) n, COUNT_IF(IS_LPR) lpr, COUNT_IF(CUSTODY = 'D') cust_d, COUNT_IF(DATE_RELEASED IS NOT NULL) released
FROM LIBRARY_MARTS.IMMIGRATION.IMMIGRATION__FED_EOIR_CASES
WHERE DATE_DETAINED >= '2018-01-01' AND DATE_DETAINED <= '2026-09-24'
GROUP BY 1,2 ORDER BY 1,2;

-- S08 eoir_janmay_by_entry_year
SELECT YEAR(DATE_DETAINED) det_yr, YEAR(DATE_OF_ENTRY) entry_yr, COUNT(*) n,
       MEDIAN(CASE_ID) med_case_id, MIN(CASE_ID) min_case_id, COUNT_IF(CUSTODY = 'D') cust_d, COUNT_IF(CUSTODY = 'R') cust_r
FROM LIBRARY_MARTS.IMMIGRATION.IMMIGRATION__FED_EOIR_CASES
WHERE MONTH(DATE_DETAINED) BETWEEN 1 AND 5 AND YEAR(DATE_DETAINED) IN (2023, 2024, 2025, 2026)
GROUP BY 1,2 ORDER BY 1,2;

-- S09 eoir_caseid_calibration_border
SELECT DATE_TRUNC('quarter', DATE_DETAINED)::DATE q, COUNT(*) n,
       APPROX_PERCENTILE(CASE_ID, 0.1) p10, MEDIAN(CASE_ID) p50, APPROX_PERCENTILE(CASE_ID, 0.9) p90
FROM LIBRARY_MARTS.IMMIGRATION.IMMIGRATION__FED_EOIR_CASES
WHERE DATE_DETAINED BETWEEN '2015-01-01' AND '2026-05-31'
  AND DATE_OF_ENTRY IS NOT NULL AND DATEDIFF('day', DATE_OF_ENTRY, DATE_DETAINED) BETWEEN 0 AND 30
GROUP BY 1 ORDER BY 1;

