-- S05 ICIS-Air pollutants vs facilities: coverage, FACIL-row class vs facility class, major-for-a-pollutant on a non-major facility
WITH p AS (
  SELECT PGM_SYS_ID, MAX(IFF(POLLUTANT_DESC='FACIL', AIR_POLLUTANT_CLASS_CODE, NULL)) facil_cls,
         COUNT_IF(POLLUTANT_DESC <> 'FACIL') n_poll,
         MAX(IFF(POLLUTANT_DESC <> 'FACIL' AND AIR_POLLUTANT_CLASS_CODE = 'MAJ', 1, 0)) any_maj,
         MAX(IFF(POLLUTANT_DESC <> 'FACIL' AND AIR_POLLUTANT_CLASS_CODE = 'SMI', 1, 0)) any_smi
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ICIS_AIR_ICIS_AIR_POLLUTANTS GROUP BY 1),
f AS (
  SELECT PGM_SYS_ID, ANY_VALUE(AIR_POLLUTANT_CLASS_CODE) fcls, ANY_VALUE(AIR_OPERATING_STATUS_CODE) st, COUNT(*) frows
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ICIS_AIR_ICIS_AIR_FACILITIES GROUP BY 1)
SELECT f.fcls, p.facil_cls, (p.PGM_SYS_ID IS NULL) no_pollutant_rows, (f.PGM_SYS_ID IS NULL) no_facility_row,
       COUNT(*) n, COUNT_IF(f.st = 'OPR') operating, SUM(p.any_maj) any_maj_pollutant, SUM(p.any_smi) any_smi_pollutant,
       MEDIAN(p.n_poll) med_pollutants, SUM(IFF(f.frows > 1, 1, 0)) dup_facility_rows
FROM f FULL OUTER JOIN p ON f.PGM_SYS_ID = p.PGM_SYS_ID
GROUP BY 1,2,3,4 ORDER BY n DESC;

