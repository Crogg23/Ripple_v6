-- @geodiv_shape
WITH t AS (SELECT * FROM LIBRARY_MARTS.REFERENCE.REFERENCE__FED_ITIS_GEOGRAPHIC_DIV)
SELECT COUNT(*) n, COUNT(DISTINCT TSN) tsn_nd, COUNT(DISTINCT ITIS_GEOGRAPHIC_DIV_KEY) key_nd, COUNT(DISTINCT TSN, GEOGRAPHIC_VALUE) pair_nd,
       (SELECT OBJECT_AGG(COALESCE(GEOGRAPHIC_VALUE, '(null)'), c) FROM (SELECT GEOGRAPHIC_VALUE, COUNT(*) c FROM t GROUP BY 1)) by_region,
       COUNT_IF(LEFT(UPDATE_DATE::VARCHAR, 10) = '1900-01-01') d1900, MIN(UPDATE_DATE)::VARCHAR d0, MAX(UPDATE_DATE)::VARCHAR d1,
       (SELECT OBJECT_AGG(y, c) FROM (SELECT LEFT(UPDATE_DATE::VARCHAR, 4) y, COUNT(*) c FROM t GROUP BY 1)) by_year,
       COUNT(DISTINCT _SOURCE_RUN_ID) runs, COUNT(DISTINCT _SRC_SHA256) files,
       (SELECT MAX(c) FROM (SELECT COUNT(*) c FROM t GROUP BY TSN)) max_regions_per_tsn,
       (SELECT MEDIAN(c) FROM (SELECT COUNT(*) c FROM t GROUP BY TSN)) med_regions_per_tsn
FROM t;

-- @geodiv_join_taxonomic_units
WITH g AS (SELECT TSN, LEFT(UPDATE_DATE::VARCHAR, 10) = '1900-01-01' d1900 FROM LIBRARY_MARTS.REFERENCE.REFERENCE__FED_ITIS_GEOGRAPHIC_DIV),
tu AS (SELECT TSN, NAME_USAGE, RANK_ID FROM LIBRARY_MARTS.REFERENCE.REFERENCE__FED_ITIS_TAXONOMIC_UNITS)
SELECT g.d1900, COALESCE(tu.NAME_USAGE::VARCHAR, '(no taxon row)') usage, COUNT(*) n, COUNT(DISTINCT g.TSN) tsns,
       COUNT_IF(tu.RANK_ID = 220) species_rank_rows
FROM g LEFT JOIN tu ON g.TSN = tu.TSN GROUP BY 1, 2 ORDER BY 1, 3 DESC;

-- @geodiv_coverage_by_kingdom
WITH g AS (SELECT DISTINCT TSN FROM LIBRARY_MARTS.REFERENCE.REFERENCE__FED_ITIS_GEOGRAPHIC_DIV),
tu AS (SELECT TSN, KINGDOM_ID FROM LIBRARY_MARTS.REFERENCE.REFERENCE__FED_ITIS_TAXONOMIC_UNITS WHERE RANK_ID = 220 AND NAME_USAGE IN ('valid', 'accepted')),
k AS (SELECT KINGDOM_ID, KINGDOM_NAME FROM LIBRARY_MARTS.REFERENCE.REFERENCE__FED_ITIS_KINGDOMS)
SELECT tu.KINGDOM_ID, MAX(k.KINGDOM_NAME) kingdom, COUNT(*) accepted_species, COUNT_IF(g.TSN IS NOT NULL) with_region,
       ROUND(100 * COUNT_IF(g.TSN IS NOT NULL) / COUNT(*), 1) pct
FROM tu LEFT JOIN g ON tu.TSN = g.TSN LEFT JOIN k ON tu.KINGDOM_ID = k.KINGDOM_ID
GROUP BY 1 ORDER BY 3 DESC;

-- @nodc_shape
