-- @nodc_join_taxonomic_units
WITH t AS (SELECT TSN, NODC_ID FROM LIBRARY_MARTS.REFERENCE.REFERENCE__FED_ITIS_NODC_IDS),
tu AS (SELECT TSN, NAME_USAGE, COMPLETE_NAME, RANK_ID FROM LIBRARY_MARTS.REFERENCE.REFERENCE__FED_ITIS_TAXONOMIC_UNITS),
s AS (SELECT COALESCE(tu.NAME_USAGE::VARCHAR, '(no taxon row)') usage, COUNT(*) n FROM t LEFT JOIN tu ON t.TSN = tu.TSN GROUP BY 1),
e AS (SELECT t.NODC_ID::VARCHAR || ' -> ' || t.TSN || ' ' || COALESCE(tu.COMPLETE_NAME, '?') || ' [' || COALESCE(tu.NAME_USAGE, '?') || ']' r
      FROM t LEFT JOIN tu ON t.TSN = tu.TSN WHERE MOD(t.TSN, 20011) = 7 LIMIT 8)
SELECT 'usage' kind, usage label, n FROM s
UNION ALL SELECT 'eyeball', r, NULL FROM e
ORDER BY 1 DESC, 3 DESC;

