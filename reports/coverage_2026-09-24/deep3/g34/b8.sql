-- S21 NPDES Missouri eyeball: permits with effluent violations in 6+ of 8 quarters in 2020-21 or in 2024-25, their state letters and formal actions in each window, and names
WITH q AS (
  SELECT NPDES_ID,
         COUNT_IF(TRY_TO_NUMBER(NUME90_Q) > 0 AND TRY_TO_NUMBER(YEARQTR) BETWEEN 20201 AND 20214) vq_2021,
         COUNT_IF(TRY_TO_NUMBER(NUME90_Q) > 0 AND TRY_TO_NUMBER(YEARQTR) BETWEEN 20241 AND 20254) vq_2425,
         SUM(IFF(TRY_TO_NUMBER(YEARQTR) BETWEEN 20241 AND 20254, TRY_TO_NUMBER(NUME90_Q), 0)) nviol_2425
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_QNCR_HISTORY WHERE LEFT(NPDES_ID,2) = 'MO' GROUP BY 1),
i AS (
  SELECT NPDES_ID, COUNT_IF(ACHIEVED_DATE BETWEEN '2020-01-01' AND '2021-12-31') inf_2021, COUNT_IF(ACHIEVED_DATE BETWEEN '2024-01-01' AND '2025-12-31') inf_2425,
         MAX(IFF(ACHIEVED_DATE <= CURRENT_DATE, ACHIEVED_DATE, NULL)) last_inf
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_INFORMAL_ENFORCEMENT_ACTIONS WHERE LEFT(NPDES_ID,2) = 'MO' GROUP BY 1),
f AS (
  SELECT NPDES_ID, COUNT_IF(SETTLEMENT_ENTERED_DATE BETWEEN '2020-01-01' AND '2021-12-31') fo_2021, COUNT_IF(SETTLEMENT_ENTERED_DATE BETWEEN '2024-01-01' AND '2025-12-31') fo_2425,
         MAX(SETTLEMENT_ENTERED_DATE) last_formal
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_NPDES_FORMAL_ENFORCEMENT_ACTIONS WHERE LEFT(NPDES_ID,2) = 'MO' GROUP BY 1),
fac AS (
  SELECT NPDES_ID, ANY_VALUE(FACILITY_NAME) facility_name, ANY_VALUE(CITY) city, ANY_VALUE(FACILITY_TYPE_CODE) ftype
  FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_NPDES_ICIS_FACILITIES WHERE LEFT(NPDES_ID,2) = 'MO' GROUP BY 1)
SELECT q.*, COALESCE(i.inf_2021,0) inf_2021, COALESCE(i.inf_2425,0) inf_2425, i.last_inf, COALESCE(f.fo_2021,0) fo_2021, COALESCE(f.fo_2425,0) fo_2425, f.last_formal,
       fac.facility_name, fac.city, fac.ftype
FROM q LEFT JOIN i ON i.NPDES_ID = q.NPDES_ID LEFT JOIN f ON f.NPDES_ID = q.NPDES_ID LEFT JOIN fac ON fac.NPDES_ID = q.NPDES_ID
WHERE q.vq_2021 >= 6 OR q.vq_2425 >= 6
ORDER BY q.vq_2425 DESC, q.nviol_2425 DESC;
