-- S10 ICIJ: every node tied to a US address (via registered_address), plus US-coded officers/intermediaries with no US address
WITH us_addr AS (
  SELECT NODE_ID, NULLIF(TRIM(ADDRESS),'') a1, NULLIF(TRIM(NAME),'') a2
  FROM LIBRARY_MARTS.CORPORATE_REGISTRY.CORPORATE_REGISTRY__FED_ICIJ_OFFSHORELEAKS_ADDRESSES
  WHERE COUNTRY_CODES ILIKE '%USA%'
), ra AS (
  SELECT NODE_ID_START, NODE_ID_END FROM LIBRARY_MARTS.CORPORATE_REGISTRY.CORPORATE_REGISTRY__FED_ICIJ_OFFSHORELEAKS_RELATIONSHIPS
  WHERE REL_TYPE = 'registered_address'
), nodes AS (
  SELECT NODE_ID, 'officer' kind, NAME, COUNTRY_CODES, SOURCE_LEAK FROM LIBRARY_MARTS.CORPORATE_REGISTRY.CORPORATE_REGISTRY__FED_ICIJ_OFFSHORELEAKS_OFFICERS
  UNION ALL SELECT NODE_ID, 'entity', NAME, COUNTRY_CODES, SOURCE_LEAK FROM LIBRARY_MARTS.CORPORATE_REGISTRY.CORPORATE_REGISTRY__FED_ICIJ_OFFSHORELEAKS_ENTITIES
  UNION ALL SELECT NODE_ID, 'intermediary', NAME, COUNTRY_CODES, SOURCE_LEAK FROM LIBRARY_MARTS.CORPORATE_REGISTRY.CORPORATE_REGISTRY__FED_ICIJ_OFFSHORELEAKS_INTERMEDIARIES
  UNION ALL SELECT NODE_ID, 'other', NAME, COUNTRY_CODES, SOURCE_LEAK FROM LIBRARY_MARTS.CORPORATE_REGISTRY.CORPORATE_REGISTRY__FED_ICIJ_OFFSHORELEAKS_OTHERS
), via_addr AS (
  SELECT n.NODE_ID, n.kind, n.NAME, n.COUNTRY_CODES, n.SOURCE_LEAK, a.NODE_ID addr_node, COALESCE(a.a1, a.a2) addr_text
  FROM us_addr a JOIN ra ON ra.NODE_ID_END = a.NODE_ID JOIN nodes n ON n.NODE_ID = ra.NODE_ID_START
), via_code AS (
  SELECT n.NODE_ID, n.kind, n.NAME, n.COUNTRY_CODES, n.SOURCE_LEAK, NULL addr_node, NULL addr_text
  FROM nodes n
  WHERE n.COUNTRY_CODES ILIKE '%USA%' AND n.kind IN ('officer','intermediary')
    AND n.NODE_ID NOT IN (SELECT NODE_ID FROM via_addr)
), unlinked AS (
  SELECT NULL NODE_ID, 'address_only' kind, NULL NAME, NULL COUNTRY_CODES, NULL SOURCE_LEAK, a.NODE_ID addr_node, COALESCE(a.a1, a.a2) addr_text
  FROM us_addr a WHERE a.NODE_ID NOT IN (SELECT NODE_ID_END FROM ra)
)
SELECT * FROM via_addr UNION ALL SELECT * FROM via_code UNION ALL SELECT * FROM unlinked;

