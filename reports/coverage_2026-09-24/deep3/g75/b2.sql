-- S13 ICIJ others: whole table plus how many edges touch each node
WITH e AS (
  SELECT NODE_ID_START nid, REL_TYPE FROM LIBRARY_MARTS.CORPORATE_REGISTRY.CORPORATE_REGISTRY__FED_ICIJ_OFFSHORELEAKS_RELATIONSHIPS
  UNION ALL SELECT NODE_ID_END, REL_TYPE FROM LIBRARY_MARTS.CORPORATE_REGISTRY.CORPORATE_REGISTRY__FED_ICIJ_OFFSHORELEAKS_RELATIONSHIPS
), c AS (SELECT nid, COUNT(*) edges, LISTAGG(DISTINCT REL_TYPE, '|') rels FROM e GROUP BY 1)
SELECT o.*, c.edges, c.rels
FROM LIBRARY_MARTS.CORPORATE_REGISTRY.CORPORATE_REGISTRY__FED_ICIJ_OFFSHORELEAKS_OTHERS o LEFT JOIN c ON c.nid = o.NODE_ID;

