-- S04 Earthquakes: month by month - rows, distinct IDs, magnitude bands, type, review status, fixed 10 km depth
SELECT DATE_TRUNC('month', TIME)::DATE mo, COUNT(*) n, COUNT(DISTINCT ID) ids,
       COUNT_IF(MAG >= 3) m3, COUNT_IF(MAG >= 4.5) m45, COUNT_IF(MAG >= 6) m6,
       COUNT_IF(TYPE = 'earthquake') eq, COUNT_IF(STATUS = 'reviewed') reviewed, COUNT_IF(DEPTH = 10) d10,
       MIN(TIME) t0, MAX(TIME) t1, MAX(UPDATED) upd_max
FROM LIBRARY_MARTS.SCIENCE.SCIENCE__FED_USGS_EARTHQUAKES GROUP BY 1 ORDER BY 1;

-- S05 Earthquakes: value profile - type, status, network, magtype, the most common depths, lat/lon that do not parse
SELECT 'type' dim, TYPE val, COUNT(*) n FROM LIBRARY_MARTS.SCIENCE.SCIENCE__FED_USGS_EARTHQUAKES GROUP BY 2
UNION ALL SELECT 'status', STATUS, COUNT(*) FROM LIBRARY_MARTS.SCIENCE.SCIENCE__FED_USGS_EARTHQUAKES GROUP BY 2
UNION ALL SELECT 'net', NET, COUNT(*) FROM LIBRARY_MARTS.SCIENCE.SCIENCE__FED_USGS_EARTHQUAKES GROUP BY 2
UNION ALL SELECT 'magtype', MAGTYPE, COUNT(*) FROM LIBRARY_MARTS.SCIENCE.SCIENCE__FED_USGS_EARTHQUAKES GROUP BY 2
UNION ALL SELECT * FROM (SELECT 'depth', TO_VARCHAR(DEPTH), COUNT(*) n FROM LIBRARY_MARTS.SCIENCE.SCIENCE__FED_USGS_EARTHQUAKES GROUP BY 2 ORDER BY n DESC LIMIT 12)
UNION ALL SELECT 'latlon_bad', 'lat or lon not a number', COUNT_IF(TRY_TO_DOUBLE(LATITUDE) IS NULL OR TRY_TO_DOUBLE(LONGITUDE) IS NULL) FROM LIBRARY_MARTS.SCIENCE.SCIENCE__FED_USGS_EARTHQUAKES
UNION ALL SELECT 'dup_id', 'rows minus distinct ID', COUNT(*) - COUNT(DISTINCT ID) FROM LIBRARY_MARTS.SCIENCE.SCIENCE__FED_USGS_EARTHQUAKES
UNION ALL SELECT 'mag_lt_2_5', 'MAG under 2.5', COUNT_IF(MAG < 2.5) FROM LIBRARY_MARTS.SCIENCE.SCIENCE__FED_USGS_EARTHQUAKES
ORDER BY 1, 3 DESC;

-- S06 Earthquakes: lower-48 box, by place suffix (state), oil-field zone, year - counts by magnitude band and who located them
WITH q AS (
  SELECT TRIM(REGEXP_SUBSTR(PLACE, '[^,]+$')) region, YEAR(TIME) yr, MAG, NET, STATUS,
         TRY_TO_DOUBLE(LATITUDE) lat, TRY_TO_DOUBLE(LONGITUDE) lon
  FROM LIBRARY_MARTS.SCIENCE.SCIENCE__FED_USGS_EARTHQUAKES
  WHERE TYPE = 'earthquake' AND TRY_TO_DOUBLE(LATITUDE) BETWEEN 24 AND 50 AND TRY_TO_DOUBLE(LONGITUDE) BETWEEN -125 AND -66)
SELECT region,
       CASE WHEN lat BETWEEN 30.5 AND 33.8 AND lon BETWEEN -105.0 AND -100.5 THEN 'PERMIAN'
            WHEN lat BETWEEN 33.6 AND 37.0 AND lon BETWEEN -99.5 AND -96.0 THEN 'OK_CENTRAL'
            WHEN lat BETWEEN 36.9 AND 37.6 AND lon BETWEEN -98.8 AND -97.0 THEN 'KS_SOUTH'
            WHEN lat BETWEEN 28.0 AND 29.5 AND lon BETWEEN -99.5 AND -97.0 THEN 'EAGLE_FORD'
            WHEN lat BETWEEN 36.9 AND 37.6 AND lon BETWEEN -105.3 AND -104.3 THEN 'RATON'
            ELSE 'OTHER' END zone,
       yr, COUNT(*) n, COUNT_IF(MAG >= 3) m3, COUNT_IF(MAG >= 3.5) m35, COUNT_IF(MAG >= 4) m4, MAX(MAG) max_mag,
       COUNT_IF(NET = 'tx') net_tx, COUNT_IF(NET = 'us') net_us, COUNT_IF(NET = 'ok') net_ok, COUNT_IF(STATUS = 'reviewed') reviewed
FROM q GROUP BY 1,2,3 ORDER BY 1,2,3;

