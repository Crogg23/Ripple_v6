-- S08 NTSB injury: keys, duplicate loads, load runs, change dates, and how many events land in the events and aircraft tables
WITH i AS (SELECT * FROM LIBRARY_MARTS.TRANSPORT.TRANSPORT__FED_NTSB_AVIATION_INJURY),
ie AS (SELECT DISTINCT EV_ID FROM i),
ia AS (SELECT DISTINCT EV_ID, AIRCRAFT_KEY FROM i),
e AS (SELECT DISTINCT EV_ID FROM LIBRARY_MARTS.TRANSPORT.TRANSPORT__FED_NTSB_AVIATION_EVENTS),
a AS (SELECT DISTINCT EV_ID, AIRCRAFT_KEY FROM LIBRARY_MARTS.TRANSPORT.TRANSPORT__FED_NTSB_AVIATION_AIRCRAFT),
m AS (SELECT LCHG_DATE d, COUNT(*) k FROM i GROUP BY 1 ORDER BY k DESC LIMIT 1)
SELECT (SELECT COUNT(*) FROM i) n, (SELECT COUNT(DISTINCT INJURY_RECORD_ID) FROM i) rec_ids,
       (SELECT COUNT(DISTINCT EV_ID, AIRCRAFT_KEY, INJ_PERSON_CATEGORY, INJURY_LEVEL) FROM i) nat_keys,
       (SELECT COUNT(DISTINCT _SOURCE_RUN_ID) FROM i) runs, (SELECT COUNT(DISTINCT _INGESTED_AT) FROM i) ingest_stamps,
       (SELECT COUNT(*) FROM ie) inj_events, (SELECT COUNT(*) FROM e) ev_events,
       (SELECT COUNT(*) FROM ie JOIN e USING (EV_ID)) inj_ev_in_events,
       (SELECT COUNT(*) FROM e WHERE EV_ID NOT IN (SELECT EV_ID FROM ie)) events_without_inj,
       (SELECT COUNT(*) FROM ia) inj_aircraft, (SELECT COUNT(*) FROM ia JOIN a USING (EV_ID, AIRCRAFT_KEY)) inj_ac_in_aircraft,
       (SELECT MIN(LEFT(EV_ID,4)) FROM i) evid_y0, (SELECT MAX(LEFT(EV_ID,4)) FROM i) evid_y1,
       (SELECT MIN(LCHG_DATE) FROM i) lchg0, (SELECT MAX(LCHG_DATE) FROM i) lchg1,
       (SELECT MAX(d) FROM m) lchg_mode, (SELECT MAX(k) FROM m) lchg_mode_n,
       (SELECT COUNT_IF(LCHG_USERID = 'None' OR LCHG_USERID IS NULL) FROM i) userid_none;

-- S09 NTSB injury: does TOTL equal the sum of the other levels, and do the per-person deaths match the events table's death count
WITH p AS (
  SELECT EV_ID, AIRCRAFT_KEY, INJ_PERSON_CATEGORY c,
         SUM(IFF(INJURY_LEVEL <> 'TOTL', COALESCE(INJ_PERSON_COUNT,0), 0)) parts,
         MAX(IFF(INJURY_LEVEL = 'TOTL', INJ_PERSON_COUNT, NULL)) totl, COUNT_IF(INJURY_LEVEL = 'TOTL') has_totl,
         SUM(IFF(INJURY_LEVEL = 'FATL', COALESCE(INJ_PERSON_COUNT,0), 0)) f
  FROM LIBRARY_MARTS.TRANSPORT.TRANSPORT__FED_NTSB_AVIATION_INJURY GROUP BY 1,2,3),
ev AS (SELECT EV_ID, SUM(f) f FROM p GROUP BY 1),
e AS (SELECT EV_ID, TRY_TO_NUMBER(TO_VARCHAR(INJ_TOT_F)) ef, TRY_TO_NUMBER(TO_VARCHAR(INJ_F_GRND)) gf, EV_HIGHEST_INJURY h
      FROM LIBRARY_MARTS.TRANSPORT.TRANSPORT__FED_NTSB_AVIATION_EVENTS)
SELECT 'groups' k, COUNT(*) n, COUNT_IF(has_totl > 0) a, COUNT_IF(totl = parts) b, COUNT_IF(totl <> parts) c, COUNT_IF(has_totl > 0 AND totl IS NULL) d
FROM p
UNION ALL
SELECT 'events', COUNT(*), COUNT_IF(COALESCE(ev.f,0) = COALESCE(e.ef,0)), COUNT_IF(COALESCE(ev.f,0) <> COALESCE(e.ef,0)),
       COUNT_IF(COALESCE(ev.f,0) + COALESCE(e.gf,0) = COALESCE(e.ef,0) AND COALESCE(ev.f,0) <> COALESCE(e.ef,0)), SUM(ev.f) - SUM(e.ef)
FROM ev JOIN e USING (EV_ID);

