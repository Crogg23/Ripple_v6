-- S09 FracFocus water: every DESCRIPTION value, percent shape, landing rate in the disclosure list
WITH d AS (SELECT DISTINCT DISCLOSURE_ID FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_FRACFOCUS_DISCLOSURE_LIST)
SELECT w.DESCRIPTION, COUNT(*) n, COUNT(DISTINCT w.DISCLOSURE_ID) discl, COUNT(d.DISCLOSURE_ID) landed,
       SUM(PERCENT) pct_sum, MEDIAN(PERCENT) pct_med, COUNT_IF(PERCENT = 0) pct0, COUNT_IF(PERCENT IS NULL) pct_null,
       COUNT_IF(PERCENT > 100) pct_over100, COUNT(DISTINCT OPERATOR_NAME) ops, COUNT(DISTINCT STATE_NAME) states
FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_FRACFOCUS_WATER_SOURCE w LEFT JOIN d ON d.DISCLOSURE_ID = w.DISCLOSURE_ID
GROUP BY ROLLUP(1) ORDER BY n DESC;

-- S10 FracFocus: disclosures by form version, how many carry water rows, per-disclosure percent sums and duplicate rows
WITH ws AS (SELECT DISCLOSURE_ID, COUNT(*) n, SUM(PERCENT) p, COUNT(DISTINCT DESCRIPTION, PERCENT) u, COUNT(DISTINCT WATER_SOURCE_ID) wid
            FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_FRACFOCUS_WATER_SOURCE GROUP BY 1),
     d AS (SELECT DISCLOSURE_ID, ANY_VALUE(FF_VERSION) ffv, COUNT(*) dn, MAX(JOB_START_DATE) js, MAX(TOTAL_BASE_WATER_VOLUME) vol
           FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_FRACFOCUS_DISCLOSURE_LIST GROUP BY 1)
SELECT COALESCE(d.ffv, 'not in list') ffv, COUNT(*) discl, COUNT_IF(d.dn > 1) dup_in_list, COUNT(ws.DISCLOSURE_ID) with_water,
       COUNT_IF(ABS(ws.p - 100) < 0.5) p100, COUNT_IF(ws.p > 100.5) p_over, COUNT_IF(ws.p < 99.5) p_under,
       COUNT_IF(ws.n > ws.u) dup_rows, COUNT_IF(ws.n > ws.wid) dup_wsid, COUNT(d.js) has_job_date,
       COUNT_IF(d.vol > 0) vol_pos, MEDIAN(d.vol) vol_med
FROM d FULL OUTER JOIN ws ON ws.DISCLOSURE_ID = d.DISCLOSURE_ID
GROUP BY 1 ORDER BY 1;

