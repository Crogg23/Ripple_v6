-- S06 FRS NAICS and SIC code tables: per program, rows, facilities, exact duplicates, code shape, blanks
SELECT 'NAICS' tbl, PGM_SYS_ACNRM, COUNT(*) n, COUNT(DISTINCT REGISTRY_ID) ids, COUNT(DISTINCT REGISTRY_ID, PGM_SYS_ID, NAICS_CODE) uniq_rows,
       COUNT_IF(LEN(TRIM(NAICS_CODE)) = 6) len6, COUNT_IF(LEN(TRIM(NAICS_CODE)) BETWEEN 1 AND 5) short, COUNT_IF(NULLIF(TRIM(NAICS_CODE),'') IS NULL) blank,
       COUNT_IF(TRY_TO_NUMBER(NAICS_CODE) = 0) zeros, MODE(NAICS_CODE) top_code, COUNT_IF(LEFT(REGISTRY_ID,3) <> '110') bad_id
FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_FRS_FRS_NAICS_CODES GROUP BY 1,2
UNION ALL
SELECT 'SIC', PGM_SYS_ACNRM, COUNT(*), COUNT(DISTINCT REGISTRY_ID), COUNT(DISTINCT REGISTRY_ID, PGM_SYS_ID, SIC_CODE),
       COUNT_IF(LEN(TRIM(SIC_CODE)) = 4), COUNT_IF(LEN(TRIM(SIC_CODE)) BETWEEN 1 AND 3), COUNT_IF(NULLIF(TRIM(SIC_CODE),'') IS NULL),
       COUNT_IF(TRY_TO_NUMBER(SIC_CODE) = 0), MODE(SIC_CODE), COUNT_IF(LEFT(REGISTRY_ID,3) <> '110')
FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_FRS_FRS_SIC_CODES GROUP BY 1,2
ORDER BY 1, 3 DESC;

-- S07 AQS: sites opened and closed per year
SELECT yr, SUM(opened) opened, SUM(closed) closed FROM (
  SELECT YEAR(SITE_ESTABLISHED_DATE) yr, 1 opened, 0 closed FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_AQS_SITES
  UNION ALL
  SELECT YEAR(SITE_CLOSED_DATE), 0, 1 FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_AQS_SITES WHERE SITE_CLOSED_DATE IS NOT NULL
) GROUP BY yr ORDER BY yr;

