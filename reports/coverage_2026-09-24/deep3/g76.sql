-- S06 NFIP book: what the raw map-date text says when it is not a date, future-date years, CRS classes, name suffix types, ID shape
WITH b AS (SELECT * FROM LIBRARY_MARTS.HOUSING.HOUSING__FED_FEMA_NFIP_COMMUNITY_STATUS_BOOK)
SELECT * FROM (SELECT 'RAW_NOT_DATE' k, CURRENTLY_EFFECTIVE_MAP_DATE_RAW v, COUNT(*) n FROM b WHERE CURRENTLY_EFFECTIVE_MAP_DATE IS NULL GROUP BY 2 ORDER BY 3 DESC LIMIT 15)
UNION ALL SELECT * FROM (SELECT 'RAW_SAMPLE', CURRENTLY_EFFECTIVE_MAP_DATE_RAW || ' -> ' || TO_VARCHAR(CURRENTLY_EFFECTIVE_MAP_DATE), COUNT(*) FROM b WHERE CURRENTLY_EFFECTIVE_MAP_DATE IS NOT NULL GROUP BY 2 ORDER BY 3 DESC LIMIT 5)
UNION ALL SELECT 'FUT_FHBM_YR', TO_VARCHAR(YEAR(INITIAL_FLOOD_HAZARD_BOUNDARY_MAP_DATE)), COUNT(*) FROM b WHERE INITIAL_FLOOD_HAZARD_BOUNDARY_MAP_DATE > CURRENT_DATE GROUP BY 2
UNION ALL SELECT 'FUT_REG_YR', TO_VARCHAR(YEAR(REGULAR_EMERGENCY_PROGRAM_DATE)), COUNT(*) FROM b WHERE REGULAR_EMERGENCY_PROGRAM_DATE > CURRENT_DATE GROUP BY 2
UNION ALL SELECT 'REG_YR_1968_75', TO_VARCHAR(YEAR(REGULAR_EMERGENCY_PROGRAM_DATE)), COUNT(*) FROM b WHERE YEAR(REGULAR_EMERGENCY_PROGRAM_DATE) BETWEEN 1960 AND 1975 GROUP BY 2
UNION ALL SELECT 'CRS', CRS_CLASS_RATING, COUNT(*) FROM b GROUP BY 2
UNION ALL SELECT * FROM (SELECT 'SUFFIX', COALESCE(REGEXP_SUBSTR(COMMUNITY_NAME, ',\\s*([^,]*)$', 1, 1, 'e'), '(none)'), COUNT(*) FROM b GROUP BY 2 ORDER BY 3 DESC LIMIT 25)
UNION ALL SELECT 'ID_LEN', TO_VARCHAR(LENGTH(COMMUNITY_ID_NUMBER)) || ' state_prefix_distinct_per_state=' || TO_VARCHAR(COUNT(DISTINCT STATE)), COUNT(*) FROM b GROUP BY LENGTH(COMMUNITY_ID_NUMBER)
UNION ALL SELECT * FROM (SELECT 'NAME_SAMPLE', COMMUNITY_ID_NUMBER || ' | ' || COMMUNITY_NAME || ' | ' || COALESCE(COUNTY,'') || ' | ' || STATE || ' | p=' || COALESCE(PARTICIPATING_IN_NFIP_FLAG,'') || ' | cem=' || COALESCE(CURRENTLY_EFFECTIVE_MAP_DATE_RAW,''), 1 FROM b SAMPLE (12 ROWS));

