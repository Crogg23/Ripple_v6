-- [S13] synonym_join_taxonomic_units
WITH s AS (SELECT TSN, TSN_ACCEPTED FROM LIBRARY_MARTS.REFERENCE.REFERENCE__FED_ITIS_SYNONYM_LINKS),
tu AS (SELECT TSN, NAME_USAGE, COMPLETE_NAME FROM LIBRARY_MARTS.REFERENCE.REFERENCE__FED_ITIS_TAXONOMIC_UNITS),
top5 AS (SELECT TSN_ACCEPTED, COUNT(*) c FROM s GROUP BY 1 ORDER BY 2 DESC LIMIT 5)
SELECT 'synonym side' side, COALESCE(tu.NAME_USAGE::VARCHAR, '(no taxon row)') label, COUNT(*) n FROM s LEFT JOIN tu ON s.TSN = tu.TSN GROUP BY 1, 2
UNION ALL SELECT 'accepted side', COALESCE(tu.NAME_USAGE::VARCHAR, '(no taxon row)'), COUNT(*) FROM s LEFT JOIN tu ON s.TSN_ACCEPTED = tu.TSN GROUP BY 1, 2
UNION ALL SELECT 'unaccepted names with no link', tu.NAME_USAGE::VARCHAR, COUNT(*) FROM tu WHERE tu.NAME_USAGE IN ('invalid', 'not accepted') AND tu.TSN NOT IN (SELECT TSN FROM s) GROUP BY 1, 2
UNION ALL SELECT 'top accepted', COALESCE(tu.COMPLETE_NAME, '?') || ' (' || top5.TSN_ACCEPTED || ')', top5.c FROM top5 LEFT JOIN tu ON top5.TSN_ACCEPTED = tu.TSN
ORDER BY 1, 3 DESC;

-- [S14] nodc_code_reuse
WITH t AS (SELECT TSN, NODC_ID FROM LIBRARY_MARTS.REFERENCE.REFERENCE__FED_ITIS_NODC_IDS),
tu AS (SELECT TSN, NAME_USAGE, COMPLETE_NAME FROM LIBRARY_MARTS.REFERENCE.REFERENCE__FED_ITIS_TAXONOMIC_UNITS),
m AS (SELECT NODC_ID FROM t GROUP BY 1 HAVING COUNT(*) > 1),
j AS (SELECT t.NODC_ID, t.TSN, tu.NAME_USAGE u, tu.COMPLETE_NAME nm FROM t JOIN m ON t.NODC_ID = m.NODC_ID LEFT JOIN tu ON t.TSN = tu.TSN),
per AS (SELECT NODC_ID, COUNT(*) c, COUNT_IF(u IN ('valid', 'accepted')) n_ok FROM j GROUP BY 1),
top1 AS (SELECT NODC_ID FROM per ORDER BY c DESC, NODC_ID LIMIT 1)
SELECT 'codes with >1 TSN' k, COUNT(*)::VARCHAR v FROM per
UNION ALL SELECT 'rows on those codes', SUM(c)::VARCHAR FROM per
UNION ALL SELECT 'codes with exactly 1 accepted TSN', COUNT_IF(n_ok = 1)::VARCHAR FROM per
UNION ALL SELECT 'codes with 0 accepted TSN', COUNT_IF(n_ok = 0)::VARCHAR FROM per
UNION ALL SELECT 'codes with 2+ accepted TSN', COUNT_IF(n_ok >= 2)::VARCHAR FROM per
UNION ALL SELECT 'top code ' || MAX(j.NODC_ID), LISTAGG(j.nm || ' [' || j.u || ']', '; ') WITHIN GROUP (ORDER BY j.u DESC, j.nm) FROM j JOIN top1 ON j.NODC_ID = top1.NODC_ID;

-- [S15] county_ct_impact
WITH ct_old AS (SELECT column1 g FROM VALUES ('09001'), ('09003'), ('09005'), ('09007'), ('09009'), ('09011'), ('09013'), ('09015')),
