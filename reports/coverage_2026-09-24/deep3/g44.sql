SELECT 'dim_county CT population_2020' k, SUM(POPULATION_2020)::VARCHAR v FROM LIBRARY_MARTS.CORE.DIM_COUNTY WHERE LPAD(TRY_TO_NUMBER(STATE_FIPS::VARCHAR)::VARCHAR, 2, '0') = '09'
UNION ALL SELECT 'dim_county CT rows', COUNT(*)::VARCHAR FROM LIBRARY_MARTS.CORE.DIM_COUNTY WHERE LPAD(TRY_TO_NUMBER(STATE_FIPS::VARCHAR)::VARCHAR, 2, '0') = '09'
UNION ALL SELECT 'drug_poisoning CT old-code rows', COUNT(*)::VARCHAR FROM dp WHERE g IN (SELECT g FROM ct_old)
UNION ALL SELECT 'drug_poisoning CT years', MIN(y)::VARCHAR || '-' || MAX(y)::VARCHAR FROM dp WHERE g IN (SELECT g FROM ct_old)
UNION ALL SELECT 'drug_poisoning rows off-map (no CB match, county-level)', COUNT(*)::VARCHAR FROM dp WHERE TRY_TO_NUMBER(g) >= 1000 AND g NOT IN (SELECT GEOID::VARCHAR FROM LIBRARY_MARTS.REFERENCE.REFERENCE__CENSUS_CB_COUNTY)
UNION ALL SELECT 'drug_poisoning county-level rows', COUNT(*)::VARCHAR FROM dp WHERE TRY_TO_NUMBER(g) >= 1000
UNION ALL SELECT 'injury CT old-code rows', COUNT(*)::VARCHAR FROM iv WHERE g IN (SELECT g FROM ct_old)
UNION ALL SELECT 'injury CT periods', COUNT(DISTINCT p)::VARCHAR FROM iv WHERE g IN (SELECT g FROM ct_old);
