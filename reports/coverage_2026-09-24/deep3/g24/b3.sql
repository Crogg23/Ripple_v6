-- S12 FDIC: active banks extract with FDIC enforcement orders aggregated by CERT (all time and since 2020)
WITH o AS (
  SELECT CERT_NUMBER cert, COUNT(*) orders_all, COUNT_IF(ORDER_DATE >= '2020-01-01') orders_2020,
         COUNT_IF(ORDER_DATE >= '2020-01-01' AND (ORDER_TYPE ILIKE '%cease%' OR ORDER_TITLE ILIKE '%consent%' OR ORDER_TITLE ILIKE '%cease%')) cd_2020,
         COUNT_IF(ORDER_DATE >= '2020-01-01' AND ORDER_TYPE ILIKE '%civil money%') cmp_2020,
         SUM(IFF(ORDER_DATE >= '2020-01-01', CMP_AMOUNT_TOTAL, 0)) cmp_amt_2020, MAX(ORDER_DATE) last_order,
         LISTAGG(DISTINCT IFF(ORDER_DATE >= '2020-01-01', ORDER_TYPE, NULL), ' | ') types_2020
  FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_FDIC_ENFORCEMENT_ORDERS WHERE CERT_NUMBER > 0 GROUP BY 1)
SELECT b.CERT, b.NAME, b.CITY, b.STALP, b.BKCLASS, b.CHRTAGNT, b.SPECGRP, b.CLCODE, b.ESTYMD, b.ASSET, b.DEP, b.DEPDOM, b.NETINC, b.REPDTE,
       b.OFFICES, b.OFFICES_DOMESTIC, b.MDI_STATUS_CODE, b.MDI_STATUS_DESC, b.HOLDING_COMPANY_NAME, b.FDIC_SUPERVISOR, b.CBSA_METRO_NAME,
       o.orders_all, o.orders_2020, o.cd_2020, o.cmp_2020, o.cmp_amt_2020, o.last_order, o.types_2020
FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_FDIC_BANK_DATA b LEFT JOIN o ON o.cert = TRY_TO_NUMBER(b.CERT)
