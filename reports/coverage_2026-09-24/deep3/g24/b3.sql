-- S13 EPA bridge: case-number year and prefix; cases, conclusions, facility rows, biggest conclusion per year
WITH t AS (SELECT CASE_NUMBER, ENF_CONCLUSION_ID, FACILITY_UIN, SPLIT_PART(CASE_NUMBER, '-', 1) pre, TRY_TO_NUMBER(SPLIT_PART(CASE_NUMBER, '-', 2)) yr
           FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_EPA_ICIS_FEC_CASE_ENFORCEMENT_CONCLUSION_FACILITIES),
c AS (SELECT yr, pre, ENF_CONCLUSION_ID, COUNT(*) fac FROM t GROUP BY 1, 2, 3)
SELECT yr, COUNT(*) conclusions, SUM(fac) fac_rows, COUNT_IF(pre = 'HQ') hq, COUNT_IF(pre IN ('EF','WF')) ef_wf,
       COUNT_IF(fac = 1) single_site, MAX(fac) max_sites, MEDIAN(fac) med_sites
FROM c GROUP BY 1 ORDER BY 1;

-- S14 EPA bridge: the top facilities by distinct cases, and the conclusions that cover the most sites
SELECT 'top_facility' kind, FACILITY_UIN id, ANY_VALUE(FACILITY_NAME) name, ANY_VALUE(FACILITY_CITY) city, ANY_VALUE(FACILITY_STATE) st,
       COUNT(DISTINCT CASE_NUMBER) cases, COUNT(*) n_rows, MIN(CASE_NUMBER) c_min, MAX(CASE_NUMBER) c_max, COUNT(DISTINCT FACILITY_NAME) names
FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_EPA_ICIS_FEC_CASE_ENFORCEMENT_CONCLUSION_FACILITIES
GROUP BY 2 QUALIFY ROW_NUMBER() OVER (ORDER BY COUNT(DISTINCT CASE_NUMBER) DESC) <= 40
UNION ALL
SELECT 'big_conclusion', ENF_CONCLUSION_ID, ANY_VALUE(FACILITY_NAME), ANY_VALUE(CASE_NUMBER), ANY_VALUE(FACILITY_STATE),
       COUNT(DISTINCT FACILITY_STATE), COUNT(*), MIN(FACILITY_NAME), MAX(FACILITY_NAME), COUNT(DISTINCT FACILITY_NAME)
FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_EPA_ICIS_FEC_CASE_ENFORCEMENT_CONCLUSION_FACILITIES
GROUP BY 2 QUALIFY ROW_NUMBER() OVER (ORDER BY COUNT(*) DESC) <= 20;

-- S15 EPA bridge x ECHO: per-facility case count joined to ECHO status by FRS registry ID (extract for local peer math)
WITH f AS (SELECT FACILITY_UIN, COUNT(DISTINCT CASE_NUMBER) cases, MAX(TRY_TO_NUMBER(SPLIT_PART(CASE_NUMBER, '-', 2))) last_case_yr,
                  MIN(TRY_TO_NUMBER(SPLIT_PART(CASE_NUMBER, '-', 2))) first_case_yr, ANY_VALUE(FACILITY_NAME) name, ANY_VALUE(FACILITY_STATE) st
           FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_EPA_ICIS_FEC_CASE_ENFORCEMENT_CONCLUSION_FACILITIES
           WHERE REGEXP_LIKE(FACILITY_UIN, '^110[0-9]{9}$') GROUP BY 1),
e AS (SELECT FRS_ID, COMPLIANCE_STATUS, QUARTERS_WITH_NONCOMPLIANCE, FORMAL_ACTION_COUNT, TOTAL_PENALTIES, IS_MAJOR_FACILITY, IS_ACTIVE,
             HAS_AIR_PROGRAM, HAS_WATER_PROGRAM, HAS_HAZWASTE_PROGRAM, TOTAL_INSPECTION_COUNT, PCT_MINORITY, FACILITY_NAME e_name, CITY e_city, STATE e_st
      FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_ECHO QUALIFY ROW_NUMBER() OVER (PARTITION BY FRS_ID ORDER BY FORMAL_ACTION_COUNT DESC NULLS LAST) = 1)
SELECT f.*, e.* FROM f LEFT JOIN e ON e.FRS_ID = f.FACILITY_UIN;

-- S16 SEC insiders 2024: every (owner, issuer) pair on 2024 filings, with fund flags and the issuer's SIC from DERA 2024 filings
WITH s AS (SELECT ACCESSION_NUMBER, FILING_DATE, DOCUMENT_TYPE, TRY_TO_NUMBER(ISSUER_CIK) icik, ISSUER_NAME, ISSUER_TICKER
           FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_INSIDER_SUBMISSION WHERE FILING_DATE >= '2024-01-01' AND FILING_DATE < '2025-01-01'),
r AS (SELECT ACCESSION_NUMBER, OWNER_CIK, OWNER_NAME, RELATIONSHIP, TITLE, CITY, STATE FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_INSIDER_REPORTINGOWNER),
fund AS (SELECT TRY_TO_NUMBER(CIK) cik FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_CLOSED_END_FUND_INFORMATION
         UNION SELECT TRY_TO_NUMBER(CIK) FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_BUSINESS_DEVELOPMENT_COMPANY_REPORT
         UNION SELECT TRY_TO_NUMBER(CIK_NUMBER) FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_INVESTMENT_COMPANY_SERIES_CLASS),
sic AS (SELECT TRY_TO_NUMBER(CIK) cik, MODE(SIC) sic, MODE(AFS) afs FROM (
          SELECT CIK, SIC, AFS FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_DERA_SUB_2024Q1 UNION ALL SELECT CIK, SIC, AFS FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_DERA_SUB_2024Q2
          UNION ALL SELECT CIK, SIC, AFS FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_DERA_SUB_2024Q3 UNION ALL SELECT CIK, SIC, AFS FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_DERA_SUB_2024Q4) GROUP BY 1)
SELECT r.OWNER_CIK, ANY_VALUE(r.OWNER_NAME) owner_name, s.icik, ANY_VALUE(s.ISSUER_NAME) issuer_name, ANY_VALUE(s.ISSUER_TICKER) ticker,
       LISTAGG(DISTINCT r.RELATIONSHIP, '|') rels, ANY_VALUE(r.TITLE) title, ANY_VALUE(r.STATE) owner_st, COUNT(DISTINCT s.ACCESSION_NUMBER) filings,
       MIN(s.FILING_DATE) d0, MAX(s.FILING_DATE) d1, MAX(IFF(fund.cik IS NOT NULL, 1, 0)) is_fund, ANY_VALUE(sic.sic) sic, ANY_VALUE(sic.afs) afs,
       (SELECT MAX(FILING_DATE) FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_INSIDER_SUBMISSION) max_filing_all
FROM r JOIN s USING (ACCESSION_NUMBER) LEFT JOIN fund ON fund.cik = s.icik LEFT JOIN sic ON sic.cik = s.icik
GROUP BY r.OWNER_CIK, s.icik
