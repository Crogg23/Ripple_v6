-- S08 IRS SOI: what the short ZIP codes are; are state totals mixed in with ZIPs?
SELECT CASE WHEN ZIP_CODE IN ('0','00000') THEN 'zip_0_state_total' WHEN ZIP_CODE = '99999' THEN 'zip_99999_other'
            WHEN LENGTH(ZIP_CODE) = 5 THEN 'zip5' ELSE 'len' || LENGTH(ZIP_CODE) END kind,
       COUNT(*) n, COUNT(DISTINCT STATE) states, SUM(TRY_TO_DOUBLE(N_RETURNS)) ret, SUM(TRY_TO_DOUBLE(WAGES_SALARIES)) wages_k,
       MAX(TRY_TO_DOUBLE(WAGES_SALARIES)) max_wages_k, MIN(ZIP_CODE) z_min, MAX(ZIP_CODE) z_max,
       ARRAY_AGG(DISTINCT STATE) WITHIN GROUP (ORDER BY STATE) st
FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_IRS_SOI
GROUP BY 1 ORDER BY 1;

-- S09 IRS SOI: per-ZIP extract (real ZIPs only), low-income brackets 1-2 vs all, for local peer math
SELECT STATE, LPAD(ZIP_CODE, 5, '0') zip5,
       SUM(TRY_TO_DOUBLE(N_RETURNS)) ret_all, SUM(IFF(AGI_STUB IN ('1','2'), TRY_TO_DOUBLE(N_RETURNS), 0)) ret_low,
       SUM(IFF(AGI_STUB IN ('1','2'), TRY_TO_DOUBLE(RAC), 0)) rac_low, SUM(TRY_TO_DOUBLE(RAC)) rac_all, SUM(TRY_TO_DOUBLE(RAL)) ral_all,
       SUM(IFF(AGI_STUB IN ('1','2'), TRY_TO_DOUBLE(PREP), 0)) prep_low, SUM(IFF(AGI_STUB IN ('1','2'), TRY_TO_DOUBLE(TOTAL_VITA), 0)) vita_low,
       SUM(TRY_TO_DOUBLE(N_EITC)) n_eitc, SUM(TRY_TO_DOUBLE(EITC_AMOUNT)) eitc_k, SUM(TRY_TO_DOUBLE(AGI)) agi_k, SUM(TRY_TO_DOUBLE(WAGES_SALARIES)) wages_k,
       SUM(TRY_TO_DOUBLE(ELDERLY)) elderly
FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_IRS_SOI
WHERE ZIP_CODE NOT IN ('0', '00000', '99999')
GROUP BY 1, 2;

