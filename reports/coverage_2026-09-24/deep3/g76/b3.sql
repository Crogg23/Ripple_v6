       CURRENTLY_EFFECTIVE_MAP_DATE_RAW cem_raw, CURRENTLY_EFFECTIVE_MAP_DATE cem, REGULAR_EMERGENCY_PROGRAM_DATE reg, ORIGINAL_ENTRY_DATE crs_entry,
       TRIBAL_FLAG, PARTICIPATING_IN_NFIP_FLAG, CLASS_RATING_EFFECTIVE_DATE, CRS_CLASS_RATING, LAST_REFRESH_AT
