-- S20 Revoked, never reinstated, yet in today's IRS master file or Publication 78: split by ruling date vs revocation date and later filing
WITH r AS (
  SELECT EIN, MAX(TRY_TO_DATE(REVOCATION_DATE)) rd, BOOLOR_AGG(WAS_REINSTATED) rein, ANY_VALUE(EXEMPTION_TYPE) ex
  FROM LIBRARY_MARTS.ECONOMICS.ECONOMICS__FED_IRS_REVOCATION GROUP BY 1
), bmf AS (
  SELECT EIN, MAX(RULING_DATE) rul, MAX(DEDUCTIBILITY_CODE) ded, MAX(REVENUE_AMT) rev, MAX(TAX_PERIOD_MONTH) tp
  FROM LIBRARY_MARTS.CORPORATE_REGISTRY.CORPORATE_REGISTRY__FED_IRS_EO_BMF GROUP BY 1
), p78 AS (SELECT DISTINCT EIN FROM LIBRARY_MARTS.ECONOMICS.ECONOMICS__FED_IRS_PUB78_ELIGIBLE_DONEES)
SELECT r.rein, bmf.EIN IS NOT NULL in_bmf, bmf.ded, CASE WHEN bmf.rul IS NULL THEN 'no_ruling' WHEN bmf.rul > r.rd THEN 'ruling_after' ELSE 'ruling_before' END rul_vs,
       p78.EIN IS NOT NULL in_p78, IFF(bmf.tp > r.rd, 'filed_after', 'no') tp_after, COUNT(*) n, SUM(bmf.rev) rev_sum, MEDIAN(bmf.rev) rev_med, COUNT_IF(bmf.rev >= 1000000) rev_1m
FROM r LEFT JOIN bmf USING (EIN) LEFT JOIN p78 USING (EIN)
GROUP BY 1,2,3,4,5,6 ORDER BY n DESC;

