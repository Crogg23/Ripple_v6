  SELECT EIN, MAX(RULING_DATE) rul, MAX(DEDUCTIBILITY_CODE) ded, MAX(REVENUE_AMT) rev, MAX(TAX_PERIOD_MONTH) tp, MAX(ORG_NAME) bnm, MAX(STATE) bst, MAX(SUBSECTION_CODE) sub, MAX(GROUP_EXEMPTION_NUM) grp
  FROM LIBRARY_MARTS.CORPORATE_REGISTRY.CORPORATE_REGISTRY__FED_IRS_EO_BMF GROUP BY 1
), p78 AS (SELECT DISTINCT EIN FROM LIBRARY_MARTS.ECONOMICS.ECONOMICS__FED_IRS_PUB78_ELIGIBLE_DONEES),
x AS (
  SELECT r.*, bmf.rul, bmf.rev, bmf.tp, bmf.bnm, bmf.bst, bmf.sub, bmf.grp
  FROM r JOIN bmf USING (EIN) JOIN p78 USING (EIN)
  WHERE NOT r.rein AND bmf.rul <= r.rd AND bmf.tp > r.rd AND bmf.ded = '1'
)
SELECT * FROM (SELECT 'top' kind, EIN, nm, bnm, st, ex, sub, grp, rd, rul, tp, rev, NULL n FROM x ORDER BY rev DESC NULLS LAST LIMIT 25)
