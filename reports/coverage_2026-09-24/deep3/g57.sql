-- S10 QCEW traps: YOY columns, pay consistency, county total vs ownership sum, hidden rows that still count workplaces
WITH c70 AS (SELECT AREA_FIPS, ANNUAL_AVG_EMPLOYMENT emp FROM LIBRARY_MARTS.ECONOMICS.ECONOMICS__FED_BLS_QCEW WHERE AGGREGATION_LEVEL_CODE = '70'),
     c71 AS (SELECT AREA_FIPS, SUM(ANNUAL_AVG_EMPLOYMENT) emp, COUNT_IF(DISCLOSURE_CODE = 'N') hid FROM LIBRARY_MARTS.ECONOMICS.ECONOMICS__FED_BLS_QCEW WHERE AGGREGATION_LEVEL_CODE = '71' GROUP BY 1),
     q AS (SELECT * FROM LIBRARY_MARTS.ECONOMICS.ECONOMICS__FED_BLS_QCEW)
SELECT 'yoy' k, COUNT(*) n, COUNT_IF(YOY_EMPLOYMENT_PCT_CHANGE = 0) v1, COUNT_IF(YOY_EMPLOYMENT_PCT_CHANGE IS NULL) v2,
       COUNT_IF(YOY_EMPLOYMENT_PCT_CHANGE = 0 AND DISCLOSURE_CODE = 'N') v3, COUNT_IF(YOY_WAGES_PCT_CHANGE = 0) v4, NULL v5
FROM q
UNION ALL
SELECT 'hidden_rows', COUNT_IF(DISCLOSURE_CODE = 'N'), COUNT_IF(DISCLOSURE_CODE = 'N' AND ANNUAL_AVG_ESTABLISHMENTS > 0),
       COUNT_IF(DISCLOSURE_CODE = 'N' AND ANNUAL_AVG_EMPLOYMENT > 0), COUNT_IF(DISCLOSURE_CODE = 'N' AND TOTAL_ANNUAL_WAGES > 0),
       COUNT_IF(COALESCE(DISCLOSURE_CODE,'') NOT IN ('N','') ), COUNT_IF(DISCLOSURE_CODE IS NULL)
FROM q
UNION ALL
SELECT 'pay_check', COUNT_IF(ANNUAL_AVG_EMPLOYMENT > 0),
       COUNT_IF(ANNUAL_AVG_EMPLOYMENT > 0 AND ABS(AVG_ANNUAL_PAY - TOTAL_ANNUAL_WAGES / ANNUAL_AVG_EMPLOYMENT) > 2),
       COUNT_IF(ANNUAL_AVG_EMPLOYMENT > 0 AND AVG_ANNUAL_PAY > 1000000), MAX(AVG_ANNUAL_PAY), MAX(ANNUAL_AVG_WEEKLY_WAGE), COUNT_IF(ANNUAL_AVG_EMPLOYMENT > 0 AND AVG_ANNUAL_PAY < 5000)
FROM q
UNION ALL
SELECT 'county_total_vs_owner_sum', COUNT(*), COUNT_IF(c71.emp IS NULL), COUNT_IF(c70.emp = c71.emp), COUNT_IF(c70.emp > c71.emp AND c71.hid > 0),
       COUNT_IF(c70.emp <> c71.emp AND c71.hid = 0), SUM(c70.emp - c71.emp)
FROM c70 LEFT JOIN c71 USING (AREA_FIPS);

