-- S18 IRS revocation vs its near-twin ECONOMICS__FED_IRS_AUTO_REVOCATIONS: EIN overlap, date and reinstatement agreement
WITH a AS (
  SELECT EIN, COUNT(*) n, MAX(TRY_TO_DATE(REVOCATION_DATE)) rd1, MAX(TRY_TO_DATE(REINSTATEMENT_DATE)) ri
  FROM LIBRARY_MARTS.ECONOMICS.ECONOMICS__FED_IRS_REVOCATION GROUP BY 1
), b AS (
  SELECT EIN, COUNT(*) n, MAX(REVOCATION_DATE) rd1, MAX(REINSTATEMENT_DATE) ri
  FROM LIBRARY_MARTS.ECONOMICS.ECONOMICS__FED_IRS_AUTO_REVOCATIONS GROUP BY 1
)
SELECT COUNT(*) eins, COUNT_IF(a.EIN IS NULL) only_auto, COUNT_IF(b.EIN IS NULL) only_rev, COUNT_IF(a.EIN IS NOT NULL AND b.EIN IS NOT NULL) both_,
       COUNT_IF(a.rd1 = b.rd1) same_last_rev, COUNT_IF(a.ri IS NOT DISTINCT FROM b.ri AND a.EIN IS NOT NULL AND b.EIN IS NOT NULL) same_rein,
       COUNT_IF(a.ri IS NULL AND b.ri IS NOT NULL AND a.EIN IS NOT NULL) rein_only_auto, COUNT_IF(a.ri IS NOT NULL AND b.ri IS NULL AND b.EIN IS NOT NULL) rein_only_rev,
       MIN(IFF(a.EIN IS NULL, b.rd1, NULL)) only_auto_rd_min, MAX(IFF(a.EIN IS NULL, b.rd1, NULL)) only_auto_rd_max,
       COUNT_IF(a.EIN IS NULL AND b.rd1 > '2026-03-15') only_auto_after_mar15,
       MIN(IFF(b.EIN IS NULL, a.rd1, NULL)) only_rev_rd_min, MAX(IFF(b.EIN IS NULL, a.rd1, NULL)) only_rev_rd_max,
       COUNT_IF(a.n <> b.n) diff_rowcount, MAX(b.ri) auto_rein_max, MAX(a.ri) rev_rein_max
FROM a FULL OUTER JOIN b USING (EIN);

