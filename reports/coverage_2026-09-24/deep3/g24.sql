-- the peer, time and join math on them ran locally in pandas (scripts and outputs in g24/).

-- ===== batch b1 =====
-- S01 column names and types for the 5 tables plus the partner tables used for joins
SELECT table_schema, table_name, LISTAGG(column_name || ':' || LEFT(data_type,4), ', ') WITHIN GROUP (ORDER BY ordinal_position) cols
FROM LIBRARY_MARTS.INFORMATION_SCHEMA.COLUMNS
WHERE table_name IN ('FINANCE__FED_IRS_SOI','FINANCE__FED_NCUA_FEDERALLY_INSURED_CU_LIST','FINANCE__FED_FDIC_BANK_DATA',
  'FINANCE__FED_EPA_ICIS_FEC_CASE_ENFORCEMENT_CONCLUSION_FACILITIES','FINANCE__FED_SEC_INSIDER_REPORTINGOWNER',
  'FINANCE__FED_SEC_INSIDER_SUBMISSION','ENVIRONMENT__FED_EPA_ECHO','JUSTICE__FED_FDIC_ENFORCEMENT_ORDERS','ECONOMICS__FED_FDIC_FAILED_BANKS',
  'FINANCE__FED_NCUA_CALL_REPORTS_FOICU','FINANCE__FED_SEC_CLOSED_END_FUND_INFORMATION','FINANCE__FED_EPA_ICIS_FEC_CASE_FACILITIES',
  'FINANCE__FED_NCUA_CHARTER_MERGER_EVENTS','FINANCE__FED_SEC_INVESTMENT_COMPANY_SERIES_CLASS')
GROUP BY 1,2 ORDER BY 2
;

-- ===== batch b2 =====
-- S02 IRS SOI: rows by tax year and income bracket, state-total ZIPs (00000/99999), numeric parse failures, sums
SELECT TAX_YEAR, AGI_STUB, COUNT(*) n, COUNT(DISTINCT ZIP_CODE) zips, COUNT(DISTINCT STATE) states, COUNT(DISTINCT DATASET_NAME) dsn,
       COUNT_IF(ZIP_CODE = '00000') z00000, COUNT_IF(ZIP_CODE = '99999') z99999, COUNT_IF(LENGTH(ZIP_CODE) <> 5) zlen_bad,
       COUNT_IF(TRY_TO_DOUBLE(N_RETURNS) IS NULL) bad_n, SUM(TRY_TO_DOUBLE(N_RETURNS)) ret, SUM(TRY_TO_DOUBLE(WAGES_SALARIES)) wages_k,
       SUM(TRY_TO_DOUBLE(N_EITC)) n_eitc, SUM(TRY_TO_DOUBLE(EITC_AMOUNT)) eitc_k, SUM(TRY_TO_DOUBLE(PREP)) prep, SUM(TRY_TO_DOUBLE(RAL)) ral,
       SUM(TRY_TO_DOUBLE(RAC)) rac, SUM(TRY_TO_DOUBLE(TOTAL_VITA)) vita, SUM(TRY_TO_DOUBLE(ELDERLY)) elderly,
       COUNT(*) - COUNT(DISTINCT ZIP_CODE, STATE, AGI_STUB, TAX_YEAR) dup_keys
FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_IRS_SOI
GROUP BY ROLLUP(1,2) ORDER BY 1,2;

-- S03 NCUA list: capital, profit, lending and growth by charter type and low-income flag; sentinels
SELECT CREDIT_UNION_TYPE, LOW_INCOME_DESIGNATION, COUNT(*) n, COUNT(DISTINCT CHARTER_NUMBER) charters, COUNT(DISTINCT YEAR_AND_QUARTER) qtrs,
       SUM(TOTAL_ASSETS) assets, MEDIAN(TOTAL_ASSETS) med_assets, MEDIAN(MEMBERS) med_members,
       MEDIAN(NET_WORTH_RATIO_EXCLUDES_CECL_TRANSITION_PROVISION) med_nw, MIN(NET_WORTH_RATIO_EXCLUDES_CECL_TRANSITION_PROVISION) min_nw,
       MAX(NET_WORTH_RATIO_EXCLUDES_CECL_TRANSITION_PROVISION) max_nw,
       COUNT_IF(NET_WORTH_RATIO_EXCLUDES_CECL_TRANSITION_PROVISION < 7) nw_lt7, COUNT_IF(NET_WORTH_RATIO_EXCLUDES_CECL_TRANSITION_PROVISION < 6) nw_lt6,
       COUNT_IF(NET_WORTH_RATIO_EXCLUDES_CECL_TRANSITION_PROVISION < 4) nw_lt4, COUNT_IF(NET_WORTH_RATIO_EXCLUDES_CECL_TRANSITION_PROVISION IS NULL) nw_null,
       MEDIAN(RETURN_ON_AVERAGE_ASSETS) med_roa, COUNT_IF(RETURN_ON_AVERAGE_ASSETS < 0) roa_neg, COUNT_IF(LOAN_TO_SHARE_RATIO > 100) lts_gt100,
       COUNT_IF(MEMBERS_4_QUARTER_GROWTH < 0) mem_shrink, MEDIAN(MEMBERS_4_QUARTER_GROWTH) med_mem_g, MEDIAN(TOTAL_LOANS_4_QUARTER_GROWTH) med_loan_g,
       COUNT_IF(TOTAL_ASSETS IS NULL OR TOTAL_ASSETS = 0) assets0, COUNT_IF(MEMBERS IS NULL OR MEMBERS = 0) members0,
       COUNT_IF(TOTAL_LOANS > TOTAL_ASSETS) loans_gt_assets
FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_NCUA_FEDERALLY_INSURED_CU_LIST
GROUP BY ROLLUP(1,2) ORDER BY 1,2;

-- S04 FDIC bank data: open vs closed, report dates, fill, MDI, load runs; is this really a "sample"?
SELECT ACTIVE, COUNT(*) n, COUNT(DISTINCT CERT) certs, COUNT_IF(ASSET IS NULL) asset_null, SUM(ASSET) asset_k, MEDIAN(ASSET) med_asset_k,
       MIN(REPDTE) rep0, MAX(REPDTE) rep1, MODE(REPDTE) rep_mode, COUNT_IF(REPDTE = (SELECT MAX(REPDTE) FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_FDIC_BANK_DATA)) at_latest,
       MIN(ESTYMD) est0, MAX(ESTYMD) est1, MIN(ENDEFYMD) end0, MAX(ENDEFYMD) end1, COUNT_IF(ENDEFYMD IS NULL) end_null,
       COUNT_IF(NULLIF(TRIM(MDI_STATUS_CODE),'') IS NOT NULL AND MDI_STATUS_CODE NOT IN ('0','00')) mdi, COUNT(DISTINCT _SOURCE_RUN_ID) runs,
       MIN(DATEUPDT) upd0, MAX(DATEUPDT) upd1, COUNT_IF(IN_CONSERVATORSHIP = 'Y') conserv, COUNT_IF(INSURANCE_DROPPED_DATE IS NOT NULL) ins_dropped,
       COUNT(DISTINCT STALP) states, COUNT_IF(NETINC < 0) netinc_neg
FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_FDIC_BANK_DATA
GROUP BY ROLLUP(1) ORDER BY 1;

-- S05 FDIC join test: do failed banks and enforcement-order banks land in the bank directory by CERT?
WITH b AS (SELECT DISTINCT TRY_TO_NUMBER(CERT) cert, ACTIVE FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_FDIC_BANK_DATA),
f AS (SELECT TRY_TO_NUMBER(FDIC_CERT) cert, YEAR(FAIL_DATE) y FROM LIBRARY_MARTS.ECONOMICS.ECONOMICS__FED_FDIC_FAILED_BANKS WHERE RESOLUTION_TYPE = 'FAILURE'),
e AS (SELECT DISTINCT CERT_NUMBER cert FROM LIBRARY_MARTS.JUSTICE.JUSTICE__FED_FDIC_ENFORCEMENT_ORDERS WHERE CERT_NUMBER > 0)
SELECT 'failed_all' src, COUNT(*) n, COUNT_IF(cert IS NOT NULL AND cert > 0) with_cert, COUNT_IF(cert IN (SELECT cert FROM b)) landed FROM f
UNION ALL SELECT 'failed_2000_on', COUNT(*), COUNT_IF(cert > 0), COUNT_IF(cert IN (SELECT cert FROM b)) FROM f WHERE y >= 2000
UNION ALL SELECT 'orders_certs', COUNT(*), COUNT(*), COUNT_IF(cert IN (SELECT cert FROM b)) FROM e
UNION ALL SELECT 'orders_certs_active', COUNT(*), COUNT(*), COUNT_IF(cert IN (SELECT cert FROM b WHERE ACTIVE = '1')) FROM e;

-- S06 EPA conclusion-facility bridge: shape of IDs, case-number formats, duplicate rows, blanks
