-- S20 SEC insiders: people filing as Director at 5+ non-fund issuers, by filing year 2016-2024, plus yearly totals
WITH s AS (SELECT ACCESSION_NUMBER, YEAR(FILING_DATE) y, TRY_TO_NUMBER(ISSUER_CIK) icik, ISSUER_NAME
           FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_INSIDER_SUBMISSION WHERE FILING_DATE >= '2016-01-01' AND FILING_DATE < '2025-01-01'),
r AS (SELECT ACCESSION_NUMBER, OWNER_CIK, OWNER_NAME FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_INSIDER_REPORTINGOWNER WHERE RELATIONSHIP ILIKE '%Director%'),
fund AS (SELECT TRY_TO_NUMBER(CIK) cik FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_CLOSED_END_FUND_INFORMATION
         UNION SELECT TRY_TO_NUMBER(CIK) FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_BUSINESS_DEVELOPMENT_COMPANY_REPORT
         UNION SELECT TRY_TO_NUMBER(CIK_NUMBER) FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_INVESTMENT_COMPANY_SERIES_CLASS),
p AS (SELECT s.y, r.OWNER_CIK, ANY_VALUE(r.OWNER_NAME) nm, COUNT(DISTINCT s.icik) n_iss,
             COUNT(DISTINCT IFF(fund.cik IS NULL AND NOT REGEXP_LIKE(s.ISSUER_NAME, '.*(FUND|TRUST|MUNI|INCOME|PORTFOLIO|OPPORTUNIT).*', 'i'), s.icik, NULL)) n_op,
             LISTAGG(DISTINCT IFF(fund.cik IS NULL AND NOT REGEXP_LIKE(s.ISSUER_NAME, '.*(FUND|TRUST|MUNI|INCOME|PORTFOLIO|OPPORTUNIT).*', 'i'), LEFT(s.ISSUER_NAME, 30), NULL), ' | ') iss
      FROM r JOIN s USING (ACCESSION_NUMBER) LEFT JOIN fund ON fund.cik = s.icik GROUP BY 1, 2)
SELECT y, OWNER_CIK, nm, n_iss, n_op, iss FROM p WHERE n_op >= 5
UNION ALL
SELECT y, 'ALL', NULL, COUNT(*), COUNT_IF(n_op >= 5), TO_VARCHAR(COUNT_IF(n_op >= 10)) FROM p GROUP BY y;

-- S21 SEC insiders: filings whose remarks say "director by deputization", per year and owner, plus yearly issuer totals
WITH s AS (SELECT ACCESSION_NUMBER, YEAR(FILING_DATE) y, TRY_TO_NUMBER(ISSUER_CIK) icik
