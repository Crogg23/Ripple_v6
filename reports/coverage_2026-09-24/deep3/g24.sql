       COUNT_IF(FACILITY_UIN IS NULL OR FACILITY_UIN IN ('','None')) uin_blank, COUNT_IF(REGEXP_LIKE(FACILITY_UIN, '^110[0-9]{9}$')) uin_ok,
       COUNT_IF(REGEXP_LIKE(CASE_NUMBER, '^[0-9]{2}-[0-9]{4}-[0-9]+$')) case_rr_yyyy, COUNT_IF(REGEXP_LIKE(CASE_NUMBER, '^HQ-[0-9]{4}-[0-9]+$')) case_hq,
       COUNT(*) - COUNT(DISTINCT ACTIVITY_ID, ENF_CONCLUSION_ID, FACILITY_UIN, ICIS_FACILITY_INTEREST_ID) dup_rows,
       COUNT(DISTINCT CASE_NUMBER, ENF_CONCLUSION_ID) case_concl_pairs,
       ARRAY_AGG(DISTINCT REGEXP_REPLACE(CASE_NUMBER, '[0-9]', '9')) WITHIN GROUP (ORDER BY REGEXP_REPLACE(CASE_NUMBER, '[0-9]', '9')) formats
FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_EPA_ICIS_FEC_CASE_ENFORCEMENT_CONCLUSION_FACILITIES;

-- S07 SEC reporting owner: link to submission by accession, filing years, doc types, duplicate owner rows
WITH r AS (SELECT ACCESSION_NUMBER, OWNER_CIK, RELATIONSHIP FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_INSIDER_REPORTINGOWNER),
s AS (SELECT ACCESSION_NUMBER, FILING_DATE, DOCUMENT_TYPE FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_SEC_INSIDER_SUBMISSION)
SELECT YEAR(s.FILING_DATE) y, COUNT(*) n, COUNT(DISTINCT r.ACCESSION_NUMBER) filings, COUNT(DISTINCT r.OWNER_CIK) owners,
       COUNT(*) - COUNT(DISTINCT r.ACCESSION_NUMBER, r.OWNER_CIK) dup_owner_rows, COUNT_IF(s.ACCESSION_NUMBER IS NULL) no_sub,
       COUNT_IF(s.DOCUMENT_TYPE = '4') f4, COUNT_IF(s.DOCUMENT_TYPE = '3') f3, COUNT_IF(s.DOCUMENT_TYPE = '5') f5,
       COUNT_IF(s.DOCUMENT_TYPE LIKE '%/A') amend, COUNT_IF(r.RELATIONSHIP ILIKE '%director%') dir_rows
FROM r LEFT JOIN (SELECT * FROM s QUALIFY ROW_NUMBER() OVER (PARTITION BY ACCESSION_NUMBER ORDER BY FILING_DATE) = 1) s USING (ACCESSION_NUMBER)
GROUP BY 1 ORDER BY 1
;

-- ===== batch b3 =====
-- S08 IRS SOI: what the short ZIP codes are; are state totals mixed in with ZIPs?
SELECT CASE WHEN ZIP_CODE IN ('0','00000') THEN 'zip_0_state_total' WHEN ZIP_CODE = '99999' THEN 'zip_99999_other'
            WHEN LENGTH(ZIP_CODE) = 5 THEN 'zip5' ELSE 'len' || LENGTH(ZIP_CODE) END kind,
       COUNT(*) n, COUNT(DISTINCT STATE) states, SUM(TRY_TO_DOUBLE(N_RETURNS)) ret, SUM(TRY_TO_DOUBLE(WAGES_SALARIES)) wages_k,
       MAX(TRY_TO_DOUBLE(WAGES_SALARIES)) max_wages_k, MIN(ZIP_CODE) z_min, MAX(ZIP_CODE) z_max,
       ARRAY_AGG(DISTINCT STATE) WITHIN GROUP (ORDER BY STATE) st
FROM LIBRARY_MARTS.FINANCE.FINANCE__FED_IRS_SOI
GROUP BY 1 ORDER BY 1;

-- S09 IRS SOI: per-ZIP extract (real ZIPs only), low-income brackets 1-2 vs all, for local peer math
SELECT STATE, LPAD(ZIP_CODE, 5, '0') zip5,
       SUM(TRY_TO_DOUBLE(N_RETURNS)) ret_all, SUM(IFF(AGI_STUB IN ('1','2'), TRY_TO_DOUBLE(N_RETURNS), 0)) ret_low,
       SUM(IFF(AGI_STUB IN ('1','2'), TRY_TO_DOUBLE(RAC), 0)) rac_low, SUM(TRY_TO_DOUBLE(RAC)) rac_all, SUM(TRY_TO_DOUBLE(RAL)) ral_all,
       SUM(IFF(AGI_STUB IN ('1','2'), TRY_TO_DOUBLE(PREP), 0)) prep_low, SUM(IFF(AGI_STUB IN ('1','2'), TRY_TO_DOUBLE(TOTAL_VITA), 0)) vita_low,
       SUM(TRY_TO_DOUBLE(N_EITC)) n_eitc, SUM(TRY_TO_DOUBLE(EITC_AMOUNT)) eitc_k, SUM(TRY_TO_DOUBLE(AGI)) agi_k, SUM(TRY_TO_DOUBLE(WAGES_SALARIES)) wages_k,
