-- S03 crosswalk profile: match method x confidence x review flag, fill of every ID column, first-word sanity
SELECT MATCH_METHOD, MATCH_CONFIDENCE, REVIEW_FLAG, COUNT(*) n, COUNT(DISTINCT EPA_REGISTRY_ID) ids,
       COUNT_IF(NULLIF(TRIM(MATCHED_LEI),'') IS NOT NULL) lei_filled, COUNT(DISTINCT MATCHED_LEI) d_lei,
       COUNT_IF(NULLIF(TRIM(MATCHED_LEGAL_NAME),'') IS NOT NULL) name_filled,
       COUNT_IF(NULLIF(TRIM(ULTIMATE_PARENT_LEI),'') IS NOT NULL) ult_filled, COUNT(DISTINCT ULTIMATE_PARENT_LEI) d_ult,
       COUNT_IF(NULLIF(TRIM(PARENT_CIK),'') IS NOT NULL) cik_filled, COUNT(DISTINCT PARENT_CIK) d_cik,
       COUNT_IF(NULLIF(TRIM(PARENT_UEI),'') IS NOT NULL) uei_filled, COUNT(DISTINCT PARENT_UEI) d_uei,
       COUNT_IF(MATCHED_LEGAL_NAME = PARENT_LEGAL_NAME) same_parent_name,
       COUNT_IF(CONTAINS(UPPER(FACILITY_NAME), UPPER(SPLIT_PART(MATCHED_LEGAL_NAME,' ',1)))) first_word_in_fac,
       COUNT_IF(NULLIF(TRIM(FACILITY_NAME),'') IS NULL) blank_fac
FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__XC_EPA_CORPORATE_CROSSWALK
GROUP BY 1,2,3 ORDER BY n DESC;

-- S04 crosswalk: the 50 matched companies holding the most facilities, with sample facility names
SELECT MATCHED_LEGAL_NAME, PARENT_LEGAL_NAME, MAX(PARENT_CIK) cik, MAX(PARENT_UEI) uei, COUNT(*) facilities,
       LISTAGG(DISTINCT MATCH_METHOD, ',') methods,
       COUNT_IF(CONTAINS(UPPER(FACILITY_NAME), UPPER(SPLIT_PART(MATCHED_LEGAL_NAME,' ',1)))) first_word_hit,
       ARRAY_TO_STRING(ARRAY_SLICE(ARRAY_AGG(DISTINCT FACILITY_NAME), 0, 6), ' / ') sample_fac
FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__XC_EPA_CORPORATE_CROSSWALK
WHERE NULLIF(TRIM(MATCHED_LEGAL_NAME),'') IS NOT NULL
GROUP BY 1,2 ORDER BY facilities DESC LIMIT 50;

