-- S07 AQS: sites opened and closed per year
SELECT yr, SUM(opened) opened, SUM(closed) closed FROM (
  SELECT YEAR(SITE_ESTABLISHED_DATE) yr, 1 opened, 0 closed FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_AQS_SITES
  UNION ALL
  SELECT YEAR(SITE_CLOSED_DATE), 0, 1 FROM LIBRARY_MARTS.ENVIRONMENT.ENVIRONMENT__FED_EPA_AQS_SITES WHERE SITE_CLOSED_DATE IS NOT NULL
) GROUP BY yr ORDER BY yr;

