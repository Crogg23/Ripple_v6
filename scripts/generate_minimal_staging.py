#!/usr/bin/env python3
"""Generate minimal staging models for sources without GRAIN/NATURAL_KEY.

These are passthrough views: snake_case rename only, no QUALIFY dedup (because
the grain hasn't been determined). The header clearly marks them as needing
manual grain resolution. This gets them into the staging layer so they're
discoverable and queryable via THE_LIBRARY, even if they haven't been fully
modeled yet.

    python3 scripts/generate_minimal_staging.py              # write all
    python3 scripts/generate_minimal_staging.py --dry-run    # preview
    python3 scripts/generate_minimal_staging.py --limit 20   # first 20
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

_REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_REPO / "library-onboarding"))
sys.path.insert(0, str(_REPO / "connect"))
try:
    from dotenv import load_dotenv
    load_dotenv(_REPO / "library-onboarding/.env", override=True)
except Exception:
    pass

import snow  # noqa: E402

DBT_PROJECT = _REPO / "library-onboarding" / "ripple_dbt"
MODELS_DIR = DBT_PROJECT / "models" / "staging"

_AUDIT_COLUMN_NAMES = {"INGESTED_AT", "SOURCE_RUN_ID", "SRC_SHA256"}


def snake(name: str) -> str:
    return name.strip().lower()


def fetch_unstaged_sources(cur) -> list[dict]:
    cur.execute("""
        SELECT r.SOURCE_ID, COALESCE(r.NAME, r.SOURCE_ID) AS name, COALESCE(r.URL, '') AS url
        FROM LIBRARY_META.REGISTRY.SOURCE_REGISTRY r
        JOIN LIBRARY_RAW.INFORMATION_SCHEMA.TABLES t
          ON t.TABLE_SCHEMA = 'LANDING' AND t.TABLE_NAME = UPPER(r.SOURCE_ID)
        WHERE UPPER(r.SOURCE_ID) NOT LIKE 'PORTAL_%%'
          AND r.INCLUDE = 'Y'
          AND (r.GRAIN IS NULL OR r.NATURAL_KEY IS NULL)
        ORDER BY t.ROW_COUNT DESC
    """)
    return [{"source_id": r[0], "name": r[1], "url": r[2]} for r in cur.fetchall()]


def fetch_columns(cur, table_name: str) -> tuple[list[str], str | None]:
    cur.execute(
        "SELECT column_name FROM LIBRARY_RAW.INFORMATION_SCHEMA.COLUMNS "
        "WHERE table_schema='LANDING' AND table_name=%s ORDER BY ordinal_position",
        (table_name,),
    )
    rows = [r[0] for r in cur.fetchall()]
    real = [c for c in rows if not c.startswith("_") and c not in _AUDIT_COLUMN_NAMES]
    ingested_at = "_INGESTED_AT" if "_INGESTED_AT" in rows else (
        "INGESTED_AT" if "INGESTED_AT" in rows else None)
    return real, ingested_at


def render_model(src: dict, columns: list[str], ingested_at: str | None) -> str:
    sid = src["source_id"]
    landing_table = sid.upper()
    col_lines = ",\n".join(f"        {c} as {snake(c)}" for c in columns)

    if ingested_at == "_INGESTED_AT":
        loaded_at = "_INGESTED_AT as _loaded_at"
    elif ingested_at == "INGESTED_AT":
        loaded_at = "INGESTED_AT as _loaded_at"
    else:
        loaded_at = "CURRENT_TIMESTAMP() as _loaded_at"

    url_escaped = src["url"].replace("'", "''")

    return f"""{{{{ config(tags=['minimal_staging']) }}}}

-- GRAIN: NOT YET DETERMINED (profiler returned AMBIGUOUS -- needs manual review)
-- This is a passthrough staging view: snake_case rename only, no dedup.
-- Once grain is resolved, replace with a full staging model via generate_staging_models.py.
-- Generated by scripts/generate_minimal_staging.py

with source as (

    select * from {{{{ source('ripple_raw', '{landing_table}') }}}}

),

renamed as (

    select
{col_lines},
        {loaded_at},
        '{url_escaped}' as _source_url

    from source

)

select * from renamed
"""


def render_schema_yml(model_name: str, src: dict, landing_table: str) -> str:
    return f"""version: 2

sources:
  - name: ripple_raw
    database: LIBRARY_RAW
    schema: LANDING
    tables:
      - name: {landing_table}
        description: >
          Raw landing table for {src['name']}. Grain not yet determined.

models:
  - name: {model_name}
    description: "Minimal passthrough staging (grain undetermined). Needs manual review."
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=None)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    conn = snow.connect()
    try:
        cur = conn.cursor()
        sources = fetch_unstaged_sources(cur)
        if args.limit:
            sources = sources[:args.limit]
        print(f"{len(sources)} source(s) without GRAIN/NATURAL_KEY, needing minimal staging.")

        written, skipped = 0, 0
        for src in sources:
            sid = src["source_id"]
            out_dir = MODELS_DIR / sid.lower()

            if out_dir.exists() and any(out_dir.glob("*.sql")):
                skipped += 1
                continue

            columns, ingested_at = fetch_columns(cur, sid.upper())
            if not columns:
                skipped += 1
                continue

            model_name = f"stg_{sid.lower()}__records"
            sql = render_model(src, columns, ingested_at)
            yml = render_schema_yml(model_name, src, sid.upper())

            if args.dry_run:
                print(f"  would write: {out_dir / (model_name + '.sql')}")
            else:
                out_dir.mkdir(parents=True, exist_ok=True)
                (out_dir / f"{model_name}.sql").write_text(sql, encoding="utf-8")
                (out_dir / "schema.yml").write_text(yml, encoding="utf-8")
            written += 1

        cur.close()
        action = "would write" if args.dry_run else "wrote"
        print(f"\n{action}: {written} model(s), skipped: {skipped}")
        return 0
    finally:
        conn.close()


if __name__ == "__main__":
    raise SystemExit(main())
