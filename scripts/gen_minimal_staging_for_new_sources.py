"""Generate minimal passthrough staging models for the housing/health/energy
block sources landed in this session (EIA-860/861, FracFocus, FEMA IA).

Same shape as scripts/generate_minimal_staging.py's output but driven by an
explicit table list instead of SOURCE_REGISTRY (these sources weren't run
through the full onboarding registry flow -- acquisition only per the
ingestion master plan).
"""
from __future__ import annotations
import sys
from pathlib import Path

_REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_REPO / "library-onboarding"))
try:
    from dotenv import load_dotenv
    load_dotenv(_REPO / "library-onboarding/.env", override=True)
except Exception:
    pass

import snow  # noqa: E402

MODELS_DIR = _REPO / "library-onboarding" / "ripple_dbt" / "models" / "staging"

AUDIT_COLS = {"_INGESTED_AT", "_SOURCE_RUN_ID", "_SRC_SHA256", "_SRC_FILE"}

TABLES = [
    "FED_EIA860_1_UTILITY", "FED_EIA860_2_PLANT", "FED_EIA860_3_1_GENERATOR",
    "FED_EIA860_3_2_WIND", "FED_EIA860_3_3_SOLAR", "FED_EIA860_3_4_ENERGY_STORAGE",
    "FED_EIA860_3_5_MULTIFUEL", "FED_EIA860_4_OWNER", "FED_EIA860_6_1_ENVIROASSOC",
    "FED_EIA860_6_2_ENVIROEQUIP",
    "FED_EIA861_SERVICE_TERRITORY", "FED_EIA861_SHORT_FORM", "FED_EIA861_UTILITY_DATA",
    "FED_EIA861_ADVANCED_METERS", "FED_EIA861_BALANCING_AUTHORITY",
    "FED_EIA861_DELIVERY_COMPANIES", "FED_EIA861_DEMAND_RESPONSE",
    "FED_EIA861_DISTRIBUTION_SYSTEMS", "FED_EIA861_DYNAMIC_PRICING",
    "FED_EIA861_ENERGY_EFFICIENCY", "FED_EIA861_FRAME", "FED_EIA861_MERGERS",
    "FED_EIA861_NET_METERING", "FED_EIA861_NON_NET_METERING_DISTRIBUTED",
    "FED_EIA861_OPERATIONAL_DATA", "FED_EIA861_RELIABILITY",
    "FED_EIA861_SALES_ULT_CUST", "FED_EIA861_SALES_ULT_CUST_CS",
    "FED_FRACFOCUS_DISCLOSURE_LIST", "FED_FRACFOCUS_WATER_SOURCE",
    "FED_FRACFOCUS_REGISTRY",
    "FED_FEMA_IA_HOUSING_REGISTRATIONS",
]


def fetch_columns(cur, table_name: str) -> list[str]:
    cur.execute(
        "SELECT column_name FROM LIBRARY_RAW.INFORMATION_SCHEMA.COLUMNS "
        "WHERE table_schema='LANDING' AND table_name=%s ORDER BY ordinal_position",
        (table_name,),
    )
    return [r[0] for r in cur.fetchall()]


def write_model(source_id: str, table_name: str, columns: list[str]):
    dirpath = MODELS_DIR / source_id
    dirpath.mkdir(parents=True, exist_ok=True)
    model_name = f"stg_{source_id}__all"

    data_cols = [c for c in columns if c not in AUDIT_COLS]
    lines = []
    for c in data_cols:
        lines.append(f"        {c} as {c.lower()},")
    audit_present = [c for c in columns if c in AUDIT_COLS]
    for c in audit_present:
        alias = "_loaded_at" if c == "_INGESTED_AT" else c.lower()
        lines.append(f"        {c} as {alias},")
    body = "\n".join(lines).rstrip(",")

    sql = f"""{{{{ config(tags=['minimal_staging']) }}}}

-- GRAIN: NOT YET DETERMINED -- passthrough staging view (snake_case rename only, no dedup).
-- Generated by scripts/gen_minimal_staging_for_new_sources.py, 2026-08-05 ingestion sweep
-- (housing/health/energy block, part 2). Acquisition only -- no analysis/publish.

with source as (

    select * from {{{{ source('ripple_raw', '{table_name}') }}}}

),

renamed as (

    select
{body}

    from source

)

select * from renamed
"""
    (dirpath / f"{model_name}.sql").write_text(sql, encoding="utf-8")

    yml = f"""version: 2

sources:
  - name: ripple_raw
    database: LIBRARY_RAW
    schema: LANDING
    tables:
      - name: {table_name}
        description: >
          Raw landing table, ingestion sweep 2026-08-05. All columns arrive as TEXT.

models:
  - name: {model_name}
    description: >
      Minimal passthrough staging view for {table_name}. Grain not yet
      determined -- snake_case rename only, no dedup.
"""
    (dirpath / "schema.yml").write_text(yml, encoding="utf-8")
    print(f"  wrote {dirpath.relative_to(_REPO)}")


def main():
    conn = snow.connect()
    cur = conn.cursor()
    for table_name in TABLES:
        source_id = table_name.lower()
        cols = fetch_columns(cur, table_name)
        if not cols:
            print(f"  SKIP {table_name}: no columns found (table missing?)")
            continue
        write_model(source_id, table_name, cols)


if __name__ == "__main__":
    main()
