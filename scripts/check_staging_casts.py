#!/usr/bin/env python3
"""Count what each generated staging cast would throw away. Read-only.

Why this exists (2026-09-19): scripts/generate_staging_models.py decides a cast
from a 10,000-row sample. The casts are try_ casts, so a value the sample never
saw (a '1.5' in a column that looked like whole numbers, a 'UNKNOWN' in a date
column) reads NULL without a sound. A silent NULL is the same sin as a silently
hidden row. The only check that catches it is the dumb one: run the cast over
the WHOLE landing table and count the rows where the raw value was filled and
the cast came back empty.

What is checked, per generated model under models/staging: every
`{{ stg_int|stg_float|stg_date|stg_ts|stg_bool(...) }} as col` line, against
every row of the landing table the model reads. "Filled" means not NULL, not
'', not 'nan' -- the two values Chris ruled are never data.

What a hit means: lost > 0 -> that cast destroys real values. The column goes in
reports/staging_cast_overrides.tsv and the generator leaves it TEXT next run.
A lost value that is a null word ('N/A', 'None') is counted apart: it was never
a number, so NULL is the right answer and the cast stays.
What a miss means: lost = 0 -> on today's landing rows the cast loses nothing.
Blind spot: tomorrow's load. Run it again after a reload.

The SQL below MIRRORS macros/staging_casts.sql. Change one, change the other.

    python scripts/check_staging_casts.py
    python scripts/check_staging_casts.py --tables FED_IRS_BMF,XC_WAPO_FATAL_FORCE
    python scripts/check_staging_casts.py --write-overrides

Writes reports/staging_cast_check_<date>.tsv, one line per cast column.
"""
from __future__ import annotations

import argparse
import datetime as dt
import queue
import re
import sys
import threading
import time
from pathlib import Path

_REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_REPO))
from connect import db  # noqa: E402

STAGING = _REPO / "library-onboarding" / "ripple_dbt" / "models" / "staging"
OVERRIDES = _REPO / "reports" / "staging_cast_overrides.tsv"

NULL_WORDS = ("n/a", "na", "null", "none", "nil", "-", "--", "#n/a", "not available", "unknown", "unk")
_DATE_GUARD = "'.*[0-9A-Za-z][-/][0-9A-Za-z].*'"

CAST_LINE = re.compile(
    r"\{\{\s*(stg_int|stg_float|stg_date|stg_ts|stg_bool)\('(\"(?:[^\"]|\"\")+\")'(?:,\s*'([A-Z]+)')?\)\s*\}\}\s+as\s+(\w+)")


def cast_sql(macro: str, q: str, fmt: str | None) -> str:
    v = f"trim({q})"
    if macro == "stg_int":
        return f"iff(regexp_like({v}, '[+-]?[0-9]+([.]0+)?'), try_to_number({v}, 38, 0), null)"
    if macro == "stg_float":
        return f"try_to_double(iff(lower({v}) = 'nan', null, {v}))"
    if macro == "stg_date" and fmt:
        return f"iff(regexp_like({v}, '[0-9]{{8}}'), try_to_date({v}, '{fmt}'), null)"
    ymd = f"regexp_replace({v}, '^([0-9]{{4}})/([0-9]{{1,2}})/([0-9]{{1,2}})', '\\\\1-\\\\2-\\\\3')"
    if macro == "stg_date":
        return f"iff(regexp_like({v}, {_DATE_GUARD}), try_to_date({ymd}), null)"
    if macro == "stg_ts":
        offset = r"'.*[0-9]:[0-9]{2}([.][0-9]+)?\\s*([+-][0-9]{2}(:?[0-9]{2})?|Z)'"
        return (f"iff(regexp_like({v}, {_DATE_GUARD}), iff(regexp_like({v}, {offset}), "
                f"convert_timezone('UTC', try_to_timestamp_tz({ymd}))::timestamp_ntz, "
                f"try_to_timestamp_ntz({ymd})), null)")
    return f"try_to_boolean({v})"


def generated_casts() -> dict[str, list[tuple[str, str, str | None]]]:
    """{landing table: [(macro, quoted column, fmt)]} from the generated model files."""
    out: dict[str, list] = {}
    for f in STAGING.rglob("*.sql"):
        body = f.read_text(encoding="utf-8", errors="ignore")
        if "Generated by scripts/generate_staging_models.py" not in body:
            continue
        src = re.search(r"source\('ripple_raw', '([^']+)'\)", body)
        casts = [(m.group(1), m.group(2).replace("\\'", "'"), m.group(3)) for m in CAST_LINE.finditer(body)]
        if src and casts:
            # extend, not assign: two models on one landing table must both be checked
            out.setdefault(src.group(1), []).extend(casts)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--tables", help="comma-separated landing table names")
    ap.add_argument("--threads", type=int, default=4)
    ap.add_argument("--write-overrides", action="store_true",
                    help="add every column that loses real values to reports/staging_cast_overrides.tsv")
    args = ap.parse_args()

    todo = generated_casts()
    if args.tables:
        keep = {t.strip().upper() for t in args.tables.split(",")}
        todo = {t: c for t, c in todo.items() if t in keep}
    c0 = db.connect()
    size = {r[0]: int(r[1] or 0) for r in db.rows(
        c0, "select table_name, row_count from LIBRARY_RAW.INFORMATION_SCHEMA.TABLES where table_schema='LANDING'")}

    jobs: queue.Queue = queue.Queue()
    for t in sorted(todo, key=lambda t: -size.get(t, 0)):
        jobs.put(t)
    total = jobs.qsize()
    words = ", ".join("'" + w + "'" for w in NULL_WORDS)
    lock = threading.Lock()
    results: list[tuple] = []
    failed: list[tuple[str, str]] = []
    n_done = [0]
    started = time.time()

    def work() -> None:
        c = db.connect()
        while True:
            try:
                table = jobs.get_nowait()
            except queue.Empty:
                return
            casts = todo[table]
            parts = []
            for macro, q, fmt in casts:
                filled = f"({q} is not null and trim({q}) <> '' and lower(trim({q})) <> 'nan')"
                lost = f"({filled} and {cast_sql(macro, q, fmt)} is null)"
                word = f"lower(trim({q})) in ({words})"
                parts += [f"count_if({filled})", f"count_if({lost} and not {word})", f"count_if({lost} and {word})",
                          f"left(min(iff({lost} and not {word}, trim({q}), null)), 60)"]
            try:
                # Wide tables: 4 expressions per cast column, 150 columns a query.
                row: list = []
                for i in range(0, len(parts), 600):
                    row += list(db.rows(c, f'select {", ".join(parts[i:i + 600])} '
                                           f'from LIBRARY_RAW.LANDING."{table}"')[0])
                with lock:
                    for j, (macro, q, fmt) in enumerate(casts):
                        filled_n, lost_n, word_n, example = row[4 * j: 4 * j + 4]
                        results.append((table, q.strip('"'), macro + (f":{fmt}" if fmt else ""),
                                        size.get(table, 0), filled_n, lost_n, word_n, example))
            except Exception as e:
                with lock:
                    failed.append((table, " ".join(str(e).split())[:200]))
            with lock:
                n_done[0] += 1
                if n_done[0] % 50 == 0 or n_done[0] == total:
                    print(f"{n_done[0]} of {total}  {time.time() - started:,.0f}s", flush=True)

    threads = [threading.Thread(target=work) for _ in range(args.threads)]
    [t.start() for t in threads]
    [t.join() for t in threads]

    results.sort(key=lambda r: (-(r[5] or 0), r[0], r[1]))
    # A --tables run is a spot check: it must not overwrite the full report
    # (it did, once, on 2026-09-19 -- 6 tables replaced 661).
    out_path = _REPO / "reports" / (f"staging_cast_check_{dt.date.today().isoformat()}"
                                    f"{'_partial' if args.tables else ''}.tsv")
    with out_path.open("w", encoding="utf-8") as fh:
        fh.write("table\tcolumn\tcast\ttable_rows\tfilled\tlost_real_values\tlost_null_words\texample_lost\n")
        for r in results:
            fh.write("\t".join("" if x is None else re.sub(r"[\t\r\n]+", " ", str(x)) for x in r) + "\n")

    bad = [r for r in results if r[5]]
    print(f"\n{total} tables, {len(results):,} cast columns checked in {time.time() - started:,.0f}s")
    print(f"casts that lose nothing:          {len(results) - len(bad):,}")
    print(f"casts that lose real values:      {len(bad):,}  ({sum(r[5] for r in bad):,} values)")
    print(f"null words a cast turned to NULL: {sum(r[6] or 0 for r in results):,}  (the right answer)")
    for r in bad[:15]:
        print(f"  {r[0]}.{r[1]}  {r[2]}  lost {r[5]:,} of {r[4]:,}  e.g. {r[7]!r}")
    for t, e in failed:
        print(f"  FAILED {t}: {e}")
    print(f"wrote {out_path}")

    if args.write_overrides and bad:
        have = set()
        if OVERRIDES.exists():
            have = {tuple(ln.split("\t")[:2]) for ln in OVERRIDES.read_text(encoding="utf-8").splitlines()[1:]}
        with OVERRIDES.open("a" if have or OVERRIDES.exists() else "w", encoding="utf-8") as fh:
            if not OVERRIDES.exists() or OVERRIDES.stat().st_size == 0:
                fh.write("table\tcolumn\tkeep_as\twhy\n")
            for r in bad:
                if (r[0], r[1]) not in have:
                    fh.write(f"{r[0]}\t{r[1]}\tTEXT\t{dt.date.today().isoformat()} {r[2]} lost {r[5]} of {r[4]} "
                             f"filled values, e.g. {re.sub(chr(9), ' ', str(r[7]))}\n")
        print(f"overrides: {OVERRIDES}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
