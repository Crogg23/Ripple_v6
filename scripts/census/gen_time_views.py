"""Generate the canonical-clock view layer: one standard timestamp on every table.

WHAT THIS BUILDS
----------------
The 2026-08-20 datetime standard defined the rules and the parser; the time index
worked out what every date column in the warehouse MEANS. What was missing was
the rollout -- the 686 mart tables did not each expose one canonical timestamp,
so there was no single timeline to query across the whole warehouse.

This generates that layer as VIEWS rather than by editing the marts:

  models/timeline/<domain>/timeline__<model>.sql   one view per clocked table,
      exposing ripple_ts / ripple_grain / ripple_clock / ripple_source beside
      every original column, which pass through untouched (rule 8: the raw
      column is never overwritten)

  models/timeline/timeline__<domain>_index.sql     per-domain rollup, one row
      per (source, clock, grain, day) with a row count

  models/timeline/timeline__warehouse.sql          the union of those -- the
      single shared timeline: "what was happening anywhere in the warehouse in
      March 2020, and which sources should I open"

  seeds/ripple_time_registry.csv                   the control table. EVERY live
      table is listed, including the ones with no usable clock, so nothing goes
      missing quietly. This is what lets the platform run on plain SQL with no
      AI at runtime (CLAUDE.md section 7).

WHY VIEWS AND NOT COLUMNS IN THE MARTS
--------------------------------------
Adding three columns to 600+ mart models means rebuilding every mart: hours of
warehouse time, real money, and a rebuild risk on tables that are currently
correct. A view computes the same three columns at query time, costs nothing to
create or store, leaves the underlying tables untouched, and can be regenerated
in seconds when a clock label is corrected. The clock labels are young -- a
21-agent pass produced them this morning -- so cheap regeneration matters more
than saving the parse at query time.

Reads reports/time_index/clock_index.csv and columns.csv. Writes files only --
runs no SQL, touches no warehouse.
"""
import argparse
import csv
import os
import re
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _time_targets import (DATE_TYPES, load_clock_roles, load_measured,  # noqa: E402
                           pick_measurable, table_alias_map)

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DBT = os.path.join(REPO, "library-onboarding", "ripple_dbt")
OUTDIR = os.path.join(DBT, "models", "timeline")
SEED = os.path.join(DBT, "seeds", "ripple_time_registry.csv")

# Which clock roles get the "cannot be in the future" guard. A span START or END
# legitimately sits in the future -- a Section 8 contract expiring in 2045 is
# correct data. An event that has already happened, been reported, or been
# decided cannot be.
FUTURE_GUARDED = ("happened", "reported", "decided")
# Preference order when a table carries several clocks. What HAPPENED beats when
# we were TOLD, which beats when somebody DECIDED, which beats a span boundary.
CLOCK_RANK = ["happened", "reported", "decided", "span_start", "span_end"]

HEADER = """-- GENERATED by scripts/census/gen_time_views.py -- do not hand-edit.
-- Regenerate after any change to reports/time_index/clock_index.csv.
--
-- Canonical clock for {source}.
--   column : {column}   ({dtype})
--   means  : {clock} -- {why}
--   grain  : {grain}
{future_note}--
-- The original columns pass through untouched; the canonical four sit in front
-- of them. Rule 8 of the datetime standard: the raw column is never overwritten,
-- so a mis-parse is always recoverable.
"""

FUTURE_NOTE = (
    "--\n-- {clock} cannot be in the future -- if this row's value is, ripple_clock\n"
    "-- reads 'planned' instead, not '{clock}'. See ripple_row_clock in\n"
    "-- macros/ripple_time.sql.\n"
)


def ts_call(col, dtype, grain):
    """The raw canonical-timestamp macro call, unwrapped (no outer {{ }}).

    Never picks a parser by guesswork: the grain measured by the scan decides
    which builder is used, and a bare year never reaches a date parser (that is
    the bug the whole standard exists to prevent).

    Returned unwrapped so the SAME call can be nested twice in one view: once
    for ripple_ts, and again inside ripple_row_clock() for FUTURE_GUARDED clocks,
    which need to compare the parsed value against today to decide happened vs
    planned. Wrap the result in "{{ ... }}" yourself where it is used standalone.
    """
    # Jinja string literals are single-quoted so the SQL identifier can keep its
    # double quotes: ripple_ts_from_date('src."SURVEY_DATE"').
    ref = "'src.\"{}\"'".format(col)
    if dtype in DATE_TYPES:
        # Already a real date/timestamp in the mart, so only the window guard
        # and the NTZ cast are needed -- no parsing, nothing to misread.
        return "ripple_window('src.\"{}\"::timestamp_ntz')".format(col)
    elif grain == "year":
        return "ripple_ts_from_year({})".format(ref)
    elif grain == "month":
        return "ripple_ts_from_yyyymm({})".format(ref)
    elif grain == "quarter":
        return "ripple_ts_from_yearquarter({})".format(ref)
    else:
        return "ripple_ts_from_date({})".format(ref)


def build_targets():
    """One row per live table: the chosen clock, or an honest 'none'."""
    roles = load_clock_roles()
    meas = load_measured()
    alias = table_alias_map()
    targets, unclocked = [], []
    for model, byrole in sorted(roles.items()):
        full = alias.get(model)
        if not full:
            continue
        chosen = None
        for role in CLOCK_RANK:
            m = pick_measurable(byrole, role, model, meas)
            if m is None:
                continue
            usable = (int(m["trusted"] or 0) > 0
                      or (m["ymin"] or "").strip() not in ("", "None"))
            if usable:
                why = ""
                for r in byrole[role]:
                    if r["column"].upper() == m["col"].upper():
                        why = (r["why"] or "").replace("\n", " ").strip()
                        break
                chosen = (role, m, why)
                break
        rec = {"model": model.lower(), "source": full,
               "schema": full.split(".")[0], "table": full.split(".")[-1]}
        if chosen is None:
            # Say WHICH kind of nothing. A table whose only time column is our
            # own download stamp is a different problem from one with no time
            # data at all -- the first is fixable upstream, the second is not.
            kinds = set(byrole)
            if "ingest" in kinds:
                why = ("the only time column here is Ripple's own download "
                       "stamp, which is not a clock for anything in the world")
            elif kinds & {"not_a_date", "unclear"}:
                why = ("time-shaped column names exist but none of them hold a "
                       "readable time value")
            else:
                why = "no column in this table holds a readable time value"
            rec.update({"clock": "none", "column": "", "grain": "none",
                        "dtype": "", "why": why, "n_rows": 0})
            unclocked.append(rec)
        else:
            role, m, why = chosen
            rec.update({"clock": role, "column": m["col"], "grain": m["grain"],
                        "dtype": m["dtype"], "why": why or "-",
                        "n_rows": int(m["n_rows"] or 0)})
            targets.append(rec)

    # The clock index only ever looked at tables with a time-SHAPED column name.
    # Every other live table has to be in the registry too, saying so plainly --
    # a table missing from the registry is indistinguishable from a table that
    # was checked and found to have no clock, and that ambiguity is exactly what
    # the registry exists to remove.
    seen = {r["source"] for r in targets + unclocked}
    live_path = os.path.join(REPO, "reports", "time_index", "live_tables.csv")
    if os.path.exists(live_path):
        with open(live_path, encoding="utf-8") as fh:
            for row in csv.DictReader(fh):
                src = "{}.{}".format(row["schema_name"], row["table_name"])
                if src in seen:
                    continue
                unclocked.append({
                    "model": row["table_name"].lower(), "source": src,
                    "schema": row["schema_name"], "table": row["table_name"],
                    "clock": "none", "column": "", "grain": "none", "dtype": "",
                    "n_rows": int(row.get("row_count") or 0),
                    "why": "never examined -- no column name in this table looks "
                           "like a clock, so the 2026-08-20 time index never "
                           "opened it",
                })
    return targets, unclocked


def write_view(rec):
    domain = rec["schema"].lower()
    d = os.path.join(OUTDIR, domain)
    os.makedirs(d, exist_ok=True)
    path = os.path.join(d, "timeline__{}.sql".format(rec["model"]))
    call = ts_call(rec["column"], rec["dtype"], rec["grain"])
    future_guarded = rec["clock"] in FUTURE_GUARDED
    if future_guarded:
        clock_line = "{{{{ ripple_row_clock({}, '{}') }}}}".format(call, rec["clock"])
    else:
        clock_line = "{{{{ ripple_clock('{}') }}}}".format(rec["clock"])
    body = (
        "{{{{ config(materialized='view', schema='TIMELINE', "
        "alias='{alias}') }}}}\n\n".format(alias=rec["table"])
        + HEADER.format(source=rec["source"], column=rec["column"],
                        dtype=rec["dtype"] or "text", clock=rec["clock"],
                        why=rec["why"][:160], grain=rec["grain"],
                        future_note=(FUTURE_NOTE.format(clock=rec["clock"])
                                     if future_guarded else ""))
        + "\nselect\n"
        + "    {{{{ {} }}}} as ripple_ts,\n".format(call)
        + "    {{{{ ripple_grain('{}') }}}} as ripple_grain,\n".format(rec["grain"])
        + "    {} as ripple_clock,\n".format(clock_line)
        + "    '{}'::varchar as ripple_source,\n".format(rec["source"])
        + "    src.*\n"
        + "from {{{{ ref('{}') }}}} as src\n".format(rec["model"])
    )
    open(path, "w", encoding="utf-8").write(body)
    return path


def write_domain_index(domain, recs):
    """One row per (source, clock, grain, day) with a count, for one domain."""
    parts = []
    for r in recs:
        parts.append(
            "select ripple_source, ripple_clock, ripple_grain,\n"
            "       date_trunc('day', ripple_ts)::date as ripple_day,\n"
            "       count(*) as n_rows\n"
            "from {{{{ ref('timeline__{}') }}}}\n"
            "where ripple_ts is not null\n"
            "group by 1, 2, 3, 4".format(r["model"]))
    # NB: .format() runs over this whole literal, so every real Jinja brace here
    # has to be doubled twice.
    body = (
        "{{{{ config(materialized='table', schema='TIMELINE') }}}}\n\n"
        "-- GENERATED by scripts/census/gen_time_views.py -- do not hand-edit.\n"
        "--\n"
        "-- The {n} clocked tables in the {d} domain, rolled up to one row per\n"
        "-- (source, clock kind, grain, day). Counting only -- no row detail, so\n"
        "-- this stays small enough to scan across the whole warehouse at once.\n"
        "-- Drill into the matching view in LIBRARY_MARTS.TIMELINE for the rows.\n"
        "--\n"
        "-- NOTE ON GRAIN: a year-grain source snaps to Jan 1 and a month-grain\n"
        "-- source to the 1st, per rule 2. ripple_grain is what stops that from\n"
        "-- reading as a real New Year's Day spike -- always filter or facet on\n"
        "-- it before drawing a daily chart.\n\n".format(n=len(recs), d=domain)
        + "\nunion all\n\n".join(parts) + "\n")
    path = os.path.join(OUTDIR, "timeline__{}_index.sql".format(domain))
    open(path, "w", encoding="utf-8").write(body)
    return path


def write_warehouse(domains):
    parts = ["select * from {{{{ ref('timeline__{}_index') }}}}".format(d)
             for d in domains]
    body = (
        "{{ config(materialized='table', schema='TIMELINE') }}\n\n"
        "-- GENERATED by scripts/census/gen_time_views.py -- do not hand-edit.\n"
        "--\n"
        "-- THE SHARED TIMELINE. Every clocked table in the warehouse on one\n"
        "-- axis, at one row per (source, clock kind, grain, day).\n"
        "--\n"
        "-- What it answers that nothing else could:\n"
        "--   * what was happening ANYWHERE in the warehouse in a given month\n"
        "--   * which sources go quiet, and exactly when\n"
        "--   * which sources cover a date at all, before a question is asked\n"
        "--   * how many independent sources touch the same day\n"
        "--\n"
        "-- What it is NOT: row detail. It counts. Open the matching view in\n"
        "-- LIBRARY_MARTS.TIMELINE for the rows behind a count.\n"
        "--\n"
        "-- ALWAYS respect ripple_grain. A year-grain source contributes a single\n"
        "-- stack on Jan 1; treating that as a daily event invents a spike.\n"
        "-- ALWAYS respect ripple_clock. Summing a 'happened' source and a\n"
        "-- 'reported' source into one line mixes two different questions.\n\n"
        + "\nunion all\n".join(parts) + "\n")
    path = os.path.join(OUTDIR, "timeline__warehouse.sql")
    open(path, "w", encoding="utf-8").write(body)
    return path


def write_registry(targets, unclocked):
    cols = ["source", "schema_name", "table_name", "model", "clock", "clock_column",
            "grain", "dtype", "has_view", "n_rows", "why"]
    os.makedirs(os.path.dirname(SEED), exist_ok=True)
    with open(SEED, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        for rec in sorted(targets + unclocked, key=lambda r: r["source"]):
            w.writerow({
                "source": rec["source"], "schema_name": rec["schema"],
                "table_name": rec["table"], "model": rec["model"],
                "clock": rec["clock"], "clock_column": rec["column"],
                "grain": rec["grain"], "dtype": rec["dtype"],
                "has_view": "true" if rec["clock"] != "none" else "false",
                "n_rows": rec["n_rows"],
                "why": re.sub(r"\s+", " ", rec["why"])[:300],
            })
    return SEED


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, help="generate only N views (smoke test)")
    ap.add_argument("--clean", action="store_true",
                    help="delete models/timeline first")
    args = ap.parse_args()

    if args.clean and os.path.isdir(OUTDIR):
        shutil.rmtree(OUTDIR)
    os.makedirs(OUTDIR, exist_ok=True)

    targets, unclocked = build_targets()
    if args.limit:
        targets = sorted(targets, key=lambda r: r["n_rows"])[:args.limit]

    by_domain = {}
    for rec in targets:
        write_view(rec)
        by_domain.setdefault(rec["schema"].lower(), []).append(rec)
    for domain, recs in sorted(by_domain.items()):
        write_domain_index(domain, recs)
    write_warehouse(sorted(by_domain))
    write_registry(targets, unclocked)

    print("GENERATED")
    print("  canonical views      : {}".format(len(targets)))
    print("  domains              : {}".format(len(by_domain)))
    print("  live tables with NO usable clock (registered, no view): {}"
          .format(len(unclocked)))
    print("  registry rows        : {}".format(len(targets) + len(unclocked)))
    grains = {}
    for r in targets:
        grains[r["grain"]] = grains.get(r["grain"], 0) + 1
    print("  grain mix            : {}".format(
        ", ".join("{} {}".format(v, k) for k, v in
                  sorted(grains.items(), key=lambda kv: -kv[1]))))
    clocks = {}
    for r in targets:
        clocks[r["clock"]] = clocks.get(r["clock"], 0) + 1
    print("  clock mix            : {}".format(
        ", ".join("{} {}".format(v, k) for k, v in
                  sorted(clocks.items(), key=lambda kv: -kv[1]))))


if __name__ == "__main__":
    main()
