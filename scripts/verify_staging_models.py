#!/usr/bin/env python3
"""Step 4 -- verify generated staging models, per-model, as they're built (not
at the end). Two automated checks; the third (spot-check against known public
figures) is a manual/agent-assisted sample, not automatable here.

  1. dbt run + dbt test for the model (unique/not_null on natural_key, from the
     schema.yml scripts/generate_staging_models.py wrote alongside it).
  2. Re-run COUNT(*) vs COUNT(DISTINCT natural_key) against the MATERIALIZED
     staging view (not the landing table -- profile_spine_backfill.py already
     proved this on landing; this re-proves it survived the rename + QUALIFY
     dedupe) and flags any NULL natural_key values (a real data-quality signal
     QUALIFY's NULL-partitioning would otherwise hide silently).

When grain is wrong, per Chris's instruction: fix the registry entry (GRAIN/
NATURAL_KEY/SPINE_ENTITY on SOURCE_REGISTRY -- via a --apply run, never a
direct UPDATE) and regenerate the model, not the generated SQL by hand.

    python3 scripts/verify_staging_models.py --source-id fed_cms_dialysis
    python3 scripts/verify_staging_models.py --all-generated     # every model this generator wrote
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

_REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_REPO / "library-onboarding"))
try:
    from dotenv import load_dotenv
    load_dotenv(_REPO / "library-onboarding/.env", override=True)
except Exception:  # pragma: no cover
    pass

# profiles.yml lives inside the dbt project itself, not ~/.dbt -- dbt won't find
# it (Env var required / profile not found) unless this is set before the
# subprocess call.
os.environ.setdefault("DBT_PROFILES_DIR", str(_REPO / "library-onboarding" / "ripple_dbt"))

import snow  # noqa: E402

DBT_DIR = _REPO / "library-onboarding" / "ripple_dbt"
MODELS_DIR = DBT_DIR / "models" / "staging"


def discover_models() -> list[str]:
    """Every model file this generator wrote (marked by its header comment)."""
    names = []
    for sql_path in MODELS_DIR.glob("*/*.sql"):
        text = sql_path.read_text(encoding="utf-8", errors="ignore")
        if "Generated by scripts/generate_staging_models.py" in text:
            names.append(sql_path.stem)
    return sorted(names)


def dbt_run_test(model_name: str) -> tuple[bool, str]:
    for cmd in (["dbt", "run", "--select", model_name], ["dbt", "test", "--select", model_name]):
        proc = subprocess.run(cmd, cwd=DBT_DIR, capture_output=True, text=True)
        if proc.returncode != 0:
            return False, f"{' '.join(cmd)} FAILED:\n{proc.stdout[-2000:]}\n{proc.stderr[-1000:]}"
    return True, "dbt run + dbt test passed"


def grain_check(cur, model_name: str, schema: str, nk_cols: list[str]) -> dict:
    concat_expr = " || '|' || ".join(f"COALESCE(TO_VARCHAR({c}), '\\x01NULL')" for c in nk_cols)
    null_expr = " OR ".join(f"{c} IS NULL" for c in nk_cols)
    sql = (
        f"SELECT COUNT(*) AS n, COUNT(DISTINCT {concat_expr}) AS d, "
        f"COUNT_IF({null_expr}) AS null_nk FROM {schema}.{model_name}"
    )
    cur.execute(sql)
    n, d, null_nk = cur.fetchone()
    return {"n": n, "distinct": d, "null_nk": null_nk, "grain_ok": (n == d and null_nk == 0)}


def main() -> int:
    ap = argparse.ArgumentParser(description="Verify generated staging models (dbt test + grain re-check).")
    ap.add_argument("--source-id", action="append", default=[], help="repeatable; specific source(s)")
    ap.add_argument("--all-generated", action="store_true", help="every model this generator wrote")
    ap.add_argument("--schema", default=None, help="staging schema (default: your dbt target schema)")
    args = ap.parse_args()

    all_models = discover_models()
    if args.all_generated:
        targets = all_models
    elif args.source_id:
        targets = [m for m in all_models if any(m.startswith(f"stg_{s}__") for s in args.source_id)]
    else:
        print("Pass --source-id <id> (repeatable) or --all-generated.")
        return 1

    if not targets:
        print("No matching generated models found under models/staging/.")
        return 1

    schema = args.schema
    if not schema:
        # ripple_dbt/dbt_project.yml pins staging to LIBRARY_STAGING; the schema
        # under it is whatever the active dbt target resolves (default: DBT_CROGERS).
        schema = "LIBRARY_STAGING.DBT_CROGERS"
        print(f"(no --schema given, assuming {schema} -- override if your dbt target differs)")

    conn = snow.connect()
    try:
        cur = conn.cursor()
        results = []
        for model_name in targets:
            print(f"\n{'=' * 78}\n{model_name}\n{'=' * 78}")
            ok, msg = dbt_run_test(model_name)
            print(msg if ok else f"FAIL: {msg}")
            if not ok:
                results.append((model_name, False, "dbt run/test failed"))
                continue

            sql_path = next(MODELS_DIR.glob(f"*/{model_name}.sql"))
            text = sql_path.read_text(encoding="utf-8")
            partition_line = next(l for l in text.splitlines() if "partition by" in l)
            nk_cols = [c.strip() for c in
                       partition_line.split("partition by", 1)[1].split("order by", 1)[0].split(",")]

            gc = grain_check(cur, model_name, schema, nk_cols)
            print(f"  n={gc['n']}  distinct({','.join(nk_cols)})={gc['distinct']}  "
                  f"null_natural_key_rows={gc['null_nk']}  -> "
                  f"{'GRAIN OK' if gc['grain_ok'] else 'GRAIN MISMATCH -- fix the registry, not the SQL'}")
            results.append((model_name, gc["grain_ok"], gc))
        cur.close()

        passed = sum(1 for _, ok, _ in results if ok)
        print(f"\n{passed}/{len(results)} models verified clean.")
        print("Remaining manual step: spot-check a sample of rows against known public "
              "figures/records where they exist (not automatable here).")
        return 0 if passed == len(results) else 1
    finally:
        conn.close()


if __name__ == "__main__":
    raise SystemExit(main())
