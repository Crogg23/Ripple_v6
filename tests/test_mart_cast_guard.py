"""Guard against the cast bug that silently emptied 133 mart columns.

On 2026-08-10 a live scan found 133 columns across 82 marts that were 100% NULL
because the model generator wrapped a text column in try_to_number /
try_to_double / try_to_date. TRY_TO_* does not raise on bad input -- it returns
NULL -- so every one of those models built green while the column was gone, and
the catalog kept advertising the source as fully modeled.

Two guards, both offline (no warehouse):

  1. infer_cast() itself must not hand a numeric cast to a textual name.
  2. No mart .sql on disk may wrap one of those names in a try_to_* call.

Guard 2 is what catches a regression: a hand-edited model, or a model generated
by an older copy of the script, would otherwise slip straight back in.
"""
import glob
import os
import re
import sys

import pytest

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "scripts"))

from gen_mart_models import cast_is_suspicious, infer_cast  # noqa: E402

MARTS = os.path.join(REPO, "library-onboarding", "ripple_dbt", "models", "marts")

# Real column names taken from the 2026-08-10 evidence file: every one of these was
# verified 100% NULL in the built mart before the fix.
KNOWN_VICTIMS = [
    "COUNTRY", "COUNTY", "COUNTRYBA", "COUNTRYINC", "COUNTRYMA",
    "COUNTY_PARISH", "COUNTY_NAME", "COUNTRY_NAME", "COUNTY_CODE",
    "COUNTY_FIPS", "COUNTY_SERVED", "COUNTRY_SUBDIVISION_PRIMARY",
    "REGISTRANT_COUNTRY", "CLIENT_COUNTRY", "FOREIGN_PRINCIPAL_COUNTRY",
    "COUNTRY_OF_BIRTH", "COUNTRY_OF_CITIZENSHIP", "COUNTRY_TERRITORY",
    "COUNTERPART_AREA_NAME", "INCORPORATION_STATE", "STATEOFINCORPORATION",
    "US_REGISTRATION_STATE", "FILTRATION_STATUS_CODE", "ACCOUNT_TYPE",
    "ENCOUNTER_TYPE", "SSHPRNAMTTYPE", "UPDATE_FREQUENCY",
    "REGISTRATION_REGISTRATIONSTATUS", "PLANT_COUNTY_NAME",
    "U_S_MEXICO_BORDER_COUNTY_INDICATOR", "ACTOR1COUNTRYCODE",
    "FOOTNOTE_FOR_DTC_RISK_STANDARDIZED_RATE",
]

# Names that must KEEP their cast -- the fix must not overshoot into real measures.
MUST_STILL_CAST = {
    "INCORPORATION_DATE": "try_to_date",
    "SENIOR_STATUS_DATE": "try_to_date",
    "ACTION_DATE": "try_to_date",
    "TRANSACTION_AMT": "try_to_double",
    "FEDERAL_ACTION_OBLIGATION": "try_to_double",
    "STATE_LOCAL_PENALTY_AMT": "try_to_double",
    "NUMBER_OF_ACTIONS": "try_to_number",
    "LATITUDE": "try_to_double",
    "LONGITUDE": "try_to_double",
}

_CAST_CALL = re.compile(
    r"\btry_to_(?:number|double|date|timestamp)\(\s*\"?([A-Za-z0-9_]+)\"?\s*[,)]")


@pytest.mark.parametrize("col", KNOWN_VICTIMS)
def test_infer_cast_leaves_text_columns_alone(col):
    assert infer_cast(col, "TEXT") is None, (
        "%s is a text column; casting it to a number silently nulls every row" % col)


@pytest.mark.parametrize("col,expected", sorted(MUST_STILL_CAST.items()))
def test_infer_cast_still_casts_real_measures(col, expected):
    assert infer_cast(col, expected and "TEXT") == expected


def test_infer_cast_never_touches_a_typed_column():
    # Casting an already-typed column raises at build time rather than nulling.
    assert infer_cast("TOTAL_AMOUNT", "NUMBER") is None
    assert infer_cast("CREATED_DATE", "DATE") is None


def test_no_mart_model_casts_a_text_column():
    """Every try_to_* call on disk must survive infer_cast's own judgement."""
    offenders = []
    for path in glob.glob(os.path.join(MARTS, "*", "*.sql")):
        text = open(path, encoding="utf-8", errors="ignore").read()
        for col in _CAST_CALL.findall(text):
            if cast_is_suspicious(col):
                offenders.append("%s: %s" % (
                    os.path.relpath(path, MARTS).replace("\\", "/"), col))
    assert not offenders, (
        "%d mart column(s) are wrapped in a cast that would null them:\n  %s"
        % (len(offenders), "\n  ".join(sorted(offenders)[:40])))


def test_no_mart_model_ships_positional_column_names():
    """c1/c2/c3 aliases mean a headerless load was passed straight through.

    Allowed only where the SOURCE genuinely uses those names -- Freedom House's
    indicator codes C1/C2/C3 are real, so the check looks at the alias, and a model
    that maps C1 to a real name is fine.
    """
    offenders = []
    for path in glob.glob(os.path.join(MARTS, "*", "*.sql")):
        text = open(path, encoding="utf-8", errors="ignore").read()
        if "-- Generated by" not in text:
            continue          # hand-written models pick their own names
        aliases = re.findall(r"\bas\s+(c\d+)\s*[,\n]", text)
        total = len(re.findall(r"\bas\s+[a-z_0-9]+\s*[,\n]", text))
        # Freedom House really does publish indicators named C1/C2/C3, so a few
        # positional-looking aliases among real ones are fine. A headerless load is
        # the case where nearly EVERY column is cN.
        if total and len(aliases) >= 3 and len(aliases) / total > 0.8:
            offenders.append("%s (%d of %d aliases positional)" % (
                os.path.relpath(path, MARTS).replace("\\", "/"),
                len(aliases), total))
    assert not offenders, (
        "mart(s) expose positional column names instead of real ones:\n  %s"
        % "\n  ".join(sorted(offenders)))
